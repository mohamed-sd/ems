<?php
/**
 * tests/guard_adoption_ratchet_test.php — شاهدُ INJ-0239
 * ═══════════════════════════════════════════════════════════════════════════
 * ⇐ شواهدُ أحكامٍ: INJ-0239
 *
 * **العطبُ المقيس**: `tools/guard_adoption_gate.php` كان يسرد **تسعًا وأربعين
 * دالةَ حراسةٍ ميتةً** ثم يختم بـ«✔ صفرُ حارسٍ بصفرِ مستهلك — كلُّ حارسٍ مبنيٍّ
 * مُتبنًّى في الإنتاج (L3)» **ويخرج بصفر**. فالجسمُ صادقٌ والختمُ يُضلِّل: العدُّ
 * على مستوى **الصنفِ** (30/30 متبنًّى) والموتُ على مستوى **الدالة**.
 * وMD-05: «البناءُ ليس تبنّيًا» — ودالةُ حراسةٍ بصفرِ مستهلكٍ **لا تحرس أحدًا**،
 * فمنها `BreakGlassService::grant` و`SensitiveFieldGuard::filterRow`.
 *
 * ── ولماذا سقّاطةٌ لا حجبٌ فوريّ ─────────────────────────────────────────────
 * حجبُ تسعٍ وأربعين فجأةً يُوقف خطَّ التسليمِ بلا خطةِ تبنٍّ، فيُلتَفُّ عليه
 * **بتعطيلِ البوابةِ** — وهو أسوأُ من العطب. فالخطُّ القائمُ يُثبَّت في ملفٍّ
 * مُعلَنٍ، وتُحجَب البوابةُ **إن نما العددُ أو ظهر اسمٌ جديد**. فالنزيفُ يتوقّف
 * اليومَ والتبنّي يمضي بخطة.
 *
 * ── وهذا الفاحصُ يُثبت الثلاثةَ ────────────────────────────────────────────────
 *   ① الختمُ يقول الحقيقتين معًا (الصنفَ والدالةَ) لا واحدةً تُخفي الأخرى.
 *   ② والخطُّ مُولَّدٌ من مصدرِه (`--list-dead`) لا مكتوبٌ بيدٍ.
 *   ③ **وتُحجَب البوابةُ فعلًا** عند دالةِ حراسةٍ ميتةٍ جديدة — بزرعِ صنفِ
 *      حراسةٍ حقيقيٍّ بدالةٍ لا يناديها أحدٌ، ثم رفعِه.
 * ═══════════════════════════════════════════════════════════════════════════
 */
if (php_sapi_name() !== 'cli') { exit("CLI فقط\n"); }
error_reporting(E_ALL & ~E_DEPRECATED);
mb_internal_encoding('UTF-8');
$ROOT = dirname(__DIR__);

$PASS = 0; $FAIL = 0;
$ok = function ($cond, $label, $extra = '') use (&$PASS, &$FAIL) {
    if ($cond) { $PASS++; fwrite(STDOUT, "  ✔ {$label}\n"); }
    else { $FAIL++; fwrite(STDOUT, "  ✘ {$label}" . ($extra !== '' ? "  ⟵ {$extra}" : '') . "\n"); }
};
$say = function ($s) { fwrite(STDOUT, $s . "\n"); };

$GATE = $ROOT . '/tools/guard_adoption_gate.php';
$BASE = $ROOT . '/docs/fix_2026-08/guard_dead_methods_baseline.txt';
/* ═══════════════════════════════════════════════════════════════════════════
 * ◆ **الزرعُ دالةٌ ميتةٌ في صنفٍ حيٍّ — لا صنفٌ ميت.**
 * أوّلُ صياغةٍ زرعت **صنفًا** جديدًا بلا مستهلك، فحجبته البوابةُ — لكن بمسارِ
 * «صنفٌ بصفرِ مستهلك» وهو سلوكُها **القديم**، فأثبتَ ما لم يكن موضعَ الشكّ.
 * والمسارُ المقصودُ هو «دالةٌ ميتةٌ **داخلَ صنفٍ حيّ**» — فيُزرع في حارسٍ قائمٍ
 * له مستهلكون، ثم يُستعاد الملفُّ **ويُتحقَّق من تطابقِ بايتاتِه**.
 * ═══════════════════════════════════════════════════════════════════════════ */
$FAMILY = 'zzRatchetProbe';
$HOST = $ROOT . '/app/Core/AuthorityGuard.php';
$hostOrig = is_file($HOST) ? (string) file_get_contents($HOST) : null;
$sweep = function () use ($HOST, $hostOrig) {
    if ($hostOrig === null || !is_file($HOST)) { return 0; }
    $now = (string) file_get_contents($HOST);
    if ($now === $hostOrig) { return 0; }
    file_put_contents($HOST, $hostOrig);
    return 1;
};
$say('══ INJ-0239 · سقّاطةُ دوالِّ الحراسةِ الميتة  (كُنس ' . $sweep() . ' من الزرع)');

$run = function ($args = '') use ($GATE) {
    $o = array(); $c = 0;
    @exec('"' . PHP_BINARY . '" "' . $GATE . '" ' . $args . ' 2>&1', $o, $c);
    return array($c, implode("\n", $o));
};

$ok(is_file($GATE), 'البوابةُ موجودةٌ: tools/guard_adoption_gate.php');
$ok(is_file($BASE), 'وخطُّ السقّاطةِ موجودٌ: docs/fix_2026-08/guard_dead_methods_baseline.txt');

/* ══ ① الختمُ يقول الحقيقتين ════════════════════════════════════════════════ */
list($c0, $o0) = $run();
$ok($c0 === 0, 'البوابةُ خضراءُ على الخطِّ القائم (رمزٌ ' . $c0 . ')');
$ok(mb_strpos($o0, 'صنفِ') !== false && mb_strpos($o0, 'الدالة') !== false,
    'والختمُ يُعلن **مستوى الصنفِ ومستوى الدالةِ معًا**',
    'كان يقول «كلُّ حارسٍ متبنًّى» و49 دالةً ميتةٌ تحته');
$ok(preg_match('~صفرُ \*\*صنفِ\*\* حراسةٍ~u', $o0) === 1,
    '   ولا يدَّعي «صفرَ حارسٍ» مطلقًا بل «صفرَ صنفٍ» — والفرقُ هو العطبُ نفسُه');

/* ══ ② الخطُّ مُولَّدٌ من مصدرِه لا مكتوبٌ بيدٍ ═══════════════════════════════ */
list($cl, $ol) = $run('--list-dead');
$listed = array();
foreach (explode("\n", $ol) as $l) {
    $l = trim($l);
    if (preg_match('~^[A-Za-z_][A-Za-z0-9_]*::[A-Za-z_][A-Za-z0-9_]*$~', $l)) { $listed[$l] = true; }
}
$ok($cl === 0 && count($listed) > 10,
    'مخرَجُ `--list-dead` يُعطي القائمةَ كاملةً (' . count($listed) . ' دالةً)',
    'أوّلُ توليدٍ للخطِّ حلَّل نصَّ العرضِ فأخرجَ **صفرَ اسمٍ** من 49 — والسردُ محدودٌ بعشرين');
$baseNames = array();
foreach (file($BASE, FILE_IGNORE_NEW_LINES) as $l) {
    $l = trim($l);
    if ($l !== '' && strpos($l, '#') !== 0) { $baseNames[$l] = true; }
}
$ok(count($baseNames) > 10, 'وخطُّ السقّاطةِ فيه ' . count($baseNames) . ' اسمًا');
$drift = array_diff(array_keys($listed), array_keys($baseNames));
$ok(count($drift) === 0, 'وصفرُ انحرافٍ بين المقيسِ والخطِّ (' . count($drift) . ')',
    implode(' · ', array_slice($drift, 0, 4)));

/* ══ ③ **الحجبُ يعمل** — بزرعِ دالةِ حراسةٍ ميتةٍ حقيقية ═══════════════════════ */
$ok($hostOrig !== null, 'وُجد حارسٌ **حيٌّ** للزرعِ فيه: app/Core/AuthorityGuard.php');
$planted = false;
if ($hostOrig !== null) {
    /* تُضاف دالةٌ عامةٌ لا يناديها أحدٌ، قبلَ آخرِ قوسٍ مُغلِقٍ في الملف */
    $pos = strrpos($hostOrig, '}');
    if ($pos !== false) {
        $method = "\n    /** دالةُ حراسةٍ **مزروعةٌ عمدًا** بصفرِ مستهلك — تُزرع وتُرفَع في\n"
                . "     *  `tests/guard_adoption_ratchet_test.php` لإثباتِ أنَّ السقّاطةَ تحجب. */\n"
                . "    public static function {$FAMILY}(\$x)\n    {\n        return (bool) \$x;\n    }\n";
        $new = substr($hostOrig, 0, $pos) . $method . substr($hostOrig, $pos);
        $planted = @file_put_contents($HOST, $new) !== false;
    }
}
$ok($planted, 'وزُرعت فيه دالةُ حراسةٍ ميتةٌ (' . $FAMILY . ')');
/* ◆ ولا تُترك صياغةٌ مكسورةٌ في حارسٍ إنتاجيٍّ ولو لحظةً */
if ($planted) {
    $o = array(); $c = 0;
    @exec('"' . PHP_BINARY . '" -l "' . $HOST . '" 2>&1', $o, $c);
    if ($c !== 0) { $sweep(); $planted = false; }
    $ok($c === 0, '   وصياغةُ الحارسِ سليمةٌ بعد الزرعِ (وإلا استُعيد فورًا)');
}

if ($planted) {
    list($c1, $o1) = $run();
    $ok($c1 !== 0, '**البوابةُ تحجب** بدالةٍ ميتةٍ جديدةٍ (رمزٌ ' . $c1 . ')',
        'لو عادت صفرًا لكانت السقّاطةُ زخرفةً — والنزيفُ يستمرُّ صامتًا');
    $ok(mb_strpos($o1, $FAMILY) !== false,
        '   وتُسمّي الدالةَ الجديدةَ بالاسم — فالمخالفةُ مرئيةٌ لا مجملة');
    $ok(mb_strpos($o1, 'فوقَ خطِّ السقّاطة') !== false, '   وتُبيّن أنها **فوقَ** الخطِّ لا ضمنَه');
    /* والرفعُ يُفحَص ثم تعود الخُضرة — فالحمرةُ كانت بالزرعِ لا بعطبٍ قائم */
    $gone = $sweep();
    $ok($gone === 1, 'رُفع الزرعُ واستُعيد الحارسُ (' . $gone . ')');
    /* ◆ ويُتحقَّق من **تطابقِ البايتات** لا من مجردِ الاستعادة */
    $ok((string) file_get_contents($HOST) === $hostOrig,
        '   والحارسُ عاد مطابقًا بايتًا ببايت — صفرُ أثرٍ في ملفٍّ إنتاجيّ');
    list($c2, ) = $run();
    $ok($c2 === 0, 'وعادت البوابةُ خضراءَ (' . $c2 . ') — فالحجبُ كان بالزرع');
}

$say('');
$say("PASS={$PASS} · FAIL={$FAIL}");
exit($FAIL === 0 ? 0 : 1);
