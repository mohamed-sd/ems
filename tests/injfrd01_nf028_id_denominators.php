<?php
/**
 * tests/injfrd01_nf028_id_denominators.php
 *   NF-28 — **مقاما عقدِ المعرِّفات: يُعلَنانِ معًا، وبينهما جسرٌ مكتوب**
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ **العطبُ الذي يعالجه هذا الشاهد** (البند ١-٣ من INJ-EXEC-CLOSE-01):
 *   لعقدِ معرِّفاتِ الأسطحِ في `gov_screen_cycle` **مقياسان لا واحد**:
 *     · **الضيّق** — صفوفٌ معرِّفُها ليس ملفَّ `.php` أصلًا (نصٌّ حرّ)؛
 *     · **الواسع** — صفوفٌ معرِّفُها **اسمٌ مجرَّدٌ بلا مسار**، فلا يُربَط بملفٍّ
 *       بعينِه ما لم يُفترَض مجلَّدُه.
 *   وكان كلُّ تقريرٍ يذكر أحدَهما فيبدو العيبُ صغيرًا أو هائلًا بحسبِ أيِّهما
 *   وقع تحتَ اليد — **ورقمٌ بلا مقامٍ يُقرَّر عليه خطأً**.
 *
 * ◆ **وكان الحارسانِ يقيسان وجودَ رقمٍ في ملفِّ ماركداون** (`mb_strpos($base,'147')`)
 *   — أي أن كتابةَ «147» في أيِّ سياقٍ كانت تُخضِّر البوابة، **ولو كان الرقمُ
 *   منقولًا لا مقيسًا**. وهو كذلك: المُعلَنُ ١٤٧ والمقيسُ حيًّا **صفر**.
 *
 * ◆ **والحكمُ هنا بالقياسِ الحيِّ وحدَه** — يُصدَّر المقامانِ معًا في مخرَجٍ واحدٍ
 *   لا يُقرأ أحدُهما دونَ الآخر، ومعهما **جدولُ التحويل**: كيف يتحوّل الضيّقُ
 *   إلى الواسعِ وما الذي يفصل بينهما.
 *
 * التشغيل: php tests/injfrd01_nf028_id_denominators.php [--negative]
 *
 * ◆ و`--negative` يُثبت أن الجسرَ **يقدر أن ينكسر**: يُمرَّر مقامٌ ناقصٌ فيُشترط
 *   رسوبُ الموازنة — فجسرٌ لا يرسُبُ على عدمِ التوازنِ ليس جسرًا.
 * ═══════════════════════════════════════════════════════════════════════════
 */
if (php_sapi_name() !== 'cli') { exit("CLI فقط\n"); }
error_reporting(E_ALL & ~E_DEPRECATED & ~E_WARNING & ~E_NOTICE);
mb_internal_encoding('UTF-8');
mysqli_report(MYSQLI_REPORT_OFF);

$ROOT = dirname(__DIR__);
require_once $ROOT . '/includes/env.php';
$host = ems_env('DB_HOST'); $port = 3306;
if (strpos($host, ':') !== false) { list($host, $port) = explode(':', $host); $port = (int) $port; }
$u = ems_env('DB_MIGRATOR_USER') ?: ems_env('DB_USER');
$p = ems_env('DB_MIGRATOR_USER') ? ems_env('DB_MIGRATOR_PASS') : ems_env('DB_PASS');
$db = new mysqli($host, $u, $p, ems_env('DB_NAME'), $port);
if ($db->connect_errno) { exit("تعذّر الاتصال: {$db->connect_error}\n"); }
$db->set_charset('utf8mb4');

$ok = 0; $bad = 0;
function chk($c, $l, $d = '')
{
    global $ok, $bad;
    if ($c) { $ok++; echo "  ✔ {$l}" . ($d !== '' ? " — {$d}" : '') . "\n"; }
    else    { $bad++; echo "  ✘ {$l}" . ($d !== '' ? " — {$d}" : '') . "\n"; }
}
$neg = in_array('--negative', $argv, true);

/**
 * يقيس مقامَي عقدِ المعرِّفاتِ **معًا** — **موضعٌ واحدٌ للقياس** يقرأ منه كلُّ
 * مُعلِن، فلا يُنقل رقمٌ ولا يُذكر مقامٌ دونَ أخيه.
 *
 * الحقول:
 *   total     كلُّ صفوفِ الدورة — المقامُ الجامع
 *   free_text الضيّق: المعرِّفُ ليس ملفَّ `.php` أصلًا (تُنزع مرساةُ `#` و`?` أولًا)
 *   bare      الواسع: اسمٌ مجرَّدٌ بلا `/` — لا يُربَط بملفٍّ إلا بافتراضِ مجلَّده
 *   pathed    معرِّفٌ بمسارٍ كامل — وهو وحدَه المستوفي للعقد
 */
function nf028_denominators(mysqli $db)
{
    $total = 0; $freeText = 0; $bare = 0; $pathed = 0;
    $q = $db->query("SELECT `screen_file` FROM `gov_screen_cycle`");
    while ($q && ($x = $q->fetch_row())) {
        $v = trim((string) $x[0]);
        $total++;
        /* مرساةُ المنظرِ (`#2`) والاستعلامُ (`?view=`) جزءٌ من الوجهةِ لا من الملفّ */
        $file = preg_replace('/[?\#].*$/', '', $v);
        if (!preg_match('/\.php$/i', $file)) { $freeText++; }
        if (strpos($v, '/') === false) { $bare++; } else { $pathed++; }
    }
    return array('total' => $total, 'free_text' => $freeText,
                 'bare' => $bare, 'pathed' => $pathed);
}

echo "══ NF-28 — مقاما عقدِ المعرِّفات · يُعلَنانِ معًا وبينهما جسر ══\n";

$D = nf028_denominators($db);
if ($neg) {
    /* ◆ **العطبُ عمدًا**: مقامٌ ناقصٌ — يُنقص صفٌّ من طرفٍ واحدٍ فيختلُّ الميزان.
     *   والعطبُ في **المصفوفةِ المقروءةِ** لا في القاعدة: لا صفَّ يُكتب ولا يُحذَف. */
    $D['bare'] = max(0, $D['bare'] - 1);
    echo "  ◆ أُنقص المقامُ الواسعُ بواحدٍ للحزامِ السلبيّ — والقاعدةُ لم تُمَسّ\n";
}

/* ═══ ① المقامانِ مقيسانِ حيًّا لا منقولان ═══════════════════════════════ */
chk($D['total'] > 0, '**المقامُ الجامعُ مقيسٌ حيًّا** من `gov_screen_cycle`',
    "صفوفُ الدورة: **{$D['total']}**");

/* ═══ ② جدولُ التحويل — يُطبع كاملًا ولا يُختصر في رقم ═════════════════ */
echo "\n── جدولُ التحويلِ بين المقامَين ──\n";
$pct = function ($n, $d) { return $d > 0 ? number_format($n * 100 / $d, 1) . '٪' : '—'; };
printf("  %-46s %6s   %s\n", 'المقياس', 'العدد', 'من المقامِ الجامع');
printf("  %-46s %6d   %s\n", 'المقامُ الجامع — كلُّ صفوفِ الدورة',
       $D['total'], $pct($D['total'], $D['total']));
printf("  %-46s %6d   %s\n", '◆ الضيّق — معرِّفٌ ليس ملفَّ php أصلًا',
       $D['free_text'], $pct($D['free_text'], $D['total']));
printf("  %-46s %6d   %s\n", '◆ الواسع — اسمٌ مجرَّدٌ بلا مسار',
       $D['bare'], $pct($D['bare'], $D['total']));
printf("  %-46s %6d   %s\n", '  المستوفي للعقد — معرِّفٌ بمسارٍ كامل',
       $D['pathed'], $pct($D['pathed'], $D['total']));
echo "  ◆ **والضيّقُ جزءٌ من الواسعِ لا مقياسٌ منافس**: كلُّ معرِّفٍ ليس ملفًّا\n"
   . "    هو بالضرورةِ اسمٌ مجرَّد — فالفرقُ بينهما هو ما يحمل امتدادَ `.php`\n"
   . "    وينقصه المجلَّد. **ورقمٌ يُذكر وحدَه من هذين يُقرَّر عليه خطأً.**\n\n";

/* ═══ ③ الميزان — الواسعُ والمسارُ الكاملُ يستوفيان المقامَ الجامع ══════ */
$balances = ($D['bare'] + $D['pathed'] === $D['total']);
chk($balances, 'و**الجسرُ يوازن**: المجرَّدُ + ذو المسارِ = المقامُ الجامع',
    "{$D['bare']} + {$D['pathed']} = " . ($D['bare'] + $D['pathed']) . " · والمقام {$D['total']}");

/* ═══ ④ الضيّقُ محتوًى في الواسع — وإلا فهما مقياسان لا مقياسٌ وتفصيلُه ═ */
chk($D['free_text'] <= $D['bare'],
    'والضيّقُ **محتوًى في الواسعِ** فالجسرُ احتواءٌ لا تجاور',
    "الضيّق {$D['free_text']} ≤ الواسع {$D['bare']}");

/* ═══ ⑤ صفرُ مقامٍ يُعلَن وحدَه — الإعلانُ بالبنيةِ لا بالانضباط ════════ */
$emitted = array('total' => $D['total'], 'free_text' => $D['free_text'],
                 'bare' => $D['bare'], 'pathed' => $D['pathed']);
chk(count(array_diff_key(array('total'=>1,'free_text'=>1,'bare'=>1,'pathed'=>1), $emitted)) === 0,
    'و**المخرَجُ يحمل الأربعةَ معًا** — فلا يُقرأ مقامٌ دونَ أخيه',
    'المُصدَّر: ' . implode(' · ', array_keys($emitted)));

/* حكمٌ مقروءٌ آليًّا — يقرأ منه المُعلِنون ولا ينقلون رقمًا بأيديهم */
printf("#NF028 total=%d free_text=%d bare=%d pathed=%d\n",
       $D['total'], $D['free_text'], $D['bare'], $D['pathed']);

if ($neg) {
    echo "\n── حكمُ الحزامِ السلبيّ ──\n";
    chk(!$balances, '**الميزانُ رسب على مقامٍ ناقص**',
        $balances ? 'مرَّ — والجسرُ لا يرى الخلل' : 'الفرقُ واحد — والجسرُ رآه');
    echo "\n◆ والحزامُ يعطب **المصفوفةَ المقروءةَ** لا القاعدة — فلا صفَّ يُكتب ولا يُحذَف.\n";
    printf("النتيجة: %d نجاح · %d رسوب\n", $ok, $bad);
    exit(!$balances ? 0 : 1);
}

echo "\n" . str_repeat('─', 66) . "\n";
printf("النتيجة: %d نجاح · %d رسوب\n", $ok, $bad);
exit($bad === 0 ? 0 : 1);
