<?php
/**
 * tests/regression_exit_contract_test.php — شاهدُ INJ-0149
 * ═══════════════════════════════════════════════════════════════════════════
 * ⇐ شواهدُ أحكامٍ: INJ-0149
 *
 * **اختبارُ قبولِ INJ-0149 نصًّا** (من السجلِّ الجامع · شاشةُ «اختبارات وحدة العقود»):
 *   «أمرٌ واحدٌ يشغّل كلَّ اختبارات وحدة العقود ويُرجع **صفرًا** عند النجاح؛
 *    و**خطُّ التسليم يفشل** عند سقوطِ أيِّ اختبار.»
 *
 * وفجوةُ البندِ **دليلٌ** لا تنفيذ: المُشغِّلُ `tests/_regression.php` قائمٌ ويعمل،
 * ولم يكن له شاهدٌ يُثبت **عقدَ رمزِ خروجِه**. فهذا الفاحصُ يُثبت الشقّين:
 *   ① جولةٌ ناجحةٌ ⇒ رمزُ خروجٍ **0**.
 *   ② وجولةٌ فيها فاحصٌ ساقطٌ ⇒ رمزُ خروجٍ **غيرُ صفرٍ** — بجولةٍ **حمراءَ حقيقيةٍ**
 *      لا بقراءةِ سطرِ `exit` في المصدر. فالشقُّ الثاني هو الذي يُسقط خطَّ
 *      التسليمِ، وقراءةُ المصدرِ لا تُثبت أنه يعمل.
 *   ③ ومسُّ ملفٍّ محميٍّ يُسقط الجولةَ **ولو نجحت تأكيداتُ الاختبار** — فالإفسادُ
 *      فشلٌ. (مقيسٌ بالمصدرِ لأنَّ إفسادَ `.env` حيًّا خطرٌ لا يُقاس به شيء.)
 *
 * ◆ ولا تُشغَّل الجولةُ الكاملةُ هنا (عشرون دقيقةً): يُستعمل مدخلُ `only` الذي
 *   يُشغّل **المُشغِّلَ نفسَه** بقائمةٍ مسمّاةٍ — فما يُقاس هو المُشغِّلُ لا نسخةٌ منه.
 * ◆ والفاحصُ الساقطُ **يُصنَع مؤقتًا ويُرفَع** بوسمٍ عائليٍّ، ويُتحقَّق من رفعِه.
 * ═══════════════════════════════════════════════════════════════════════════
 */
if (php_sapi_name() !== 'cli') { exit("CLI فقط\n"); }
error_reporting(E_ALL & ~E_DEPRECATED);
mb_internal_encoding('UTF-8');
$ROOT = dirname(__DIR__);
$DIR = __DIR__;

$PASS = 0; $FAIL = 0;
$ok = function ($cond, $label, $extra = '') use (&$PASS, &$FAIL) {
    if ($cond) { $PASS++; fwrite(STDOUT, "  ✔ {$label}\n"); }
    else { $FAIL++; fwrite(STDOUT, "  ✘ {$label}" . ($extra !== '' ? "  ⟵ {$extra}" : '') . "\n"); }
};
$say = function ($s) { fwrite(STDOUT, $s . "\n"); };

/* الوسمُ عائليٌّ — والكنسُ بعائلتِه لا بالوسمِ وحدَه (جولةٌ ماتت تترك ثغرةً) */
$FAMILY = 'zz_exitprobe';
$TMP = $DIR . '/' . $FAMILY . '_' . getmypid() . '_test.php';
$sweep = function () use ($DIR, $FAMILY) {
    $n = 0;
    foreach (glob($DIR . '/' . $FAMILY . '_*_test.php') as $f) { if (@unlink($f)) { $n++; } }
    return $n;
};
$say('══ INJ-0149 · عقدُ رمزِ خروجِ مُشغِّلِ الانحدار  (كُنس ' . $sweep() . ' من عائلةِ ' . $FAMILY . ')');

$RUNNER = $DIR . '/_regression.php';
$ok(is_file($RUNNER), 'المُشغِّلُ الواحدُ موجودٌ: tests/_regression.php');

/** يُشغّل المُشغِّلَ بسويتٍ ويُرجع (رمزُ الخروج · المخرَج) */
$run = function ($suite, $list = null) use ($RUNNER) {
    $cmd = '"' . PHP_BINARY . '" "' . $RUNNER . '" ' . escapeshellarg($suite);
    if ($list !== null) { $cmd .= ' ' . escapeshellarg($list); }
    $o = array(); $c = 0;
    @exec($cmd . ' 2>&1', $o, $c);
    return array($c, implode("\n", $o));
};

/* ══ ① مدخلُ القياسِ قائمٌ ويسري عليه عقدُ المُشغِّلِ نفسُه ═══════════════════════ */
$src = (string) file_get_contents($RUNNER);
$ok(strpos($src, "\$suite === 'only'") !== false,
    'مدخلُ `only` قائمٌ — فالقياسُ على المُشغِّلِ نفسِه لا على نسخةٍ منه');
$ok(preg_match('~exit\(\(\$red > 0 \|\| \$harmedBy\) \? 1 : 0\);~', $src) === 1,
    'وعقدُ الخروجِ مكتوبٌ: صفرٌ إن نجح الكلُّ · وواحدٌ إن سقط واحدٌ **أو** مُسَّ ملفٌّ محميّ',
    'وهذا الشقُّ الثالثُ يُقاس بالمصدرِ لأنَّ إفسادَ .env حيًّا خطرٌ لا يُقاس به شيء');

/* ══ ② الشقُّ الأول: جولةٌ ناجحةٌ ⇒ صفر ══════════════════════════════════════ */
$GREEN = 'tenant_leak_test,audit_trail_test';
list($c1, $o1) = $run('only', $GREEN);
$ok($c1 === 0, 'جولةٌ ناجحةٌ (فاحصان) ⇒ رمزُ خروجٍ **0**', 'الرمزُ ' . $c1);
$ok(preg_match('~حمراء:\s*0~u', $o1) === 1, '   والمخرَجُ يعلن «حمراء: 0»');
$ok(preg_match('~مجموعُ الفحوص: ناجحٌ\s*(\d+)~u', $o1, $m1) === 1 && (int) $m1[1] > 0,
    '   ويعدُّ الفحوصَ لا الملفاتِ وحدَها (' . (isset($m1[1]) ? $m1[1] : '?') . ' فحصًا)');

/* ══ ③ **الشقُّ الثاني — جولةٌ حمراءُ حقيقيةٌ** ⇒ رمزٌ غيرُ صفرٍ ══════════════════
     يُصنَع فاحصٌ ساقطٌ عمدًا: يطبع عدَّادًا يقرأه المُشغِّلُ ويخرج بواحدٍ. */
$body = "<?php\n"
      . "/* فاحصٌ ساقطٌ **عمدًا** — يُصنَع ويُرفَع في `regression_exit_contract_test`\n"
      . " * لإثباتِ أنَّ خطَّ التسليمِ يفشل عند سقوطِ اختبار (INJ-0149). */\n"
      . "fwrite(STDOUT, \"  ✘ فحصٌ ساقطٌ عمدًا\\n\");\n"
      . "fwrite(STDOUT, \"PASS=0 · FAIL=1\\n\");\n"
      . "exit(1);\n";
$wrote = @file_put_contents($TMP, $body);
$ok($wrote !== false && is_file($TMP), 'صُنع فاحصٌ ساقطٌ عمدًا (' . basename($TMP) . ')');

if (is_file($TMP)) {
    $name = basename($TMP, '.php');
    list($c2, $o2) = $run('only', $GREEN . ',' . $name);
    $ok($c2 !== 0,
        '**جولةٌ فيها ساقطٌ ⇒ رمزُ خروجٍ غيرُ صفرٍ** (' . $c2 . ') — خطُّ التسليمِ يفشل',
        'لو عادت صفرًا لكان خطُّ التسليمِ يمرّر عملًا مكسورًا');
    $ok(preg_match('~حمراء:\s*([1-9]\d*)~u', $o2) === 1,
        '   والمخرَجُ يعلن حمراءَ ≥ 1 — فالسقوطُ مرئيٌّ لا صامت');
    $ok(mb_strpos($o2, $name) !== false, '   ويسمّي الفاحصَ الساقطَ بالاسم');
    /* ◆ والرفعُ يُفحَص: ثغرةٌ باقيةٌ تُسقط الشجرةَ كلَّها في الجولةِ التالية */
    $gone = $sweep();
    $ok($gone >= 1, 'رُفع الفاحصُ الساقطُ (' . $gone . ' ملفًّا)');
    $ok(count(glob($DIR . '/' . $FAMILY . '_*_test.php')) === 0,
        '   وصفرُ ثغرةٍ من عائلةِ الوسمِ بعد الجولة');
    /* ◆ وعودةُ الخُضرةِ بعد الرفعِ — فالحمرةُ كانت بالزرعِ لا بعطبٍ قائم */
    list($c3, ) = $run('only', $GREEN);
    $ok($c3 === 0, 'وعادت الجولةُ خضراءَ بعد الرفعِ (' . $c3 . ') — فالحمرةُ كانت بالزرع');
}

$say('');
$say("PASS={$PASS} · FAIL={$FAIL}");
exit($FAIL === 0 ? 0 : 1);
