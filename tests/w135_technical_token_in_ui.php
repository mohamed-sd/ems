<?php
/**
 * tests/w135_technical_token_in_ui.php — أيعرف كاشفُ التسرُّبِ كيف يرسُب؟
 * ═══════════════════════════════════════════════════════════════════════════
 * **حكمُ المالك 2026-08-27**: الهدف `TECHNICAL_TOKEN_IN_UI_LABEL = 0` ⛔
 * «**ولا نعتبر الحارسَ مكتملًا حتى يثبت أنّه يستطيع الرسوب**».
 *
 * ◆ **وأربعُ زوايا لأنَّ للكاشفِ أربعَ طرقٍ للكذب**:
 *   ① يمرُّ على النظيف · ② **يُمسِك التسرُّبَ الحقيقيَّ** · ③ لا يخلط
 *   الجافاسكربتَ بنصِّ الواجهة · ④ ولا يخلط الشِّفرةَ المعروضةَ عمدًا بالتسرُّب.
 *
 * ⚠ وثلاثُ نسخٍ سبقت هذا الكاشفَ أعطت **2222 ثمَّ 939 ثمَّ 153** — وكلُّها
 *   ضجيج. والنسخةُ الرابعةُ تقيس بـ`token_get_all()` **بتعريفِ PHP لا بتقريبي**،
 *   وتتتبَّع كتلةَ السكربتِ **عبر الرموزِ** لأنَّ `<?= ?>` يقطعها.
 *
 * التشغيل: php tests/w135_technical_token_in_ui.php   (خروج 0 = نجاح)
 * ═══════════════════════════════════════════════════════════════════════════
 */
if (php_sapi_name() !== 'cli') { exit("CLI فقط\n"); }
error_reporting(E_ALL & ~E_DEPRECATED);
mb_internal_encoding('UTF-8');
$ROOT = dirname(__DIR__);
$TOOL = $ROOT . '/tools/repair01_edc_token_leak.php';
$PROBE = $ROOT . '/Reports/_edc_token_probe.php';
$pass = 0; $fail = 0;
$ok = function ($c, $m) use (&$pass, &$fail) {
    if ($c) { $pass++; echo "  ✔ $m\n"; } else { $fail++; echo "  ✘ $m\n"; }
};
/* يشغّل الكاشفَ ويعيد العددَ المحكومَ به */
$run = function () use ($TOOL) {
    $out = array();
    exec('"' . PHP_BINARY . '" ' . escapeshellarg($TOOL) . ' 2>&1', $out);
    foreach ($out as $l) {
        if (preg_match('~TECHNICAL_TOKEN_IN_UI_LABEL = (\d+)~u', $l, $m)) { return (int) $m[1]; }
    }
    return -1;
};
$seed = function ($body) use ($PROBE) { file_put_contents($PROBE, $body); };

echo "\n══ ① الحالُ النظيفُ ══\n";
$base = $run();
$ok($base === 0, "الشجرةُ الحيّةُ صفرٌ في الحكم (‏المقيس $base)");

echo "\n══ ② والكاشفُ يعرف كيف يرسُب — تسرُّبٌ حقيقيٌّ بالشكلِ الحقيقيّ ══\n";
$seed("<?php \$typetext = 'تأكيد'; ?>\n<h2>\$typetext</h2>\n");
$ok($run() === 1, '**رمزٌ في نصِّ HTML أُمسِك** — ولولا ذلك لكان جدارًا أبيض');

echo "\n══ ③ ولا يخلط الجافاسكربتَ بنصِّ الواجهة ══\n";
$seed("<?php \$n = 1; ?>\n<script>\n  var x = <?= \$n ?>;\n  \$('#t').text(\$data);\n</script>\n");
$ok($run() === 0, '`$` في سكربتٍ يقطعه `<?= ?>` لا يُعدُّ تسرُّبًا — والحالةُ تُتتبَّع عبر الرموز');

echo "\n══ ④ ولا يخلط الشِّفرةَ المعروضةَ عمدًا بالتسرُّب ══\n";
$seed("<p>الجلسة عبر <code>\$_SESSION['x']</code>.</p>\n");
$ok($run() === 0, 'رمزٌ داخلَ وسمِ شِفرةٍ خبرٌ لا حكم — والرمزُ المعروضُ رمزًا ليس تسرُّبًا');

echo "\n══ ⑤ الكنس ══\n";
@unlink($PROBE);
$ok(!is_file($PROBE), 'كُنس الزرعُ من الشجرة');
$ok($run() === $base, 'والحالُ عاد إلى ما كان — ' . $base);

echo "\n──────────────────────────────────────────────────────────\n";
printf("النتيجة: %d نجاح · %d رسوب\n", $pass, $fail);
exit($fail === 0 ? 0 : 1);
