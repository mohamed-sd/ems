if (!function_exists('ems_dept_unit_of_role')) {
    function ems_dept_unit_of_role($roleId)
    {
        $map = array(
            1  => 1,   // التشغيل
            2  => 15,  // الموردون — وحدةٌ موازية (ORG v4)
            3  => 5,   // الأسطول
