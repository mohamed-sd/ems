<?php
/**
 * includes/guide_label.php — اسمُ حقلِ الورقةِ كما يُعرَض للمستخدم
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ **مسألتان تتجاذبان اسمًا واحدًا**، وكلتاهما بحقٍّ:
 *   · `GOV_EXEC` §12 يوجب أن يحمل السطحُ **حقلَ الورقةِ باسمِه** — فالخريطةُ
 *     `$GUIDE_COLS` تحمل الاسمَ حرفًا كما في «02 · تتبع الحقول»، وهو ما يقرؤه
 *     المقياسُ (الرافد `F8`) ويُطابقه.
 *   · و`REPAIR01 · W06 §٤-٩` (سقّاطةُ `UI-01`/`UI-02` المقفلةُ الاتجاه) تمنع
 *     **التشكيلَ والزخرفةَ في نصِّ شاشةٍ حيّة** — والرقمُ فيها لا يزيد.
 *
 * ◆ **والحسمُ ليس ترجيحًا بل تمييزُ طبقتَين**: `◄` و`▼` في الورقةِ **اصطلاحُ
 *   تصنيفٍ** (مشتقٌّ · قائمةٌ محكومة) لا جزءٌ من اسمِ الحقل، والتشكيلُ زينةُ
 *   كتابةٍ لا معنًى. فالاسمُ المخزَّنُ يبقى حرفًا (‏للمصدرِ والمقياس) والاسمُ
 *   **المعروضُ** يُنقّى منهما — فلا §12 يُخالَف ولا سقّاطةُ الواجهةِ تُخترق.
 *
 * ⛔ **ولا يُحذف حرفٌ من الاسم**: النقاءُ يطال التشكيلَ والاصطلاحَ وحدَهما،
 *   ولو حُذفت كلمةٌ لَتغيّر الحقلُ لا شكلُه.
 */
if (!function_exists('ems_guide_label')) {
    /**
     * @param  string $s اسمُ الحقلِ كما في ورقةِ الدليل
     * @return string الاسمُ المعروضُ — بلا تشكيلٍ ولا اصطلاحِ تصنيف
     */
    function ems_guide_label($s)
    {
        $s = (string) $s;
        /* اصطلاحُ الورقة: ◄ مشتقّ · ▼ قائمةٌ محكومة */
        $s = str_replace(array('◄', '▼'), '', $s);
        /* ◆ **والمرادفُ التقنيُّ بعدَ النقطةِ الوسطى يُسقَط** — الورقةُ تكتب
             «كود الوحدة التعاقدية · Slot_ID» و«مفتاح دورة الالتزام · Key»:
             الاسمُ عربيٌّ والذيلُ **معرِّفٌ تقنيٌّ** وهو بعينِه ما تمنعه
             سقّاطةُ `UI-02` في نصِّ الشاشة.
           ⛔ **ولا يُسقَط ذيلٌ فيه حرفٌ عربيّ**: «التكلفة · مرجع» يبقى كاملًا —
             فالقاعدةُ تطال المرادفَ اللاتينيَّ وحدَه لا كلَّ ما بعدَ الفاصل. */
        if (preg_match('~^(.*?)\s*·\s*([^\x{0600}-\x{06FF}]+)$~u', $s, $m)) { $s = $m[1]; }
        /* التشكيلُ والتطويل — نطاقُ الحركاتِ العربيّةِ وحدَه */
        $s = preg_replace('~[\x{0640}\x{064B}-\x{0652}\x{0670}]~u', '', $s);
        return trim(preg_replace('~\s+~u', ' ', $s));
    }
}
