<?php
/**
 * includes/public_shell.php — مدخلُ القشرةِ لشاشاتِ ما قبلَ الدخول (INJ-0236)
 * ═══════════════════════════════════════════════════════════════════════════
 * **العيب**: سبعةُ مساراتٍ مستقلةٍ تُصدر `<html>` و`<head>` وهيكلَها الخاص.
 * والقياسُ الحيُّ (بالرموزِ لا بالنص — فالتعليقاتُ التي تصف الحالةَ القديمةَ
 * كانت تُحسَب إصدارًا) أعطى **١٩ ملفًّا**، منها **١٣ شاشةَ ما-قبلَ-دخولٍ** حقيقية:
 * الدخولُ الرئيسُ · دخولُ الإدارةِ العليا · بوابةُ الشركاتِ بسبعِ شاشاتٍ ·
 * استعادةُ كلمةِ المرورِ وإعادةُ تعيينها · الصفحةُ الأولى.
 *
 * ولماذا لا تُضمَّن `inheader.php`: القشرةُ المصادَقةُ تفترض جلسةً ودورًا وقائمةً
 * وصلاحيات — ولا شيءَ من ذلك قبلَ الدخول. فالمدخلُ الصحيحُ ليس «القشرةَ نفسَها»
 * بل **مدخلًا معتمدًا ثانيًا** بالعقدِ نفسِه: مستندٌ صحيحٌ · اتجاهٌ عربيٌّ ·
 * `viewport` · وخطوطُ النظامِ ورموزُه من مصدرِها الواحد.
 *
 * ── والصفحةُ تُكمل رأسَها ────────────────────────────────────────────────────
 * ما تنفرد به كلُّ شاشةٍ من أنماطٍ يبقى بعد النداءِ مباشرةً وقبلَ `</head>` —
 * فالنقلُ لا يغيّر بايتًا في المُخرَجِ الظاهر، ويصير للمستندِ **مصدرٌ واحدٌ**.
 * ═══════════════════════════════════════════════════════════════════════════
 */

if (!function_exists('ems_public_head')) {
    /**
     * @param string $title عنوانُ الصفحةِ كما يظهر في لسانِ المتصفح
     * @param array  $opts  lang · dir · extra (وسومٌ إضافيةٌ في الرأس)
     */
    function ems_public_head($title, array $opts = array())
    {
        $E = function ($v) { return htmlspecialchars((string) $v, ENT_QUOTES, 'UTF-8'); };
        $lang = isset($opts['lang']) ? (string) $opts['lang'] : 'ar';
        $dir  = isset($opts['dir'])  ? (string) $opts['dir']  : 'rtl';
        echo '<!DOCTYPE html>' . "\n"
           . '<html lang="' . $E($lang) . '" dir="' . $E($dir) . '">' . "\n"
           . '<head>' . "\n"
           . '  <meta charset="UTF-8">' . "\n"
           . '  <meta name="viewport" content="width=device-width, initial-scale=1.0">' . "\n"
           . '  <meta http-equiv="X-UA-Compatible" content="ie=edge">' . "\n"
           . '  <title>' . $E($title) . '</title>' . "\n"
           . '  <link href="/ems/assets/css/local-fonts.css" rel="stylesheet">' . "\n";
        /* ◆ بعضُ شاشاتِ ما قبلَ الدخولِ لا تعرض أيقونةً واحدةً (استعادةُ كلمةِ
             المرورِ مثلًا) — فتحميلُ ورقةِ الرموزِ فيها كيلوباياتٌ بلا مقابل.
             والافتراضُ حملُها لأنَّ أكثرَها يستعملها. */
        if (!isset($opts['icons']) || $opts['icons']) {
            echo '  <link rel="stylesheet" href="/ems/assets/css/all.min.css">' . "\n";
        }
        if (!empty($opts['extra'])) { echo $opts['extra'] . "\n"; }
    }
}
