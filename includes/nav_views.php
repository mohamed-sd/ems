/** يُعلن أن الشاشةَ الجاريةَ تملك `?view=` وتتولّى معناه بنفسِها. */
function ems_nav_view_claim()
{
    $GLOBALS['ems_nav_view_owner'] = true;
}

/** أأُعلنت ملكيةُ المعاملِ في هذه الطلبة؟ */
function ems_nav_view_claimed()
{
    return !empty($GLOBALS['ems_nav_view_owner']);
}
