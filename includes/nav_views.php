/** هل الرمزُ مُعلَنٌ لهذا الملف؟ يُرجع الإعلانَ أو null. */
function ems_nav_view_declared($file, $code)
{
    $file = strtolower(trim(str_replace('\\', '/', (string) $file), '/'));
    $file = preg_replace('~^(\.\./)+~', '', $file);
    $reg  = ems_nav_views_registry();
    if (!isset($reg[$file])) { return null; }
    $code = (string) $code;
    return isset($reg[$file][$code]) ? $reg[$file][$code] : null;
}

/**
 * هل يحمل هذا المسارُ مِنظرًا **مُعلَنًا**؟ — يستعمله حارسُ التكرارِ ليعرف
 * أنَّ الصفَّينِ وجهتانِ لا صفٌّ مكرَّر. ورمزٌ غيرُ مُعلَنٍ **لا يُميّز شيئًا**
 * فلا يُهرَّب به صفٌّ مكرَّرٌ من الحارس.
 */
function ems_nav_route_has_view($route)
{
    $route = (string) $route;
    if (strpos($route, 'view=') === false) { return false; }
    if (!preg_match('~[?&]view=([^&#]+)~', $route, $m)) { return false; }
    $file = preg_replace('~[?#].*$~', '', $route);
    return ems_nav_view_declared($file, urldecode($m[1])) !== null;
}

