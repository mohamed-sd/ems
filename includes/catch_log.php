<?php
/**
 * includes/catch_log.php — تسجيلُ الاستثناءِ الملتقَط في موضعٍ واحد (CS-12)
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ العلّةُ التي يعالجها: النمطُ الغالبُ في الخدماتِ هو
 *     `try { $x = read(); } catch (\Throwable $t) { $x = null; }`
 *   ثم `if (!$x) { return ['code'=>404, 'reason'=>'غيرُ موجود']; }`.
 *   والفشلُ **يُصعَّد** بعد سطرين — فليس ابتلاعًا بالمعنى الكامل. لكنّ عيبَين
 *   حقيقيَّين يبقيان:
 *     ① **تفاصيلُ الاستثناءِ تتبخّر**: عطلُ اتصالٍ أو خطأُ صياغةٍ أو رفضُ قيدٍ
 *        — كلُّها تختفي بلا أثرٍ واحدٍ يُقرأ لاحقًا.
 *     ② **عطلُ البنيةِ يُلبَس ثوبَ غيابِ العمل**: «المشروعُ غير موجودٍ في
 *        نطاقك» رسالةٌ كاذبةٌ حين يكون السببُ انقطاعَ القاعدة. والمستخدمُ
 *        يطارد صلاحيةً وهميةً بينما العطلُ في مكانٍ آخرَ تمامًا.
 *
 * ◆ ولذلك لا يُغيَّر مسارُ التحكُّم — يُضاف **التسجيلُ** وحدَه. تغييرُ المسارِ
 *   في 262 موضعًا دفعةً واحدةً مخاطرةٌ لا يبرّرها مكسب، والسقّاطةُ المفحوصةُ
 *   بعد الالتقاطِ تؤدي الغرضَ سلفًا.
 *
 * ◆ والرسالةُ موسومةٌ بـ`CS12` ليُمكن حصرُها: `grep CS12 logs/php_errors.log`.
 */

if (!function_exists('ems_catch_log')) {
    /**
     * يسجّل استثناءً التُقط ولم يُصعَّد فورًا.
     *
     * @param \Throwable $e
     * @param string     $where  الموضعُ — يُمرَّر `__METHOD__` أو `__FUNCTION__`
     * @return void  لا يُرجع شيئًا ولا يرمي: التسجيلُ لا يُفشِل ما يسجّله.
     */
    function ems_catch_log($e, $where = '')
    {
        if (!($e instanceof \Throwable)) { return; }
        $msg = '[CS12] ' . ($where !== '' ? $where . ' — ' : '')
             . get_class($e) . ': ' . $e->getMessage()
             . ' @ ' . basename($e->getFile()) . ':' . $e->getLine();
        error_log($msg);
    }
}

if (!function_exists('ems_catch_ignored')) {
    /**
     * فشلٌ **مقصودُ التجاهل** — ويجب أن يُعلَن سببُه.
     *
     * ◆ لماذا دالةٌ ثانيةٌ ولا يكفي التسجيل: بعضُ الفشلِ تجاهلُه هو الصوابُ لا
     *   التساهل — إدراجٌ عاطلٌ يصطدم بمفتاحٍ مكرَّرٍ فالصفُّ موجودٌ سلفًا وهذا
     *   عينُ المطلوب؛ وإخطارٌ جانبيٌّ يفشل فلا يصحُّ أن يُسقط المعاملةَ التي
     *   نجحت. وتجريمُ هذا يدفع إلى رميٍ يُتلف عملًا سليمًا.
     *
     * ◆ لكنّ التجاهلَ الصامتَ هو ما تحظره CS-12. فالحلُّ ألّا يُمنع التجاهلُ
     *   بل **يُمنع كتمانُه**: مَن يتجاهل يُصرّح بالسبب، فيصير القرارُ مقروءًا
     *   في الكودِ ومحصورًا في السجلِّ وقابلًا للمراجعة. والفرقُ بين
     *   `ems_catch_log` وهذه: الأولى «فشلٌ سيُفحص أثرُه بعد سطور»، والثانية
     *   «فشلٌ قرّرنا أنه لا يغيّر النتيجة — وهذا هو السبب».
     *
     * @param \Throwable $e
     * @param string     $where  `__METHOD__`
     * @param string     $why    سببُ التجاهلِ بعبارةٍ مفهومة — إلزاميّ
     * @return void
     */
    function ems_catch_ignored($e, $where = '', $why = '')
    {
        if (!($e instanceof \Throwable)) { return; }
        $why = trim((string) $why);
        if ($why === '') { $why = '⚠ بلا سبب معلن — يحتاج مراجعة'; }
        error_log('[CS12-IGNORED] ' . ($where !== '' ? $where . ' — ' : '')
                . $why . ' :: ' . get_class($e) . ': ' . $e->getMessage());
    }
}
