/**
 * includes/sheet_fields.php — خليّةُ حقلِ ورقةِ الدليلِ في جدولِ الشاشة
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ **الحقلُ صار عمودًا في جدولِ الشاشةِ نفسِه** (‏هجرة `2028_06_01_sheet_merge_fields`)،
 *   فالخليّةُ تقرأ من صفِّ الجدولِ الحقيقيِّ لا من قوقعةٍ ثانية.
 *
 * ◆ **والغيابُ يُعرَض شرطةً لا فراغًا**: خليّةٌ فارغةٌ تُقرَأ عطلًا، والشرطةُ تقول
 *   «لا قيمةَ لهذا الصفِّ» — وهي المفردةُ نفسُها التي كان يستعملها `ems_w14_grid`.
 *
 * ⛔ **ولا يُخترع مصدر**: مفتاحٌ غائبٌ عن الصفِّ يُعطي شرطةً — ولا يُبحَث عنه في
 *   جدولٍ آخر، فالعمودُ الذي لا مصدرَ له في هذا الصفِّ **لا قيمةَ له فيه**.
 * ═══════════════════════════════════════════════════════════════════════════
 */
if (!function_exists('ems_sf')) {
    /**
     * @param  mixed  $row صفُّ الجدولِ (مصفوفةٌ أو كائن)
     * @param  string $col اسمُ العمود
     * @return string HTML جاهزٌ للطباعةِ داخلَ <td>
     */
    function ems_sf($row, $col)
    {
        $v = null;
        if (is_array($row) && array_key_exists($col, $row))      { $v = $row[$col]; }
        elseif (is_object($row) && isset($row->$col))            { $v = $row->$col; }
        if ($v === null || $v === '') { return '<span class="ems-gov-empty">—</span>'; }
        return htmlspecialchars((string) $v, ENT_QUOTES, 'UTF-8');
    }
}
