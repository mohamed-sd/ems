            'نصدر', 'ننفذ', 'ننفذ', 'نستقبل', 'نكمل', 'نغلق', 'نتحقق', 'نضبط',
            'نقيس', 'نوثق', 'نوثق', 'نستلم', 'نسلم', 'نسلم', 'ننشئ', 'ننشئ',
        );
    }
}

/**
 * النمطُ الكنسيّ.
 * ◆ ويُشترط بعدَ الفعلِ فاصلٌ (مسافةٌ أو نهايةُ نصّ) فلا يبتلع الفعلُ ما
 *   يشاركه حروفَه الأولى — **ويُسمح قبلَ الفاصلِ بضميرِ مفعولٍ متصل**
 *   (ـه ـها ـهم ـنا …)، فقد كشف الشاهدُ السالبُ أنَّ «نحاسبه ونصرف» كان
 *   يُفلت لأن الضميرَ يلتصق بالفعلِ فيُبطل حدَّ الكلمة.
 * ◆ والأطولُ قبلَ الأقصرِ في بدائلِ الضمير («ها» قبلَ «ه») وإلا اقتطع
 *   البديلُ الأقصرُ فسقط الحدّ.
 */
if (!function_exists('ems_conv_pattern')) {
    function ems_conv_pattern()
    {
        $verbs = array_map(
            static function ($v) { return preg_quote($v, '/'); },
            ems_conv_verbs()
        );
        return '/^(?:' . implode('|', $verbs) . ')(?:هما|ها|هم|هن|ه|كما|كم|كن|ك|نا|ني)?(?:\s|$)/u';
    }
}

/** هل النصُّ صيغةٌ محادثية؟ */
if (!function_exists('ems_is_conversational')) {
    function ems_is_conversational($s)
    {
        return (bool) preg_match(ems_conv_pattern(), (string) $s);
    }
}
