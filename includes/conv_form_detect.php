/** أفعالُ المضارعِ للجماعةِ الواردةُ في دفترِ الدورةِ وسجلِّ التنقّل */
if (!function_exists('ems_conv_verbs')) {
    function ems_conv_verbs()
    {
        return array(
            'نبدأ', 'نسجل', 'نسجل', 'نوزع', 'نوزع', 'نوقع', 'نوقع', 'نحاسب', 'نصرف',
            'نتفاوض', 'نسعر', 'نسعر', 'نفوتر', 'نحصل', 'نحصل', 'نتابع', 'نراجع',
