<?php
namespace App\Services\Ui;

/**
 * app/Services/Ui/UiPurity.php
 *   نواةُ نقاءِ لغةِ الواجهة — REPAIR01 · W06 · **مصدرٌ واحدٌ لا مصدران**
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ **لماذا صنفٌ بلا قاعدةِ بيانات**: يقرؤه أربعةُ مستهلكين — الخدمةُ الحيّةُ
 *   (`UiLabelRegistry`) والمنقّي (`tools/repair01_w6_apply.php`) والفاحصُ
 *   (`tools/repair01_ui_purity.php`) والسقّاطةُ (`repair01_debt_scan`).
 *   ولو نسخ كلٌّ منهم نمطَ الكشفِ لتفرّقت الأرقامُ بصمتٍ عند أوّلِ تعديل —
 *   وهو ما وقع قبلًا في عدّادٍ وعارضٍ في ملفَّين. **فالكاشفُ واحدٌ وله أربعةُ
 *   مستهلكين.**
 *
 * ◆ **والثلاثةُ التي لا تُمَسّ قناعٌ بنيويٌّ لا استثناءٌ مكتوبٌ في كلِّ أداة**
 *   (‏W06 §٤-١٠ · البنود ١٩ · ٢٠ · ٢١): `maskProtected()` تحجب قبل أيِّ فحص:
 *   ① **أكوادُ الأعمال** (`REQ-000278` · `AR-26Q3` · `EV-1204`) — قيمُ بياناتٍ
 *     لا مصطلحاتٌ تقنيّة. وبلا حجبِها يصير كلُّ رقمِ مستندٍ «مصطلحًا تقنيًّا»
 *     فيُنقَّى ما أمرت القاعدةُ بألّا يُمَسّ.
 *   ② **البريدُ الإلكترونيُّ والهاتفُ والتاريخُ والنسبةُ** — قيمُ بياناتٍ صراحةً.
 *   ③ **هويّةُ الفاعلِ داخلَ «…»** — القوسانِ العربيّانِ **ترقيمٌ ضروريٌّ**
 *     لا زخرفة، ولا يُنزعان. وما بينهما يُحجَب عن **فحصِ المصطلحِ التقنيِّ
 *     وحدَه** (‏فهو معرِّفٌ أو بريدٌ من البيانات)، **ولا يُحجَب عن فحصِ
 *     التشكيل**: القوسانِ يُستعملان أيضًا لتوكيدِ عبارةٍ مؤلَّفة، وحجبُهما
 *     كليًّا يُعمي الحاجبَ عن ستّةِ صفوفٍ تُصيَّر في الترويسة.
 *   ④ **ذيلُ العنوانِ المركَّبِ بين قوسين** — وصفُ بلاغٍ أو مبرِّرُ رفضٍ كتبه
 *     صاحبُه، ويُقاس بالعلمِ أنّه الذيلُ لا أيَّ قوسين: قوسانِ في وسطِ الجملةِ
 *     نصُّ نظامٍ (‏«بمفتاح (الوحدة × الفترة)») ومسُّهما واجب.
 *
 * ◆ **والشدّةُ تشكيلٌ** (U+0651): تُنزع مع أخواتِها. والعربيّةُ المكتوبةُ في
 *   الواجهاتِ بلا شكلٍ — «المشغّلون» ⇐ «المشغلون» قراءةٌ قياسيّةٌ لا لبسَ فيها.
 *   أمّا الهمزاتُ (أ إ آ ؤ ئ ء) والتاءُ المربوطةُ والألفُ المقصورةُ **حروفٌ
 *   لا تشكيلٌ** — ولا تُمَسّ.
 *
 * ◆ **والكاشفُ لا يرصد مفرداتِه هو**: هذا الملفُّ وأدواتُ القياسِ ووثائقُ
 *   الحملةِ خارجَ النطاقِ بالبنية (‏_CONTEXT: «أدواتُ القياسِ ووثائقُ الحملةِ
 *   ومخرجاتُ البوّاباتِ ليست واجهةَ أعمال»).
 *
 * ⛔ **ولا عتبةٌ رقميّةٌ هنا**: حدودُ الطولِ تُمرَّر من `repair01_w6_thresholds`
 *   (‏W06 §٥). ودالّةُ الطولِ تأخذ الحدَّ ولا تعرفه.
 * ═══════════════════════════════════════════════════════════════════════════
 */
class UiPurity
{
    /** التشكيلُ والتطويل — نطاقاتُ يونيكود لا حروفٌ مفردة. */
    public const RE_DIACRITIC = '/[\x{0610}-\x{061A}\x{064B}-\x{065F}\x{0670}\x{06D6}-\x{06ED}\x{0640}]/u';

    /**
     * الزخرفةُ والأسهم. **والقوسانِ العربيّانِ «» ليسا منها** — هما حدُّ هويّةِ
     * الفاعلِ الذي يقرؤه القناع، ونزعُهما يمحو الحدَّ نفسَه.
     */
    public const RE_DECOR = '/[\x{2190}-\x{21FF}\x{2500}-\x{257F}\x{25A0}-\x{25FF}\x{2600}-\x{27BF}'
                          . '\x{2022}\x{00B7}\x{2014}\x{2013}\x{00AC}]/u';

    /**
     * ⛔ **النقطتانِ في اسمِ عنصر** — ممنوعةٌ بالقاعدة ③ بمثالٍ حرفيّ
     * («حالة الطلب: معتمد» غيرُ مناسب). وأُضيفت إلى الكواشفِ في الجولةِ
     * الثانية (‏W06 §٤-٤) لأنَّ **الجولةَ الأولى هي التي أدخلتها**: كانت
     * `stripDecoration` تحوّل الشرطةَ ` — ` إلى `: ` فولّدت ٣٩٨ اسمًا
     * مخالفًا، والبوّابةُ عمياءُ عنها لأنَّ الكاشفَ لم يكن يعرفها.
     *
     * ◆ **والمحميُّ يُستثنى بالبنيةِ لا بالنيّة**: الوقتُ (`14:30`) وعنوانُ
     *   المسارِ (`https://`) نقطتاهما **قيمةُ بياناتٍ** لا ترقيمُ اسم
     *   (‏البند ١٩) — فتُحجَبانِ قبل الفحص.
     */
    public const RE_TIME_OR_URL = '/\d{1,2}:\d{2}|[A-Za-z][A-Za-z0-9+.-]*:\/\//u';
    public const RE_NAME_COLON  = '/[:\x{FF1A}]/u';

    /** المعادلةُ وقاعدةُ الاشتقاق — رياضيّاتٌ ظاهرةٌ في نصِّ أعمال. */
    public const RE_EQUATION = '/[=\x{00D7}\x{2212}\x{2211}\x{00F7}\x{2260}\x{2264}\x{2265}]|\bSUM\b|\bCOUNT\s*\(/u';

    /**
     * كودُ أعمالٍ: `REQ-000278` · `AR-26Q3` · `DEC-M4-11` · `EV-1204`.
     * ◆ **واللاحقةُ قد تكون عربيّة** (`DEC-تتبع` مقيسٌ حيًّا في بندِ عمل):
     *   حصرُها في اللاتينيِّ يترك البادئةَ `DEC` مكشوفةً فتُعَدُّ «لفظًا
     *   لاتينيًّا» — **وهي نصفُ كودٍ لا مصطلحٌ تقنيّ**.
     */
    public const RE_BUSINESS_CODE = '/\b[A-Z]{2,4}-[\p{L}\p{N}]+(?:-[\p{L}\p{N}]+)*/u';

    /** بريدٌ إلكترونيّ — قيمةُ بياناتٍ صراحةً (‏البند ١٩). */
    public const RE_EMAIL = '/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/u';

    /** نصُّ مستخدمٍ منقولٌ بين قوسَينِ عربيَّين. */
    public const RE_QUOTED = '/\x{00AB}[^\x{00BB}]*\x{00BB}/u';

    /**
     * المصطلحاتُ التقنيّةُ الممنوعةُ في نصٍّ مُصيَّر (‏W06 §٤-٨ ②).
     * الرسوُّ على الكلمةِ الكاملةِ لا على المقطع.
     */
    public static function techPatterns()
    {
        return array(
            'PK'              => '/\bPK\b/u',
            'FK'              => '/\bFK\b/u',
            'Grain'           => '/\bGrain\b/iu',
            'Derived'         => '/\bDERIVED\b/iu',
            'Source of Truth' => '/\bSource\s+of\s+Truth\b/iu',
            'Migration'       => '/\bMigrations?\b/iu',
            'SQL'             => '/\bSQL\b/u',
            'API'             => '/\bAPI\b/u',
            'Rule ID'         => '/\bRule[\s_]?ID\b/iu',
            'Event Code'      => '/\bEvent[\s_]?Code\b/iu',
            'ENUM'            => '/\bENUM\b/u',
            'JOIN'            => '/\bJOIN\b/u',
            'صنف أو خدمة'     => '/[A-Za-z][A-Za-z0-9]*::[A-Za-z]/u',
            'ملف شيفرة'       => '/[A-Za-z0-9_\/-]+\.(?:php|js|css|sql)\b/iu',
            /* رمزٌ داخليٌّ خامّ (`NEEDS_SOURCE`) واسمُ جدولٍ (`asset_intake`)
               ورمزُ حدثٍ (`fleet.asset.exited`) — ثمَّ **أيُّ لفظٍ لاتينيٍّ
               حرٍّ** في نصٍّ عربيٍّ مُصيَّر: `مسار movement` رمزٌ تقنيٌّ ظاهرٌ
               وإن لم يحمل شرطةً ولا نقطة. والأكوادُ والبريدُ محجوبةٌ قبلَه. */
            'رمز أو لفظ لاتيني' => '/[A-Za-z]{2,}/u',
        );
    }

    /**
     * حجبُ ما لا يُمَسّ قبل أيِّ فحص — الثلاثةُ (‏البنود ١٩ · ٢٠ · ٢١).
     *
     * ◆ **والقوسانِ العربيّانِ يحجبان الهويّةَ لا العبارة**: مسحُ الحيِّ يجد
     *   لهما استعمالَين لا واحدًا —
     *   ① **هويّةُ فاعلٍ مُقحَمةٌ من البيانات**: «‏fin.deptmgr@equipation.sd» ·
     *     «‏u13_render» · «‏مدير المنجم MB1» — قيمُ بياناتٍ (البند ١٩).
     *   ② **عبارةٌ مؤلَّفةٌ للتوكيد**: «يرى ولا يمنع» · «يمنع ويسمح بقرارٍ
     *     موثَّق» — **نصُّ نظامٍ يخضع للقاعدةِ الدستوريّةِ كاملًا**.
     *   وحجبُهما كليًّا يجعل الحاجبَ أعمى عن الثاني (‏قِيس: **ستّةُ صفوفٍ
     *   مشكولةٍ تُصيَّر في ترويسةِ الشاشةِ ويقرؤها الحاجبُ صفرًا**).
     *   فالحجبُ **مقصورٌ على فحصِ المصطلحِ التقنيّ**: ما بين القوسَين إن كان
     *   لاتينيًّا فهو معرّفٌ من البيانات، وإن كان عربيًّا مشكولًا فهو تأليفٌ
     *   يُنقّى. و`$forTech` هو هذا الفرق.
     *
     * @param string $s
     * @param bool   $compositeTail هل النصُّ عنوانٌ مركَّبٌ ذيلُه نصُّ مستخدم؟
     * @param bool   $forTech       هل الفحصُ عن مصطلحٍ تقنيٍّ (فيُحجَب المقتبَس)؟
     */
    public static function maskProtected($s, $compositeTail = false, $forTech = false)
    {
        $s = (string) $s;
        if ($compositeTail) {
            list($gen, $user) = self::splitUserText($s);
            if ($user !== '') { $s = $gen; }
        }
        if ($forTech) { $s = preg_replace(self::RE_QUOTED, ' ', $s); }
        $s = preg_replace(self::RE_EMAIL, ' ', $s);
        $s = preg_replace(self::RE_BUSINESS_CODE, ' ', $s);
        /* FINAL_CLOSE ⑰ — «هـ» الترتيبيّةُ (هاءٌ + تطويل) حرفُ تعدادٍ عربيٌّ
           قائمٌ بذاتِه (أ·ب·ج·د·هـ·و) لا زخرفة: التطويلُ فيها جزءُ رسمِ
           الحرفِ المفردِ، ونزعُه يقلبها ضميرًا. تُحجَب ككلمةٍ مفردةٍ فقط. */
        $s = preg_replace('~(?<![\x{0621}-\x{064A}])\x{0647}\x{0640}(?![\x{0621}-\x{064A}\x{0640}])~u', 'ه', $s);
        return $s;
    }

    /** هل يحمل النصُّ المولَّدُ تشكيلًا أو تطويلًا؟ (بعد حجبِ ما لا يُمَسّ) */
    public static function hasDiacritics($s, $compositeTail = false)
    {
        return preg_match(self::RE_DIACRITIC, self::maskProtected($s, $compositeTail)) === 1;
    }

    /** نزعُ التشكيلِ والتطويل — والحروفُ كما هي. */
    public static function stripDiacritics($s)
    {
        return preg_replace(self::RE_DIACRITIC, '', (string) $s);
    }

    /**
     * هل يحمل النصُّ المولَّدُ زخرفةً أو سهمًا — **أو نقطتَين**؟
     * ◆ **والنقطتانِ أُضيفتا في الجولةِ الثانية** (‏W06 §٤-٤): «وأضِفْ `:` إلى
     *   كواشفِ الزخرفةِ وإلّا بقيت البوّابةُ عمياءَ عن مخالفتِها» — وهي مخالفةٌ
     *   **أدخلَتها الجولةُ الأولى بنفسِها** حين حوّلت الشرطةَ إليها.
     */
    public static function hasDecoration($s, $compositeTail = false)
    {
        $probe = self::maskProtected($s, $compositeTail);
        if (preg_match(self::RE_DECOR, $probe) === 1) { return true; }
        return self::hasNameColon($probe);
    }

    /**
     * ⛔ **نقطتانِ في اسمِ عنصر** — والوقتُ والمسارُ محجوبانِ قبل الفحصِ فهما
     * قيمتا بياناتٍ لا ترقيمُ اسم.
     */
    public static function hasNameColon($s)
    {
        $probe = preg_replace(self::RE_TIME_OR_URL, ' ', (string) $s);
        return preg_match(self::RE_NAME_COLON, $probe) === 1;
    }

    /**
     * نزعُ الزخرفة.
     * ═══════════════════════════════════════════════════════════════════════
     * ⛔ **والشرطةُ لا تصير نقطتَين** (‏W06 §٤-٤ — تصحيحُ الجولةِ الأولى):
     *   كان هذا السطرُ يحوّل ` — ` إلى `: ` بحجّةِ أنّها «ترقيمٌ ضروريٌّ يفصل
     *   التصنيفَ عن فرعِه» — **والقاعدةُ ③ تمنع النقطتَينِ في أسماءِ العناصرِ
     *   بمثالٍ حرفيّ**. فولّدت الجولةُ الأولى ٣٩٨ اسمًا مخالفًا وهي تظنُّ
     *   أنّها تُنقّي. والصوابُ: **الشرطةُ تُحذف أو تُستبدل بمسافة**،
     *   **والاسمُ المركَّبُ يُعاد صوغُه لا يُوصَل بعلامة**
     *   («لوحة الإدارة: النقل» ⇐ «لوحة إدارة النقل») — وإعادةُ الصوغِ قرارُ
     *   لغةٍ يُسجَّل في `repair01_ui_labels` بمفتاحِه لا يُشتقُّ بنمطٍ في أداة.
     */
    public static function stripDecoration($s)
    {
        $s = (string) $s;
        $s = preg_replace('/^\s*[\x{2014}\x{2013}\x{25C6}\x{2022}\x{00B7}\x{25B8}\x{2190}\x{2192}]+\s*/u', '', $s);
        $s = preg_replace('/\s*[\x{2014}\x{2013}\x{25C6}\x{2022}\x{00B7}\x{25B8}\x{2190}\x{2192}]+\s*$/u', '', $s);
        $s = preg_replace('/\s*[\x{2014}\x{2013}]\s*/u', ' ', $s);
        $s = preg_replace('/\s*[\x{00B7}\x{2022}\x{25C6}\x{25B8}\x{25BA}]\s*/u', ' ', $s);
        $s = preg_replace(self::RE_DECOR, ' ', $s);
        return $s;
    }

    /**
     * نزعُ النقطتَين من اسمِ عنصر — **والوقتُ والمسارُ يعودانِ كما كانا**.
     * والحجبُ هنا بديلٌ مؤقّتٌ ثمَّ إرجاعٌ، لا حذفٌ: قيمةُ البياناتِ لا تُمَسّ.
     */
    public static function stripNameColon($s)
    {
        $s = (string) $s;
        $keep = array();
        $s = preg_replace_callback(self::RE_TIME_OR_URL, function ($m) use (&$keep) {
            $keep[] = $m[0];
            return "\x02" . (count($keep) - 1) . "\x03";
        }, $s);
        $s = preg_replace(self::RE_NAME_COLON, ' ', $s);
        return preg_replace_callback('/\x02(\d+)\x03/', function ($m) use ($keep) {
            return isset($keep[(int) $m[1]]) ? $keep[(int) $m[1]] : '';
        }, $s);
    }

    /** هل في النصِّ المولَّدِ معادلةٌ أو قاعدةُ اشتقاقٍ ظاهرة؟ */
    public static function hasEquation($s, $compositeTail = false)
    {
        return preg_match(self::RE_EQUATION, self::maskProtected($s, $compositeTail)) === 1;
    }

    /**
     * المصطلحاتُ التقنيّةُ الظاهرةُ في النصّ — بأسمائها لا بعددِها.
     * @return array<string> أسماءُ الأنماطِ التي طابقت
     */
    public static function techTerms($s, $compositeTail = false)
    {
        $probe = self::maskProtected($s, $compositeTail, true);
        $out = array();
        foreach (self::techPatterns() as $name => $re) {
            if (preg_match($re, $probe)) { $out[] = $name; }
        }
        return $out;
    }

    /** هل في النصِّ مصطلحٌ تقنيٌّ ظاهر؟ */
    public static function hasTechTerm($s, $compositeTail = false)
    {
        return count(self::techTerms($s, $compositeTail)) > 0;
    }

    /**
     * الطولُ الزائد — **والحدُّ يُمرَّر ولا يُعرَف هنا** (‏W06 §٥):
     * يقرؤه المستهلكُ من `repair01_w6_thresholds`.
     */
    public static function tooLong($s, $maxChars)
    {
        $maxChars = (int) $maxChars;
        if ($maxChars <= 0) { return false; }
        return mb_strlen(trim((string) $s), 'UTF-8') > $maxChars;
    }

    /**
     * التنقيةُ الآليّةُ لنصٍّ **يولّده النظام**: تشكيلٌ ← زخرفةٌ ← ترقيمٌ
     * فائضٌ ← مسافاتٌ متتالية. ولا تمسُّ حرفًا عربيًّا ولا رقمًا ولا كودًا
     * ولا لفظًا لاتينيًّا ولا بريدًا.
     *
     * ◆ **وما بين «…» يُنقّى ولا يُستثنى**: القوسانِ يحملان تارةً هويّةَ فاعلٍ
     *   من البيانات (‏لاتينيّةً أو بريدًا — **والتنقيةُ لا تمسُّ أيًّا منهما
     *   أصلًا**) وتارةً عبارةً مؤلَّفةً للتوكيد («يمنع ويسمح بقرارٍ موثَّق»).
     *   واستثناءُ ما بينهما من نزعِ التشكيلِ يترك **ستّةَ صفوفٍ مشكولةٍ
     *   تُصيَّر في ترويسةِ الشاشة** — والحاجبُ يقرؤها صفرًا.
     */
    public static function purifyGenerated($s)
    {
        $s = (string) $s;
        $s = self::stripDiacritics($s);
        $s = self::stripDecoration($s);
        /* ⛔ النقطتانِ تُنزَع لا تُطبَّع (‏W06 §٤-٤) — والوقتُ والمسارُ يُستثنَيان */
        $s = self::stripNameColon($s);
        $s = preg_replace('/[ \t\x{00A0}]+/u', ' ', $s);
        $s = preg_replace('/\s+([،؛,])/u', '$1', $s);
        $s = preg_replace('/^\s*[،؛,]\s*/u', '', $s);
        $s = preg_replace('/\s*[،؛,]\s*$/u', '', $s);
        return trim($s);
    }

    /**
     * فصلُ نصِّ المستخدمِ عن الشقِّ المولَّد: ما بين قوسَي `(` و`)` **في
     * نهايةِ** عنوانٍ مولَّدٍ نصُّ مستخدمٍ منقول (وصفُ بلاغٍ · مبرِّرُ رفض)،
     * ومسُّه خرقٌ للبند ٢٠. والقيدُ «في النهاية» مقصود: قوسانِ في وسطِ الجملةِ
     * نصُّ نظامٍ (‏«بمفتاح (الوحدة × الفترة)») ويُنقّى.
     * @return array{0:string,1:string} [المولَّد, نصُّ المستخدمِ أو '']
     */
    public static function splitUserText($s)
    {
        $s = (string) $s;
        if (preg_match('/^(.*?)\s*\((.*)\)\s*$/us', $s, $m) && trim($m[2]) !== '') {
            return array($m[1], $m[2]);
        }
        return array($s, '');
    }

    /**
     * تنقيةُ عنوانٍ مركَّبٍ يحمل شقًّا مولَّدًا وشقَّ مستخدم: يُنقّى الأوّلُ
     * ويُعاد الثاني حرفًا كما كتبه صاحبُه.
     */
    public static function purifyComposite($s)
    {
        list($gen, $user) = self::splitUserText($s);
        $clean = self::purifyGenerated($gen);
        if ($user === '') { return $clean; }
        return $clean === '' ? '(' . $user . ')' : $clean . ' (' . $user . ')';
    }

    /**
     * ضمُّ أجزاءِ عنوانٍ مولَّدٍ **بلا شرطةِ ربط** (‏W06 §٤-٤): الشرطةُ هي
     * التي جعلت كلَّ فعلٍ في النظامِ يولّد نصًّا مخالفًا. الفراغُ يكفي.
     */
    public static function join($parts)
    {
        $out = array();
        foreach ((array) $parts as $p) {
            $p = trim((string) $p);
            if ($p !== '') { $out[] = $p; }
        }
        return preg_replace('/\s+/u', ' ', trim(implode(' ', $out)));
    }

    /**
     * حكمٌ كاملٌ على نصٍّ مُصيَّر — الأصنافُ الأربعةُ في موضعٍ واحد.
     * @return array{clean:bool, defects:array<string>}
     */
    public static function verdict($s, $maxChars = 0, $compositeTail = false)
    {
        $d = array();
        if (self::hasDiacritics($s, $compositeTail)) { $d[] = 'DIACRITICS'; }
        foreach (self::techTerms($s, $compositeTail) as $t) { $d[] = 'TECH_TERM:' . $t; }
        if (self::hasEquation($s, $compositeTail)) { $d[] = 'EQUATION'; }
        if (self::hasNameColon(self::maskProtected($s, $compositeTail))) { $d[] = 'NAME_COLON'; }
        if (self::tooLong($s, $maxChars)) { $d[] = 'TOO_LONG'; }
        return array('clean' => count($d) === 0, 'defects' => $d);
    }
}
