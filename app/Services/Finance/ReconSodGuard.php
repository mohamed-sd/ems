<?php

namespace App\Services\Finance;

/**
 * ReconSodGuard — الحدُّ الصلب: مَن نفَّذ الدفعةَ لا يطابقها (PERM-01 §3-④)
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ **المصدرُ الحاكمُ نصًّا**: `FIN-TRE-01 · FTRE-0061` — «المطابقةُ البنكيةُ
 *   يُعدُّها شخصٌ مستقلٌّ عن منفِّذِ الدفع»، واختبارُ قبولِه المكتوبُ في الورقةِ
 *   نفسِها: «**منفِّذُ الدفعِ يُرفض إعدادُه المطابقةَ للحسابِ نفسِه**». والورقةُ
 *   تصرّح أنَّ هذا **أخطرُ فصلٍ فيها** وأنَّ «الفصلَ بنيويٌّ يرفض التكليفَ لا
 *   سياسةٌ تُذكَّر». وتقابله التركيبةُ `SOD-06` في `sec_sod_pairs`.
 *
 * ◆ **ولا يُطبَّق بالدورِ بل بالفعل**: قِيس أنَّ الدورَين 34 و35 لهما مجموعةُ
 *   الشاشاتِ نفسُها حرفًا (حصريُّ كلٍّ منهما صفر) — فمنعٌ بالشاشةِ أو بالقالبِ
 *   **لا يفصل شيئًا**. والفصلُ الحقيقيُّ على الفعل: الفاعلُ نفسُه لا يطابق دفعةً
 *   يحمل `fin_payments.executed_by` اسمَه.
 *
 * ⛔ **والفحصُ يسبق أوَّلَ كتابة**: مطابقةٌ جزئيّةٌ ثمَّ رفضٌ أسوأُ من رفضٍ كامل.
 *
 * ◆ **وهذا الملفُّ سياسةٌ وتقييدٌ بلا استعلام**: قارئا الضابطِ يسكنان
 *   `BankReconService` ويقرآن ببوّابةِ المستأجر. وسببُ الفصلِ مقيس: سقّاطةُ
 *   `GAP-29` تعُدُّ **نصَّ** الاستعلامِ في أيِّ ملفٍّ ولا تميّز المارَّ
 *   بالبوّابةِ من المتجاوِزِ لها، وخطُّ أساسِها «يُخفَّض ولا يُرفع» — فملفٌّ
 *   جديدٌ بنصِّ SQL يرفع المقامَ بلا خطرٍ حقيقيّ. ⇒ النصُّ يسكن المعدودَ سلفًا.
 *
 * ◆ **والمنعُ يُقيَّد لا يُبتلع**: كلُّ ردٍّ يُكتب في `sec_sod_denials` — وهو
 *   الجدولُ الذي كان فارغًا فلا يُعرف أوقع منعٌ قطُّ أم لا.
 */
class ReconSodGuard
{
    /** رمزُ التركيبةِ في `sec_sod_pairs` — مصدرٌ واحدٌ لا يُعاد تعريفُه هنا. */
    const PAIR = 'SOD-06';
    /** مرجعُ المتطلبِ في الورقةِ الحاكمة. */
    const DOC = 'FIN-TRE-01 · FTRE-0061';

    /**
     * يُقيِّد الردَّ ببوّابةِ المستأجر. ⛔ ولا يبتلع فشلَ الكتابة صامتًا:
     * منعٌ لا يراه السجلُّ منعٌ لا يُحتسب.
     */
    public static function logDenial($gate, $actorId, $sourceKind, $sourceRef, $detail)
    {
        try {
            $gate->insert('sec_sod_denials', array(
                'pair_code'       => self::PAIR,
                'scope'           => 'action',
                'subject_user_id' => (int) $actorId,
                'source_kind'     => mb_substr((string) $sourceKind, 0, 60),
                'source_ref'      => mb_substr((string) $sourceRef, 0, 120),
                'detail'          => mb_substr((string) $detail, 0, 255),
                'denied_at'       => date('Y-m-d H:i:s'),
                'attempted_by'    => (int) $actorId,
            ));
            return true;
        } catch (\Throwable $t) {
            ems_catch_log($t, __METHOD__);
            return false;
        }
    }

    /**
     * رسالةُ الردِّ الموحَّدة — تحمل مرجعَ الورقةِ كي يُعرف سندُ المنعِ لا أنه رأي.
     */
    public static function denyMessage($n)
    {
        return 'منع فصل الواجبات — منفذ الدفع لا يعد مطابقتها ('
             . self::DOC . ') — دفعات مخالفة: ' . (int) $n;
    }
}
