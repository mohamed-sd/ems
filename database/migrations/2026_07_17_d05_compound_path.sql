-- ═══════════════════════════════════════════════════════════════════════════
-- المسار المركّب (D05 §6.2) — parent_request_id: «كل تفرّعٍ يبقى ابنًا لأصله»
-- ───────────────────────────────────────────────────────────────────────────
-- الطلب الواحد قد يتفرّع (شراءٌ + دفعة مقدّمة + دفعة نهائية) — الفرع طلبٌ
-- كاملٌ برقمه الخادمي يحمل مرجع أصله، فيمشي المدقّق الشجرة في الاتجاهين.
-- قيد FK ذاتيٌّ RESTRICT: لا يُحذف أصلٌ وله فروع (سلامة النسب المالي —
-- «لا يضيع فرعٌ بلا أصلٍ يُسأل عنه»). العمود إلحاقيٌّ NULL — صفر أثرٍ
-- على الصفوف القائمة.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `fin_requests`
  ADD COLUMN `parent_request_id` INT UNSIGNED DEFAULT NULL
    COMMENT 'المسار المركب §6.2: الطلب الأصل الذي تفرّع عنه هذا الطلب — NULL = أصلٌ أو مستقل'
    AFTER `merged_into_id`,
  ADD KEY `ix_req_parent` (`parent_request_id`),
  ADD CONSTRAINT `fk_req_parent` FOREIGN KEY (`parent_request_id`)
    REFERENCES `fin_requests` (`id`);
