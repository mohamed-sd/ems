-- المسألة المرفوعة في ترحيل 2026_07_18_unit_source_of_truth حُسمت بقرار المالك
-- (2026-07-26): القيدُ uq_stage_once كان يمنع مرحلةً أعادت الوحدة (returned)
-- من اعتمادها بعد استكمالها — بينما §8.2 يوجب أن تعود «بسببٍ وبالرقم نفسه»
-- فتُستكمل وتُعاد ضمن الدورة نفسها.
--
-- الحل: كلُّ إعادةٍ تفتح جولةً جديدة (round_no+1) والرقمُ entry_no لا يتغيّر.
-- القيد الفريد يتوسّع بالجولة: قرارٌ واحدٌ لكل مرحلةٍ *في الجولة الواحدة* —
-- فيبقى منعُ التكرار قائمًا داخل الجولة، ويُقرأ تاريخُ كل الجولات كاملًا.
--
-- الجدول فارغ (صفر صفوف مقيسة قبل الترحيل) فلا ردمَ ولا خطرَ بيانات.
-- التطبيق عبر database/migrate.php حصرًا بعميل utf8mb4.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `unit_approvals`
  ADD COLUMN `round_no` SMALLINT UNSIGNED NOT NULL DEFAULT 1
    COMMENT 'جولة السلسلة — كل إعادةٍ تفتح جولةً جديدة (UX-03 §8.2)'
    AFTER `entry_id`,
  DROP KEY `uq_stage_once`,
  ADD UNIQUE KEY `uq_stage_once_per_round`
    (`company_id`,`entry_id`,`round_no`,`stage`)
    COMMENT 'قرارٌ واحدٌ لكل مرحلةٍ في الجولة';

-- عدّاد الجولة الجارية على الواقعة نفسها: يبدأ 1 ويزيد مع كل ReturnedToSite —
-- فتعرف الخدمةُ الجولةَ الحالية بلا MAX() تحت سباق.
ALTER TABLE `unit_entries`
  ADD COLUMN `current_round` SMALLINT UNSIGNED NOT NULL DEFAULT 1
    COMMENT 'الجولة الجارية — تزيد مع كل إعادةٍ للموقع (UX-03 §8.2)'
    AFTER `revision_no`;
