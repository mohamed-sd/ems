-- **گوتشا مقيسةٌ باختبار القبول**: `UNIQUE` في MySQL **لا يرى NULL مكررًا**،
-- فشرطٌ على مستوى العقد كلِّه (`contract_item_id = NULL`) كان يُكتب مرتين
-- وثلاثًا بلا 409 — والمفتاحُ الفريد زخرفةٌ في أشيع الحالات.
-- فـ«كلُّ البنود» تصير **صفرًا صريحًا**: قيمةٌ يراها المفتاحُ ويرفض تكرارَها.
-- (لا FK على العمود فالصفرُ سليمٌ بنيويًّا، والدلالةُ مكتوبةٌ في COMMENT.)
-- ═══════════════════════════════════════════════════════════════════════════

