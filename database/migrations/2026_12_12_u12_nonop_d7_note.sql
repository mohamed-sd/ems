-- ───────────────────────────────────────────────────────────────────────────
-- الهجرةُ السابقةُ (2026_12_11) كتبت استثناءَ D7 لثلاثةٍ من طبقةِ 42 (4201 ·
-- 4203 · 4204) وأغفلت 4202 «إيراداتُ الجزاءاتِ المحصَّلة» لأنها عولجت في
-- بندِ الجزاءاتِ فأخذت D8 ونُسي إعلانُ استثنائها من D7.
--
-- والحكمُ نفسُه يسري: الجزاءُ المحصَّلُ إيرادٌ غيرُ تشغيليٍّ لا نموذجَ عملٍ
-- خلفَه — يحمل عقدَه (D8) وطرفَه (D6) ولا يحمل ساعةً ولا طنًّا ولا مترًا.
-- والاستثناءُ يُكتب ليكون قرارًا ظاهرًا يُراجَع، لا فجوةً تُكتشف لاحقًا.
--
-- عكسُه: نزعُ العبارةِ من حقلِ coa_note للحساب 4202.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE fin_chart_of_accounts
   SET coa_note = CONCAT(COALESCE(coa_note, ''),
        CASE WHEN COALESCE(coa_note, '') = '' THEN '' ELSE ' · ' END,
        'استثناءٌ معلَن: D7 نموذجُ العمل لا يلزم هذا الحساب — إيرادٌ غيرُ تشغيليٍّ لا نموذجَ عملٍ خلفَه (قرارُ update0012)')
 WHERE is_canonical = 1
   AND code = '4202'
   AND COALESCE(coa_note, '') NOT LIKE '%استثناءٌ معلَن: D7%';
