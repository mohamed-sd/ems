-- ───────────────────────────────────────────────────────────────────────────
-- تكملةُ 2026_11_27: معيارُ التاريخ وحدَه لم يلتقط كلَّ القوالب الدخيلة،
-- وصفوفٌ أُغلقت قبل الإصلاح تركت مساراتٍ معلَّقة. بياناتٌ فقط · لا حذف.
-- ═══════════════════════════════════════════════════════════════════════════

-- ① بقيّةُ القوالب الدورية الدخيلة — الرابطُ موضوعيٌّ لا اسميّ
--    القوالبُ وسياساتُ المهلة دخلت في دفعةِ استيرادٍ واحدة، فحملت الأسماءَ
--    نفسَها. ما طابق اسمُه سياسةً عُطِّلت لتساوي استجابتِها وإنجازِها فهو من
--    الدفعة نفسها. القالبُ التشغيليُّ الحقيقي لا يطابق شيئًا فيبقى فعّالًا.
UPDATE ticket_recurrence_templates r
   SET r.active = 0
 WHERE r.active = 1
   AND EXISTS (SELECT 1 FROM ticket_sla_policies p
                WHERE p.active = 0
                  AND p.response_hours >= p.resolution_hours
                  AND p.name = r.name);

-- ② مصالحةُ الصفوف المُقفلة قبل الإصلاح
--    بلاغٌ ملغًى أو مغلقٌ ومسارُه ما زال مفتوحًا = نموذجان متناقضان على صفٍّ
--    واحد. الإغلاقُ التاريخي فعلُ إنسانٍ يُحترم، فتُقفَل المساراتُ المعلَّقة
--    إداريًّا (لا تُحذف) ليتّسق الرأسُ مع تنفيذه — وهو عينُ ما يفعله الإلغاءُ
--    الآن في الشيفرة.
UPDATE ticket_workstreams w
   JOIN tickets t ON t.id = w.tk_id
    SET w.state = 'admin_closed',
        w.closed_at = COALESCE(w.closed_at, NOW())
 WHERE t.stage IN ('closed', 'cancelled')
   AND w.state NOT IN ('closed', 'admin_closed');

UPDATE tickets
   SET head_state = 'closed'
 WHERE stage IN ('closed', 'cancelled')
   AND head_state = 'open';
