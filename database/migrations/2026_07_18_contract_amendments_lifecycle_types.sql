-- قرار المستخدم: «الأوامر مصدر الحقيقة، والملاحق إسقاطٌ منها». كل إجراءٍ ماديّ
-- في `Contracts/contract_actions_handler.php` (تجديد/تسوية/إيقاف/استئناف/إنهاء/
-- دمج/انتهاء) يولّد صفَّ ملحقٍ مبنينًا داخل معاملته نفسها. وشاشة الملاحق تتحوّل
-- إلى دفترٍ يُقرأ (لا CRUD يدويّ).
--
-- هذا الترحيل يوسّع ENUM النوع بأنواع دورة الحياة الخمسة الناقصة حتى يستوعب
-- كلَّ إجراءٍ ماديّ (اختيار المستخدم: «كل الأحداث المادّية» تدخل السجلّ):
--   إيقاف · استئناف · إنهاء · انتهاء · دمج
-- الأنواع السبعة الأصلية تبقى كما هي (لا تُمَسّ الصفوف الستّة التاريخية).
--
-- التراجع: ALTER ... MODIFY amend_type ENUM(<الأنواع السبعة الأصلية>) — بشرط عدم
--          وجود صفوفٍ تحمل نوعًا من الخمسة الجديدة (وإلا تتحوّل صامتةً إلى '').
-- idempotent: MODIFY يضبط التعريف إلى الحالة المقصودة؛ إعادةُ التطبيق لا أثر لها.
-- الترميز: يُطبَّق عبر database/migrate.php حصرًا (يفرض utf8mb4 — لا تشوّه للعربية).
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `contract_amendments`
    MODIFY `amend_type`
    ENUM(
        'تجديد',
        'تمديد',
        'زيادة نطاق',
        'تخفيض نطاق',
        'تغيير أسعار',
        'إضافة معدات',
        'إضافة خدمات',
        'إيقاف',
        'استئناف',
        'إنهاء',
        'انتهاء',
        'دمج'
    ) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
    NOT NULL DEFAULT 'تجديد';
