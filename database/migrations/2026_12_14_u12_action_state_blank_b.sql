-- إتمامُ 2026_12_13 — الحارسُ الصحيحُ للحياة: وحدةُ الصلاحياتِ لا خريطةُ الملفات
-- ───────────────────────────────────────────────────────────────────────────
-- الهجرةُ السابقةُ لم تُصِب صفًّا واحدًا: شرطُها كان وجودَ الملفِّ في
-- `nav09_file_map`، وملفاتُ مساحةِ المخاطرِ ليست فيها — ولا يلزم أن تكون.
--
-- فخريطةُ الملفاتِ عقدُ **ترجمةٍ** بين اسمٍ قانونيٍّ في الوثيقةِ ومسارٍ مختلفٍ
-- على القرص (`invoices.php` ⇐ `Finance/invoices_fin.php`). وشاشاتُ المخاطرِ
-- اسمُها في الوثيقةِ هو مسارُها نفسُه، فلا ترجمةَ تلزمها ولا صفَّ لها هناك.
-- واشتراطُ حضورِها في جدولِ ترجمةٍ لا تحتاجه شرطٌ لا يصفُ الحياةَ بل يصف
-- بنيةً أخرى — ولذلك لم يُطابق شيئًا (والأخواتُ الثمانِ والعشرون المربوطاتُ
-- سلفًا لا تجتزنه هي الأخرى).
--
-- الحارسُ الصحيحُ للحياة: **وحدةُ صلاحياتٍ مسجَّلةٌ** في `modules` — فهي بابُ
-- المنعِ والسماحِ ولا تُسجَّل إلا لوجهةٍ قائمة.
--
-- عكسُه: UPDATE nav09_action_map SET state = '' للرموزِ الاثني عشرَ.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE nav09_action_map am
  JOIN modules mo ON mo.code = am.canonical_file
   SET am.state = 'bound_page',
       am.updated_at = NOW()
 WHERE (am.state = '' OR am.state IS NULL)
   AND am.canonical_file LIKE 'Risk/%';
