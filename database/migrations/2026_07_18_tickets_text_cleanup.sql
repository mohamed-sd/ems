-- وحدة البلاغات — تنقيح النصوص المخزَّنة المعروضة للمستخدم
--
-- الغرض: ألّا يقرأ المستخدمُ في الشاشات مصطلحاتٍ داخليّةً أو إشاراتٍ إلى
-- أنظمةٍ سابقة. النصوص هنا تظهر فعليًّا في خطّ زمن التذكرة وفي قوائم الوحدات،
-- فتُصاغ صياغةً محايدةً موجزة تحفظ المعلومة وتُسقط ما لا يعني المستخدم.
--
-- ① أجساد أحداث السجلّات المنقولة: يُكتفى بالرقم المرجعي السابق.
-- ② أسماء الوحدات في القوائم: تسمياتٌ مباشرةٌ بلا وصفٍ لحالة التحوّل.
-- idempotent: التحديثات مشروطةٌ بالنص القديم، فإعادةُ التطبيق بلا أثر.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── ① خطّ الزمن: نصّ حدث السجلّات المنقولة ──────────────────────────────────
UPDATE ticket_events
   SET body = REPLACE(body, 'مُرحَّل من نظام البلاغات القديم — الكود الأصلي: ',
                            'الرقم المرجعي السابق: ')
 WHERE body LIKE 'مُرحَّل من نظام البلاغات القديم%';

-- ── ② تسميات الوحدات في قوائم الصلاحيات والتنقّل ────────────────────────────
UPDATE `modules`
   SET `name` = 'البلاغات (غير مفعّلة)'
 WHERE `id` = 42 AND `name` <> 'البلاغات (غير مفعّلة)';

UPDATE `modules` SET `name` = 'البلاغات'          WHERE `id` = 132 AND `name` <> 'البلاغات';
UPDATE `modules` SET `name` = 'لوحة متابعة البلاغات' WHERE `id` = 137 AND `name` <> 'لوحة متابعة البلاغات';

