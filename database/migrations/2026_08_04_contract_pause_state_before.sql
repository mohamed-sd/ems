-- H-02 (تتمّة) · حفظُ ما قبل التعليق — 2026-07-29
-- ───────────────────────────────────────────────────────────────────────────
-- «أي مرحلة → معلَّق … **ويعود الكلُّ بالاستئناف**» (OPM-01 §3). والعودةُ إلى
-- **حيث كان** لا إلى حالةٍ مفترَضة: عقدٌ عُلّق وهو «قيد التنفيذ» لا يعود «نافذًا»
-- — ذلك يُسقط تقدّمَه صامتًا ويُعيد فتحَ بابٍ أُغلق.
--
-- ولذلك تُحفظ الحالةُ السابقةُ عند التعليق وتُقرأ عند الاستئناف. وبدونه كان
-- الاستئنافُ **تخمينًا** — وهو ما ترفضه قاعدةُ عدم التلفيق.
--
-- والعقدان المعلَّقان اليوم (6 · 9) عُلّقا **قبل** هذه الآلة فلا حالةَ محفوظةً
-- لهما: تُترك NULL عمدًا، و`resume()` تردّ بـ422 تطلب نقلًا يدويًّا بقرارٍ
-- موثَّق — **إعلانُ الجهل أصدقُ من اختراع مرجع**.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `contracts`
  ADD COLUMN `pause_state_before`
    ENUM('مسودة','تفاوض','معتمد','موقَّع','نافذ','قيد التنفيذ',
         'معلَّق','معدَّل','مجدَّد','منتهٍ','مقفل','مصفّى')
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
    DEFAULT NULL
    COMMENT 'H-02: الحالةُ قبل التعليق — يعود إليها بالاستئناف. NULL = عُلّق قبل الآلة فلا يُخمَّن'
    AFTER `contract_status`;
