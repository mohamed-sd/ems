-- ENT-01 §8-Validation يفرّق بينهما نصًّا:
--   «عقدٌ غيرُ نافذٍ بالفترة → **يُستبعد بسببٍ مكتوب**»
--   «لقطةٌ مفقودةٌ → **Blocked** لا احتسابَ افتراضيًّا»
-- فالأولُ ليس عطبًا: عقدُ مسودةٍ خارج نطاق الدورة أصلًا — يُكتب سببُه ولا
-- يُوقف الدورة. والثاني عطبٌ حقيقيٌّ يُوقفها حتى يُعالَج.
-- ودمجُهما (كما كان) يجعل كلَّ دورةٍ Blocked لمجرد وجود مسودةٍ في السجل.
-- الجدولُ فارغٌ عمليًّا (بُني قبل دقائق) — ولا صفَّ حيًّا يُمسّ.
