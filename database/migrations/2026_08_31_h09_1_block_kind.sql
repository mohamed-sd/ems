ALTER TABLE `payroll_run_blocks`
  ADD COLUMN `kind` ENUM('excluded','blocked') NOT NULL DEFAULT 'blocked'
    COMMENT 'excluded = خارج النطاق بسببٍ مكتوب · blocked = عطبٌ يوقف الدورة'
    AFTER `person_id`;

UPDATE `payroll_run_blocks` SET `kind` = 'excluded' WHERE `block_code` = 'contract_not_readable';
