-- ── إعادة حساب مؤشر العقد لكل عقود الشركة (§6.6): 0 بنود=لم يبدأ · الكل مجتاز=مجتاز · غير ذلك=جارٍ ──
UPDATE `contracts` c SET c.`readiness_state` = (
  CASE
    WHEN NOT EXISTS (SELECT 1 FROM `readiness_lines` r WHERE r.`contract_ref` = c.`id` AND r.`is_deleted` = 0) THEN 'لم يبدأ'
    WHEN NOT EXISTS (SELECT 1 FROM `readiness_lines` r WHERE r.`contract_ref` = c.`id` AND r.`is_deleted` = 0 AND r.`state` <> 'مجتاز') THEN 'مجتاز'
    ELSE 'جارٍ'
  END
) WHERE c.`company_id` = 4;

