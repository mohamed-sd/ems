-- تصحيح توجيه بوابة الطلبات: المراجع = المدير حيث دورُ المراجع غير مأهول
-- ───────────────────────────────────────────────────────────────────────────
-- قرار المستخدم 2026-07-18: «وجود مدير الإدارة يغني عن المشرف — والمشرف
-- يُنشأ يوم يُحتاج إليه». ثلاث إداراتٍ كان مراجعُها دورَ مشرفٍ بلا مستخدمين
-- (فمرحلة المراجعة غير مأهولة والبيانات تخالف الواقع):
--   الموردون: 8 (مشرف موردين) ← 2 (ادارة الموردين)
--   الصيانة:  14 (مشرف صيانة) ← 13 (ادارة الصيانة)
--   الأسطول:  10 (مشرف اسطول) ← 3 (ادارة الاسطول)
--
-- الحارس: التعديل مشروطٌ بخلوّ دور المراجع الحالي من مستخدمين نشطين في
-- الشركة نفسها — فلو عُيّن مشرفٌ قبل تطبيق هذا الملف في بيئةٍ ما، صفُّه
-- لا يُمَسّ. عاطل التكرار (الشرط لا يتحقق بعد أول تطبيق).
--
-- لا يمسّ: الإدارات الثماني الأخرى · فصل الواجبات المالي (fin_can_perform —
-- كودٌ منفصل لا علاقة له بهذا الجدول) · أي صلاحية شاشة.
-- التراجع: UPDATE عكسي بنفس الأزواج من شاشة «توجيه الإدارات».
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE fin_request_routing rt
SET rt.reviewer_role_id = rt.manager_role_id
WHERE rt.source_module IN ('suppliers', 'maintenance', 'assets')
  AND rt.reviewer_role_id IN (8, 14, 10)
  AND rt.reviewer_role_id <> rt.manager_role_id
  AND NOT EXISTS (
      SELECT 1 FROM users u
      WHERE u.role = rt.reviewer_role_id
        AND u.company_id = rt.company_id
        AND u.status = 'active'
  );
