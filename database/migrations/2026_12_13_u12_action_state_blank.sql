-- اثنا عشرَ فعلًا بحالةٍ فارغةٍ — ENUM ابتلع '' صامتًا
-- ───────────────────────────────────────────────────────────────────────────
-- كشفت الهندسةُ العكسيةُ اثني عشرَ صفًّا في `nav09_action_map` حالتُها نصٌّ
-- فارغٌ لا قيمةٌ من قيمِ الـENUM الأربع. والسببُ الگوتشا المعروفةُ في هذه
-- الحوزة: **ENUM يقبل '' صامتًا** حين يُمرَّر نصٌّ فارغٌ بدل NULL — فالإدراجُ
-- ينجح والحالةُ تضيع.
--
-- والأثرُ ليس شكليًّا: كلُّ عدٍّ يفرز بالحالةِ يُسقط هذه الاثني عشر — فتبدو
-- أفعالٌ مبنيةٌ وكأنها غيرُ موجودة، ويُقاس تقدّمُ M-16 أقلَّ من حقيقته.
--
-- والاثنا عشرَ مبنيةٌ فعلًا — قيس ذلك لا ادُّعي:
--   · تسعةٌ لها مُرسِلٌ حيٌّ في `Risk/risk_actions.php`:
--       appetite_set · control_fail · field_sync · gov_attest · incident_log
--       kri_threshold · report_export · risk_review · taxonomy_define
--   · وثلاثةٌ قراءةٌ خالصة (write_class=read_only) تخدمها صفحتُها نفسُها بلا
--     مُرسِل: GOV-RSK-VIEW · RSK-VIEW-COMMITTEE · RSK-VIEW-FIELD
--   · وملفاتُ الأربعِ كلِّها حيةٌ على القرص.
--
-- فحالتُها الصحيحةُ `bound_page` — كأخواتِها الثمانِ والعشرين في المساحةِ نفسِها.
--
-- ◆ الحارسُ: لا يُصحَّح إلا صفٌّ ملفُّه مسجَّلٌ حيًّا في `nav09_file_map` —
--   فلا تُرقَّى حالةُ فعلٍ لا شاشةَ له.
--
-- عكسُه: UPDATE nav09_action_map SET state = '' للرموزِ الاثني عشرَ أدناه.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE nav09_action_map am
  JOIN nav09_file_map fm
    ON fm.real_path = am.canonical_file
   AND fm.state = 'live'
   SET am.state = 'bound_page',
       am.updated_at = NOW()
 WHERE (am.state = '' OR am.state IS NULL)
   AND am.canonical_file LIKE 'Risk/%';
