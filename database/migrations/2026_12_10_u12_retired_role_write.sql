-- ───────────────────────────────────────────────────────────────────────────
-- الخرقُ الأخيرُ في AC-GOV-02: الدورُ 5 «إدارة الموقع (قديم — مدمج في 6)» يملك
-- حقَّ إضافةٍ على `Risk/risk_field.php` بلا بابٍ يقود إليها.
--
-- وحالُ الدورِ يحسم العلاج: صفرُ مستخدمٍ عليه · صفرُ عنصرِ تنقّلٍ له · واسمُه
-- يعلن تقاعدَه («مدمج في 6»). ففتحُ بابٍ لدورٍ متقاعدٍ إحياءٌ لا تصحيح — والحقُّ
-- الذي لا بابَ له ولا حاملَ يبقى سطحَ هجومٍ صامتًا إن أُحيي الدورُ يومًا.
-- فالعلاجُ خفضُ الحقِّ إلى قراءةٍ لا فتحُ باب.
--
-- ولا يُحذف الدورُ ولا صفُّ صلاحيتِه: التقاعدُ يُوصف ولا يُمحى — فسجلاتُ
-- الماضي تشير إليه، ومحوُه يقطع أثرَها.
--
-- عكسُه: UPDATE role_permissions ... SET can_add = 1 للدور 5 على الشاشة نفسِها.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE role_permissions rp
  JOIN modules mo ON mo.id = rp.module_id
   SET rp.can_add = 0, rp.can_edit = 0, rp.can_delete = 0
 WHERE mo.code LIKE 'Risk/%'
   AND rp.role_id = 5
   AND (rp.can_add = 1 OR rp.can_edit = 1 OR rp.can_delete = 1);
