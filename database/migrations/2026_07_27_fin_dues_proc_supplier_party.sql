-- نوعُ طرفٍ ثالثٌ في الذمّة: مورد المشتريات — 2026-07-27
-- ───────────────────────────────────────────────────────────────────────────
-- **قرار المالك (نصُّه)**: «المشترياتُ تتعامل مع `proc_supplier` بينما التايم شيت
-- وساعاتُ الاستحقاق تتعامل مع `suppliers`» — فالجدولان مجالان مختلفان لا خطأٌ
-- يُدمج. ويوافقه UX-09 §5.3: «موطنُهم الأصلي هنا حصرًا … لا حاوياتِ وحداتٍ ولا
-- اعتمادَ تايم شيت»، وFES-01 §4.1: مورد المشتريات طرفُ supplier **بمصدرٍ شرائي**.
--
-- **الخطرُ المقيس قبل هذا الفصل**: `fin_dues.party_ref` يشير إلى `suppliers`،
-- والمعرّفاتُ متصادمة — المورد رقم 3 هو «الوطنية للفلاتر» في المشتريات و«إيكوبيشن»
-- في المالية. فنسبةُ دَينِ فاتورةٍ شرائيةٍ بالرقم وحده كانت ستُقيّده **على شركةٍ
-- أخرى** بلا أي خطأٍ ظاهر. القيمةُ الثالثة تمنع ذلك بنيويًّا.
--
-- إضافيٌّ محض: القيمتان القائمتان لا تُمسّان وصفوفُهما كما هي.
-- الرجوع: إعادةُ الـENUM إلى قيمتيه بعد إفراغ صفوف proc_supplier.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `fin_dues`
  MODIFY COLUMN `party_type` ENUM('supplier','employee','proc_supplier') NOT NULL
  COMMENT 'supplier=مورد الآليات (suppliers) · employee=عامل · proc_supplier=مورد المشتريات (proc_supplier) — سجلّان مختلفان لا يُخلطان';
