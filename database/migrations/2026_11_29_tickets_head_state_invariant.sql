-- ثابتُ head_state — تعريفٌ واحدٌ لـ«المفتوح» عبر النظام
-- ───────────────────────────────────────────────────────────────────────────
-- «المفتوحُ ما لم يُغلق ولم يُلغَ». المرحلةُ `done` (منجَزٌ بانتظار التأكيد)
-- **مفتوحةٌ** — العملُ انتهى والمركزُ لم يُقفل بعد، فهي في عهدته.
-- الشارةُ واللوحةُ وبطاقاتُ القائمة تتبع هذا التعريف نفسه، وهذا الترحيلُ
-- يُلحق `head_state` به فلا يبقى صفٌّ يقول «مغلقٌ» ومرحلتُه تقول غير ذلك.
-- الترحيل السابق استثنى `done` تحوّطًا فبقي صفٌّ خارجَ الثابت.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE tickets
   SET head_state = 'open'
 WHERE head_state = 'closed'
   AND stage NOT IN ('closed', 'cancelled');
