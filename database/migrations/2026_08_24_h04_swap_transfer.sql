-- ───────────────────────────────────────────────────────────────────────────
-- «تُجمَّد حاويةُ المعطلة عند رصيدها وتُفتح حاويةُ البديلة بالمتبقي — بحركة
-- نقلٍ واحدةٍ ذرية». السجلُّ القائم وصفٌ بلا حركة (صفرُ صفٍّ حي — لا بياناتَ
-- تاريخيةً تُمسّ) — يُضاف الرصيدُ المنقولُ ومرجعُ البديلة.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `container_swaps`
  ADD COLUMN `moved_qty` DECIMAL(16,2) NULL DEFAULT NULL
      COMMENT 'الرصيدُ المنقول (متبقي الخارجة) — حركةُ الاستبدال لا وصفُه' AFTER `in_ref`,
  ADD COLUMN `to_container_id` INT UNSIGNED NULL DEFAULT NULL
      COMMENT 'الحاويةُ البديلة (وليدةً أو مفعَّلةً)' AFTER `moved_qty`,
  ADD CONSTRAINT `fk_swap_to_container` FOREIGN KEY (`to_container_id`) REFERENCES `op_containers` (`id`);
