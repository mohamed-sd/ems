-- الجزاءاتُ تحمل عقدَها — إنفاذُ حكمِ D8 كما نصّت الورقة 02
-- ───────────────────────────────────────────────────────────────────────────
-- كشفت الهندسةُ العكسيةُ (tools/u12_reverse_audit.php) مخالفةً لحكمٍ صريح:
-- الورقة 02 «الأبعاد التحليلية» تقول عن **D8 العقد**: «إلزاميٌّ في الإيرادِ
-- **والجزاءات**». وحساباتُ الجزاءاتِ الثلاثةُ في الشجرةِ خرجت تلزم D1 وحدَه:
--
--   2108  الجزاءاتُ والخصوماتُ المستحقةُ على الشركة   (التزام)
--   4202  إيراداتُ الجزاءاتِ المحصَّلة                (إيراد)
--   5116  الجزاءاتُ التعاقديةُ المتحمَّلة             (مصروف — يلزمه D7 ولا D8)
--
-- والأثرُ ليس شكليًّا: جزاءٌ بلا عقدٍ لا يدخل هامشَ عقدِه، فتُحتسب ربحيةُ
-- العقدِ (M2 بالبُعد D8) أعلى من حقيقتها بمقدارِ جزاءاتِه — وهو بالضبط ما
-- تمنعه الوثيقةُ حين تُلزم البُعدَ.
--
-- ◆ ما لا تفعله هذه الهجرةُ عمدًا: لا تفرض D7 «نموذجَ العمل» على حساباتِ
--   الإيرادِ غيرِ التشغيليِّ (42xx: أرباحُ بيعِ الأصولِ · فروقُ العملةِ ·
--   الإيراداتُ المتنوعة). فنموذجُ العملِ (ساعةٌ · طنٌّ · مترٌ) لا معنى له خلفَ
--   فرقِ عملة، وإلزامُه يدفع المستخدمَ لاختيارِ نموذجٍ كاذبٍ ليمرَّ القيد —
--   وقيمةٌ كاذبةٌ في بُعدٍ أسوأُ من بُعدٍ غائب. والاستثناءُ يُكتب في حقلِ
--   الملاحظةِ ليكون قرارًا ظاهرًا لا سكوتًا.
--
-- عكسُه: إعادةُ required_dims للحساباتِ الثلاثةِ إلى قيمها السابقة أدناه.
--   2108 ⇐ 'D1'   ·   4202 ⇐ 'D1'   ·   5116 ⇐ 'D1,D4,D2,D3,D5,D7'
-- ═══════════════════════════════════════════════════════════════════════════

-- ① الجزاءُ المستحقُّ على الشركةِ يحمل عقدَه
UPDATE fin_chart_of_accounts
   SET required_dims = 'D1,D6,D8'
 WHERE is_canonical = 1 AND code = '2108' AND required_dims NOT LIKE '%D8%';

-- ② الجزاءُ المحصَّلُ من الغيرِ يحمل عقدَه وطرفَه
UPDATE fin_chart_of_accounts
   SET required_dims = 'D1,D6,D8'
 WHERE is_canonical = 1 AND code = '4202' AND required_dims NOT LIKE '%D8%';

-- ③ الجزاءُ المتحمَّلُ يضيف العقدَ إلى أبعادِه القائمة
UPDATE fin_chart_of_accounts
   SET required_dims = CONCAT(required_dims, ',D8')
 WHERE is_canonical = 1 AND code = '5116' AND required_dims NOT LIKE '%D8%';

-- ④ الاستثناءُ المعلَن: الإيرادُ غيرُ التشغيليِّ بلا نموذجِ عمل
UPDATE fin_chart_of_accounts
   SET coa_note = CONCAT(COALESCE(coa_note, ''),
        CASE WHEN COALESCE(coa_note, '') = '' THEN '' ELSE ' · ' END,
        'استثناءٌ معلَن: D7 نموذجُ العمل لا يلزم هذا الحساب — إيرادٌ غيرُ تشغيليٍّ لا نموذجَ عملٍ خلفَه (قرارُ update0012)')
 WHERE is_canonical = 1
   AND code IN ('4201', '4203', '4204')
   AND COALESCE(coa_note, '') NOT LIKE '%استثناءٌ معلَن: D7%';
