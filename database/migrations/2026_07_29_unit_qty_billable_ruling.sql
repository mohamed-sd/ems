-- M-24 · البُعدُ الأول: حكمُ الكمية نفسِها — 2026-07-29
-- ───────────────────────────────────────────────────────────────────────────
-- **لماذا عمودٌ على الواقعة لا حكمٌ على السطور** (CON-02 §3-④ · §5):
-- عقدُ الطن/المتر يسجّل **كميةً واحدةً** وسطورَ زمنٍ متعددة. ومصفوفةُ الالتزامات
-- تحكم **السطورَ** (`unit_time_log.billable`) لا الكمية. فالحكمُ بُعدان لا بُعدٌ
-- واحد، ولا يُسحقان في واحد:
--   ① **هل الكميةُ نفسُها مفوترة؟**  ← حكمٌ على **الواقعة** — وهذا العمود.
--      («إعادةُ التنفيذ لعيبٍ لا تُفوتر»: المترُ الذي أُعيد تنفيذُه لا يُدفع مرتين.)
--   ② **هل يُضاف بندُ استعدادٍ منفصل؟** ← حكمٌ على **سطور التوقف** — قائمٌ سلفًا
--      في لقطة الإسناد (`billable` لكل سطر) ولا يحتاج عمودًا.
--
-- ولماذا لم يُوسَّع `revision_kind`: قيمُه (adjustment · reversal · split · merge)
-- تصف **تصحيحَ السجل**، وإعادةُ التنفيذ **عملٌ جديدٌ وقع فعلًا** لا تصحيحُ قيد.
-- خلطُهما يجعل تقاريرَ المراجعة تعدّ عملًا حقيقيًّا تصحيحًا إداريًّا.
--
-- **الافتراضُ NULL = لم يُحكم = مفوترة** — وهو سلوكُ اليوم حرفًا بحرف، فالترحيلُ
-- **صفرُ أثرٍ على العشرين واقعةً القائمة** ولا يُعاد احتساب شيءٍ صامتًا (معيارُ
-- القبول). ولا تصير الكميةُ غيرَ مفوترةٍ إلا بقرارٍ صريحٍ **بسببه المكتوب**.
--
-- `qty_ruling_note` إلزاميٌّ تطبيقيًّا عند `qty_billable = 0`: حكمٌ يمنع مالًا
-- بلا سببٍ مكتوبٍ لا يُدقَّق بعد سنتين.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `unit_entries`
  ADD COLUMN `qty_billable` TINYINT(1) DEFAULT NULL
    COMMENT 'M-24 ①: هل الكميةُ نفسُها مفوترةٌ للعميل؟ NULL=لم يُحكم (مفوترة) · 0=لا (إعادةُ تنفيذٍ لعيب) · 1=نعم صراحةً'
    AFTER `capacity_flag`,
  ADD COLUMN `qty_ruling_note` VARCHAR(200) DEFAULT NULL
    COMMENT 'سببُ الحكم — إلزامٌ عند qty_billable=0'
    AFTER `qty_billable`,
  ADD COLUMN `qty_decided_by` INT UNSIGNED DEFAULT NULL
    COMMENT 'مَن حكم — الحكمُ باسم صاحبه'
    AFTER `qty_ruling_note`,
  ADD COLUMN `qty_decided_at` DATETIME DEFAULT NULL
    AFTER `qty_decided_by`;

-- فهرسُ التقارير: «كم واقعةً حُكم بعدم فوترة كميتها؟» سؤالٌ يُسأل في المطابقة.
ALTER TABLE `unit_entries`
  ADD INDEX `ix_qty_billable` (`company_id`, `qty_billable`);
