-- ═══════════════════════════════════════════════════════════════════════════
-- «لا دفعَ لطرفٍ بلا تسويةٍ معتمدة» — قيدٌ بنيويٌّ لا تذكير — 2026-07-28
-- ───────────────────────────────────────────────────────────────────────────
-- UX-02 §15.4 نصًّا: «الإنفاذُ البنيوي — لا دفعَ بلا تسويةٍ معتمدة: **مرجعُ
-- التسوية إلزاميٌّ في طلب دفع الأطراف (قيدُ NOT NULL لنوعه)**».
--
-- **الفجوةُ المقيسة**: صفّان في `fin_dues` بـ141,600 موسومان «مدفوع» بلا وجود
-- أيِّ تسوية — أي مالٌ خرج ولا مستندَ يسنده. وُسما إرثًا في هجرةٍ سابقة،
-- وهذا القيدُ يمنع تكرارَه بنيويًّا لا بتدريبٍ ولا بتذكير.
--
-- **قرارُ المالك (2026-07-28) — النطاق**: تسري على **دفعات الأطراف وحدها**
-- (`supplier_payment` · `employee_payment` · `settlement`). أمّا `purchase`
-- فسندُه المطابقةُ الثلاثية لا التسوية (UX-09 §8.2) — وإلزامُه بتسويةٍ يعطّل
-- المشترياتِ بلا سبب. **والمقيسُ يؤيّده**: طلباتُ الموردين الثلاثة القائمة
-- (179 · 180 · 183) كلُّها `purchase` — فلا صفَّ واحدٌ يُكسر بهذا القيد.
--
-- **لماذا عمودٌ ومفتاحٌ لا نصٌّ في `source_ref`**: النصُّ يُكتب ويُخطأ ويُحذف
-- مرجعُه؛ والمفتاحُ الأجنبيُّ يضمن أن التسويةَ **موجودةٌ فعلًا** وأنها لا تُحذف
-- ما دام لها دفعة (RESTRICT).
--
-- الرجوع: إسقاطُ القيد ثم المفتاح ثم العمود.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `fin_requests`
  ADD COLUMN `settlement_id` INT NULL
      COMMENT 'التسويةُ المعتمدة التي وُلِّد عنها هذا الطلب — إلزاميٌّ لدفعات الأطراف (UX-02 §15.4)'
      AFTER `source_ref`,
  ADD KEY `ix_req_settlement` (`settlement_id`);

-- `RESTRICT` في الطرفين لا `CASCADE`: **MySQL يمنع قيدَ CHECK على عمودٍ خاضعٍ
-- لإجراءٍ مرجعيٍّ متتالٍ** (خطأ 3823). و`ON UPDATE CASCADE` بلا فائدةٍ هنا أصلًا —
-- `settlements.id` مفتاحٌ تلقائيُّ الترقيم لا يتغيّر أبدًا. فالتنازلُ لفظيٌّ
-- والمكسبُ هو القيدُ الحاكمُ أدناه.
ALTER TABLE `fin_requests`
  ADD CONSTRAINT `fk_req_settlement`
      FOREIGN KEY (`settlement_id`) REFERENCES `settlements` (`id`)
      ON UPDATE RESTRICT ON DELETE RESTRICT;

-- القيدُ الحاكم: نوعُ دفعِ طرفٍ بلا مرجع تسويةٍ = رفضٌ عند الكتابة
ALTER TABLE `fin_requests`
  ADD CONSTRAINT `chk_party_payment_needs_settlement`
  CHECK (
        `request_type` NOT IN ('supplier_payment', 'employee_payment', 'settlement')
     OR `settlement_id` IS NOT NULL
  );
