-- D02 §3.10 · §4.3 · §14⑬ — حارس الطاقة اليومية وسجلّ تخليصه
-- ───────────────────────────────────────────────────────────────────────────
-- «تجاوزُ الطاقة لا يُمنع إدخالُه (فبعض التجاوز صحيحٌ كالإضافي والتسوية):
--  يحذّر النظام ويحفظ أوليًّا ويرفع capacity_flag — ويمنع اعتمادَ الموقع (②)
--  حتى: إدخال سببٍ، وفحص تداخل الورديات والتكرار، وتحديد وجود مشغّلٍ ثانٍ،
--  واعتماد المسؤول» (§3.10 · وأعادها §4.3 شرطًا على المرحلة ②).
--
-- الواقع المقيس قبل التنفيذ على بيانات co4 الحيّة (قراءةٌ فقط — لم يُمسّ صفّ):
--   • آلةٌ واحدة تجاوزت طاقتها اليومية: المعدة 12 يوم 2026-04-27 — ثلاثة صفوفٍ
--     مجموعها 28 ساعةَ عملٍ على ورديات مجموعها 30، والطاقة الافتراضية 20.
--   • 17 حالةَ مشغّلٍ تجاوز عشر ساعاتٍ في يومٍ واحد.
--   ولا شيء في النظام يلتقط أيًّا منها اليوم.
--
-- لماذا جدولٌ منفصلٌ ولم تُضف أعمدةُ التخليص إلى unit_entries؟
--   §3.1 نُقل حرفيًّا ولا يعرف من الحارس إلا العلم capacity_flag البوليّ. أما
--   *تخليصُ* العلم — السببُ وفحصُ التداخل والمشغّلُ الثاني والمسؤولُ المخلِّص —
--   فسجلٌّ مستقلٌّ: فيبقى §3.1 كما نصّ الدستور، ويأخذ الحارس سجلَّه هو. ولأن
--   الواقعة الواحدة قد تتجاوز في محورين معًا (المعدة والمشغّل) فلكلٍّ صفُّه
--   وتخليصُه — ولا يُخلَّص أحدهما بتخليص الآخر.
--
-- حدودٌ معلنة: الطاقة تُقرأ من .env (20 للمعدة · 10 للمشغّل — قيمتا §3.10)،
-- فهي «إعدادٌ لا ثابت» كما نصّ. أما التمييزُ حسب المشروع ونوع المعدة وخطة
-- التشغيل فمؤجَّلٌ صراحةً إلى حين وجود حاجةٍ حقيقيةٍ تفرّق بينها — لا يُبنى
-- جدولُ إعداداتٍ لحالةٍ لم تقع.
--
-- التطبيق بعميل utf8mb4 عبر database/migrate.php حصرًا (لا DDL يدوي).
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS `unit_capacity_flags` (
  `id`             INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `company_id`     INT UNSIGNED NOT NULL,
  `entry_id`       INT UNSIGNED NOT NULL COMMENT 'الواقعة التي رُفع عليها العلم',

  -- محور التجاوز: المعدة أو المشغّل. «تشغيلُ المعدة 20 ساعةً يفترض مشغّلًا لكل
  -- ورديةٍ لا مشغّلًا واحدًا 20 ساعة» (§3.10) — فالمحوران مستقلّان بالتصميم.
  `subject`        ENUM('equipment','operator') NOT NULL,
  `subject_ref`    INT UNSIGNED NOT NULL COMMENT 'معرّف المعدة أو الموظف',
  `flag_date`      DATE NOT NULL,

  `measured_hours` DECIMAL(8,2) NOT NULL COMMENT 'مجموع اليوم المقيس شاملًا هذه الواقعة',
  `capacity_hours` DECIMAL(8,2) NOT NULL COMMENT 'الطاقة النافذة وقت الرفع — لقطةٌ لا مرجع',

  -- الفحوص الثلاثة التي يوجبها §3.10 قبل اعتماد الموقع. NULL = لم يُفحص بعد،
  -- وهو المنعُ بعينه: الحارس لا يفترض السلامة، بل يطلب إعلانًا صريحًا.
  `overlap_found`  TINYINT(1) NULL COMMENT 'تداخلُ ورديات — نتيجة الفحص',
  `duplicate_found` TINYINT(1) NULL COMMENT 'تكرارٌ مشتبهٌ به — نتيجة الفحص',
  `second_operator_present` TINYINT(1) NULL COMMENT 'هل وُجد مشغّلٌ ثانٍ؟ (إعلانٌ صريح)',

  `cause_note`     VARCHAR(200) NULL COMMENT 'سبب التجاوز — إلزامٌ قبل التخليص',
  `cleared_by`     INT UNSIGNED NULL COMMENT 'المسؤول المعتمِد — users',
  `cleared_at`     DATETIME NULL,

  `created_at`     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at`     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
                     ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (`id`),
  -- علمٌ واحدٌ لكل محورٍ عن كل واقعة — العطالة بقيدٍ في القاعدة لا بفحصٍ في الكود.
  UNIQUE KEY `uq_flag` (`company_id`,`entry_id`,`subject`),
  KEY `ix_open`    (`company_id`,`cleared_at`),
  KEY `ix_subject` (`company_id`,`subject`,`subject_ref`,`flag_date`),
  CONSTRAINT `fk_ucf_entry` FOREIGN KEY (`entry_id`)
    REFERENCES `unit_entries`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='D02 §3.10 — أعلام تجاوز الطاقة وتخليصها: لا اعتمادَ موقعٍ قبل الحسم';
