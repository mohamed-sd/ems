-- القيدُ البنيويُّ في الترحيل السابق يرفض **كلَّ** خصمٍ بلا مصدر. وهو الصواب
-- حيث يوجد مصدر — لكنه يقفل بابًا لا مصدرَ له أصلًا: **سلفُ الموظفين وخصومُهم**
-- لا جدولَ لها بعد (نطاقُ M-12/M-20). فالإلزامُ المطلق يمنع الموارد البشرية من
-- تسجيل خصمٍ حقيقيٍّ وقع، ويدفعها إلى تسميته باسمٍ آخر — وهو أسوأُ من إعلانه.
--
-- **فالقيمةُ السادسة `pending_source`** = «بلا مصدرٍ مستنديٍّ بعد — بقرارٍ موثَّق».
-- والفرقُ بينها وبين NULL هو الفرقُ بين **فجوةٍ معلَنةٍ** و**فجوةٍ منسيّة**:
--   • NULL           = لم يُسأل ⇒ **مرفوضٌ بنيويًّا**
--   • pending_source = سُئل وأُجيب: لا مصدرَ له بعد، والسببُ مكتوبٌ وظاهرٌ في الشاشة
--   • legacy_no_ref  = صفٌّ تاريخيٌّ سابقٌ للقاعدة (لا يُنشأ جديدًا به)
--
-- ⚠️ **وهي مقيَّدةٌ بأنواعها**: تُقبل لـ`advance`/`deduction` وحدَهما — فما له
-- مصدرٌ مبنيٌّ (قطعٌ · صيانةٌ · نقلٌ · جزاءٌ · تسوية) **لا يُقبل بلا مستنده**،
-- وإلا صارت القيمةُ بابًا خلفيًّا يُفرغ القيدَ من معناه. والتقييدُ في طبقة
-- التطبيق لا في `CHECK` لأن ENUM القيم لا يُقيَّد بعمودٍ آخرَ في MySQL بلا
-- تعقيدٍ يفوق فائدته — والشاشةُ والخدمةُ تحرسانه، ويحرسه الاختبار.
-- ═══════════════════════════════════════════════════════════════════════════

