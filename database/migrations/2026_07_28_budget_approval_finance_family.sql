-- كانت الإجازةُ محصورةً في الدور 19 وحده (قرارُ 2026-07-27)، فكان المديرُ الماليُّ
-- نفسُه (17) يفتح الشاشةَ فلا يرى زرًّا. والتوسعةُ تُشتَقّ في الكود **بالتبعية**
-- من `roles.parent_role_id = 17` لا بقائمةٍ مكتوبة — فلا يحتاج هذا الملفُّ إلى
-- ذكر الأدوار بأسمائها.
--
-- والذي يحتاج ترحيلًا هو الترشيحُ الثاني: الشاشةُ تشترط `can_edit` قبل أي انتقال،
-- ومعاونو المالية 18/20/21 كانوا **عرضًا فقط** فلا يفعلون شيئًا ولو ظهر الزر.
--
-- و**القارئُ المالي (22) يُستثنى عمدًا**: الفعلُ يناقض تعريفَ دوره. فهو داخلُ
-- الأسرة في الكود، ويخرج هنا بالصلاحية — وهذا هو معنى «التبعيةُ تحدد القائمة
-- والصلاحيةُ ترشّح» (قاعدة المالك في المصدر الموحّد للقوائم).
--
-- ولا يُمَسّ فصلُ اليدين: `fin_budget_self_owned()` تمنع كلَّ مُجيزٍ من إجازة
-- موازنةِ قسمٍ يديره — فالمديرُ الماليُّ لا يُجيز الإيراداتِ والخزينةَ والعام
-- (أقسامَه هو)، وتبقى للدور 19 الذي لا يملك قسمًا.
--
-- إضافةٌ محضة: `can_add` و`can_delete` لا تُمَسّان — الإنشاءُ والحذفُ ليسا إجازة.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE `role_permissions` p
  JOIN `modules` m ON m.`id` = p.`module_id`
   SET p.`can_edit` = 1
 WHERE m.`code` = 'Finance/budget_form_fin.php'
   AND p.`role_id` IN (18, 20, 21)
   AND p.`can_edit` = 0;
