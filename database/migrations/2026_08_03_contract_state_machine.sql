-- ═══════════════════════════════════════════════════════════════════════════
-- H-02 · آلةُ حالات العقد (OPM-01 §3) — 2026-07-29
-- ───────────────────────────────────────────────────────────────────────────
-- **الفجوة**: `contracts.contract_status` نوعُه `mediumtext` نصٌّ حر، ولا آلةَ
-- حالاتٍ ولا انتقالاتٍ محروسة. و**القيمةُ NULL في 9 من 9** — أي أنه **لا نصَّ
-- حرًّا يُرحَّل أصلًا**، فبندُ «خريطةُ تحويلٍ من النص الحر» يسقط عمليًّا.
--
-- ── الحالةُ الابتدائيةُ **مشتقّةٌ من شواهدَ قائمةٍ لا مخترَعة** ──────────────
-- كلُّ قاعدةٍ أدناه تقرأ عمودًا موجودًا، وبأسبقيةٍ معلَنة:
--   ① `status = 0` ومعه `pause_date` بلا `resume_date`  ⇒ **معلَّق**
--      (إيقافٌ صريحٌ مسجَّلٌ بتاريخه — أقوى شاهدٍ فيُقدَّم)
--   ② `actual_end < CURDATE()`                          ⇒ **منتهٍ**
--   ③ له تشغيلٌ مرتبطٌ (`operations`)                    ⇒ **قيد التنفيذ**
--   ④ وما بقي (موقَّعٌ بمصفوفةٍ مُجازةٍ ولم يبدأ تشغيلُه) ⇒ **نافذ**
-- والنتيجةُ المقيسة: 2 معلَّق · 1 منتهٍ · 4 قيد التنفيذ · 2 نافذ.
-- **ولا عقدَ يبدأ «مسودةً»**: التسعةُ موقَّعةٌ بتواريخها ولها معداتُها ومصفوفاتُها،
-- فإرجاعُها إلى المسودة كذبٌ على الواقع.
--
-- ── الحالاتُ الاثنتا عشرة بترتيب الوثيقة ──────────────────────────────────
-- مسودة → تفاوض → معتمد → موقَّع → **نافذ** → قيد التنفيذ
--   ↳ معلَّق (من أي مرحلة، ويعود بالاستئناف)
--   ↳ معدَّل · مجدَّد (من قيد التنفيذ، ويعودان إليه)
--   ↳ منتهٍ → مقفل → مصفّى (نهائيةٌ بلا رجوع)
--
-- ⚠️ **«نافذ» هو مدخلُ H-01**: لا حاويةَ تُفتح إلا من عقدٍ نافذ. فتعريفُه هنا
--    واحدٌ محسوم، ويُقرأ من `ContractStateMachine::isEffective()` لا من نصٍّ يُعاد كتابتُه.
--
-- ── والمفرداتُ الإنجليزيةُ القديمة تموت هنا ───────────────────────────────
-- `emsreports/reports/_report_template.php` كان يقارن بـ`'paused'`/`'terminated'`/
-- `'merged'` ويعدّ NULL «نشطًا». وهي مفرداتٌ **لم يُكتب بها صفٌّ واحد** (9 من 9
-- NULL)، فتحويلُها إلى ENUM عربيٍّ لا يُتلف بيانًا — لكن **قارئَها يُحدَّث في
-- الشيفرة** مع هذا الترحيل، وإلا بقي يقارن بقيمٍ لا يمكن أن توجد («الاسمُ في
-- موضعين = انفصامٌ مؤجَّل»).
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE `contracts`
  MODIFY COLUMN `contract_status`
    ENUM('مسودة','تفاوض','معتمد','موقَّع','نافذ','قيد التنفيذ',
         'معلَّق','معدَّل','مجدَّد','منتهٍ','مقفل','مصفّى')
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
    DEFAULT NULL
    COMMENT 'H-02 · OPM-01 §3: آلةُ حالات العقد. الانتقالُ يُحرَس في ContractStateMachine لا في الشاشة. «نافذ» = شرطُ فتح الحاويات (H-01)';

-- ── الاشتقاقُ بأسبقيته — صفٌّ واحدٌ لكل عقد، ولا عقدَ يُترك NULL ─────────────
UPDATE `contracts`
   SET `contract_status` = CASE
        WHEN `status` = 0 AND `pause_date` IS NOT NULL AND `resume_date` IS NULL THEN 'معلَّق'
        WHEN `actual_end` IS NOT NULL AND `actual_end` < CURDATE()               THEN 'منتهٍ'
        WHEN EXISTS (SELECT 1 FROM (SELECT contract_id FROM operations) o
                      WHERE o.contract_id = `contracts`.`id`)                    THEN 'قيد التنفيذ'
        ELSE 'نافذ'
   END
 WHERE `contract_status` IS NULL AND COALESCE(`is_deleted`, 0) = 0;

-- فهرسُ السؤال الحاكم: «أيُّ العقود نافذةٌ؟» (مدخلُ H-01) و«كم معلَّقًا؟»
ALTER TABLE `contracts`
  ADD INDEX `ix_contract_state` (`company_id`, `contract_status`);
