-- تنظيفُ قيم العملة الفاسدة وحارسُها البنيوي — 2026-07-28
-- ───────────────────────────────────────────────────────────────────────────
-- **المقيس**: عمودُ العملة يقبل نصًّا حرًّا، فحملت ستةُ صفوفٍ بقايا بذرٍ عشوائي
-- (Lorem Ipsum) بدل رمز عملة:
--     ems_business_events  #1246 · #1247 · #1249  = 'Ut volup'  (مبلغ 69 · revenue)
--     fin_requests         #181 = 'Nulla qu' (8) · #182 = 'Ut volup' (69) · #184 = 'Laborum' (86)
--
-- وهذه قيمٌ لا معنى لها: لا تُحسب ولا تُصرف ولا تُقارن. والأخطرُ أن العمود
-- **بلا قيدٍ ولا قائمةٍ محصورة** — فما منع دخولَها أولَ مرةٍ يبقى مفتوحًا.
--
-- **قرارُ المعالجة — NULL لا قيمةٌ مفترَضة**: لا تُنسب هذه المبالغُ إلى الدولار
-- ولا إلى الجنيه، فنحن **لا نعرف** عملتَها؛ ونسبتُها إلى عملةٍ بعينها تلفيقٌ
-- يُنتج معادلًا موحّدًا كاذبًا. وNULL تقول الصدق: «عملةٌ مجهولة». والصفوفُ
-- تبقى — الدفترُ سجلُّ وقائعَ إلحاقيٌّ لا يُحذف منه (ADR-15).
--
-- القيمُ القديمة موثَّقةٌ أعلاه نصًّا — وبها يكون الرجوعُ إن لزم.
--
-- **الحارسُ البنيوي**: مفتاحٌ أجنبيٌّ مركّبٌ (company_id, currency) → سجلِّ
-- العملات. فلا تدخل عملةٌ غيرُ مسجَّلةٍ بعد اليوم — والتسجيلُ نقرتان في شاشتها.
-- وNULL يمرّ بحكم المفتاح الأجنبي، فالمجهولُ يبقى ممكنًا والمخترَعُ يُرفض.
--
-- **`fin_requests` تُستثنى من المفتاح**: عمودُ `company_id` فيها `int unsigned`
-- بينما هو `int` في سجل العملات وفي الدفتر — واختلافُ الإشارة يمنع المفتاح
-- الأجنبي بنيويًّا. وتوحيدُ النوع تغييرٌ في جدولٍ حيٍّ بمفاتيحَ عليه، فلا يُقحم
-- في ملفِّ تنظيف. تُحرَس عبر طبقة التطبيق ويبقى التوحيدُ دينًا موثَّقًا.
--
-- يعتمد على: 2026_07_28_fx_currency_foundation.sql (يجب تطبيقُه أولًا).
-- الرجوع: إسقاطُ المفتاحين، وإعادةُ القيم الست من نصِّها أعلاه.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── ① القيمُ الفاسدة تصير «مجهولة» صراحةً ─────────────────────────────────
UPDATE `ems_business_events`
   SET `currency` = NULL
 WHERE `currency` IS NOT NULL
   AND `currency` NOT IN (SELECT `code` FROM `fin_currencies`);

UPDATE `fin_requests`
   SET `currency` = NULL
 WHERE `currency` IS NOT NULL
   AND `currency` NOT IN (SELECT `code` FROM `fin_currencies`);

-- ── ② وما صار مجهولَ العملة لا يصحّ له معادلٌ موحّد ────────────────────────
UPDATE `ems_business_events`
   SET `fx_rate` = NULL, `base_amount` = NULL
 WHERE `currency` IS NULL;

-- ── ③ الحارسُ: لا حركةَ بعملةٍ غير مسجَّلة ────────────────────────────────
ALTER TABLE `ems_business_events`
  ADD CONSTRAINT `fk_be_currency`
      FOREIGN KEY (`company_id`, `currency`)
      REFERENCES `fin_currencies` (`company_id`, `code`)
      ON UPDATE CASCADE ON DELETE RESTRICT;

ALTER TABLE `fin_dues`
  ADD CONSTRAINT `fk_dues_currency`
      FOREIGN KEY (`company_id`, `currency`)
      REFERENCES `fin_currencies` (`company_id`, `code`)
      ON UPDATE CASCADE ON DELETE RESTRICT;
