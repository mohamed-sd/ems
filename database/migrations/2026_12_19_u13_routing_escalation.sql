-- ═══════════════════════════════════════════════════════════════════════════
-- كشفت بوابةُ القبولِ أن تخصصين من العشرةِ تصلهما مساراتٌ ولا حاملَ لهما في
-- القاعدةِ الحية (ACC-05 التمويل · ACC-09 الضرائب). والمعالجةُ بنيويةٌ لا بيانية:
-- BR-01 «الانتظارُ الصامتُ أسوأُ من الرفض» — فالواقعةُ التي لا تجد محاسبَ
-- تخصصِها تُصعَّد إلى **رئيسِ الحسابات** وهو الحلقةُ التاليةُ في سلسلةِ كلِّ
-- مسارٍ أصلًا، ويُسجَّل التصعيدُ في `resolved_by` فيُقاس ولا يختفي.
--
-- ◆ گوتشا موثَّقة: ENUM يبتلع القيمةَ غيرَ المعرَّفةِ إلى '' **صامتًا** —
--   فتوسيعُ المجالِ قبلَ كتابةِ 'escalated' إلزامٌ لا تحسين، والعميلُ utf8mb4.

ALTER TABLE `fin_routing_log`
  MODIFY COLUMN `resolved_by`
    ENUM('matrix','fallback','escalated','manual') NOT NULL DEFAULT 'matrix'
    COMMENT 'matrix مسارٌ صريح · fallback الحكمُ الجامع · escalated لا حاملَ للتخصص · manual استثناءٌ مسجَّل';
