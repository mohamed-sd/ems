$__u = null;
$__st = $conn->prepare("SELECT unit_id FROM org_units WHERE company_id = ? AND unit_code = 'finance' AND active = 1 LIMIT 1");
$__st->bind_param('i', $company_id);
$__st->execute();
if ($__row = $__st->get_result()->fetch_assoc()) { $__u = (int) $__row['unit_id']; }
$__st->close();
if ($__u !== null) {
    $_GET['unit'] = (string) $__u;              // للمحفظة الكاملة (الرئيس · المخاطر · السوبر)
