<?php
/**
 * tools/rpr02a_sidebar_spec.php — دليلُ السايدبارِ المعياريُّ ومصالحتُه بدليلِ الأدوار
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ **المقامُ من المخزنِ لا من ورقة**: سبعَ عشرةَ إدارةً وأربعةُ رموزٍ خارجَها
 *   كما في `repair01_departments` — ⛔ لا يُشتقُّ المقامُ من عدِّ تبويباتٍ ولا
 *   من عدِّ أوراقٍ في مصنَّف.
 *
 * ◆ **والمجموعاتُ وترتيبُ الشاشاتِ من ورقةِ كلِّ إدارةٍ في الدليلِ المعماريّ**
 *   لا كما تراكمت — والقاعدةُ الأولى: «ترتيبُ الشاشاتِ في الـSidebar = دورةُ
 *   العملِ الحقيقية».
 *
 * ◆ **ودليلُ الأدوارِ مرجعٌ لا مقام**: `EMS_دليل_شاشات_السايدبار_…` تصييرٌ
 *   فعليٌّ لـ`insidebar.php` بجلسةِ كلِّ دور — **فهو «دليلُ العرضِ بالأدوار»**،
 *   ويُنزع عنه وصفُ «الشامل النهائي». والمصالحةُ تسمّي كلَّ فرقٍ واحدًا واحدًا.
 *
 * ⚠ **وفصلٌ لازم**: «نزعُ دورٍ» ≠ «إعادةُ تسميةِ إدارةٍ حملها دورٌ». فـ`أمين
 *   المستودع` هو **الحاملُ الوحيدُ لإدارةِ المخازن `DEP-17`** — ونزعُه بلا
 *   إعادةِ تسميةٍ يُفقِد إدارةً كاملة.
 *
 * التشغيل: php tools/rpr02a_sidebar_spec.php
 * ═══════════════════════════════════════════════════════════════════════════
 */
if (php_sapi_name() !== 'cli') { exit("CLI only\n"); }
error_reporting(E_ALL & ~E_DEPRECATED);
mb_internal_encoding('UTF-8');
define('EMS_CLI', true);
$ROOT = dirname(__DIR__);
require_once $ROOT . '/includes/session_bootstrap.php';
require_once $ROOT . '/config.php';
while (ob_get_level()) { ob_end_clean(); }
require_once $ROOT . '/tools/lib/rpr02a_guide.php';
$conn = $GLOBALS['conn'];
$conn->set_charset('utf8mb4');

/* ═══ ① المقامُ من المخزن ═══ */
$depts = array();
$r = $conn->query("SELECT canonical_code, display_order, name_ar, sector, parent_code, note
                     FROM repair01_departments ORDER BY (display_order IS NULL), display_order, canonical_code");
while ($r && ($x = $r->fetch_assoc())) { $depts[$x['canonical_code']] = $x; }
$deptCount = 0; $outCount = 0; $platform = null;
foreach ($depts as $code => $d) {
    if ($code === 'PLATFORM') { $platform = $d; continue; }
    if ($d['display_order'] !== null) { $deptCount++; } else { $outCount++; }
}

/* ═══ ② المجموعاتُ والترتيبُ من الدليلِ المعماريِّ نفسِه ═══ */
$cards = rpr02a_read_cards($ROOT . '/docs/REPAIR01_20260823/01 · الدليل المعماري.xlsx');
$spec = array();
foreach ($cards as $c) {
    if (rpr02a_is_doc($c)) { continue; }                 /* سطحُ التوثيقِ خارجَ السايدبار */
    $spec[$c['code']]['groups'][$c['group']][] = $c;
    $spec[$c['code']]['n'] = ($spec[$c['code']]['n'] ?? 0) + 1;
}

/* ═══ ③ دليلُ العرضِ بالأدوار ═══ */
$ROLES_XLSX = $ROOT . '/docs/EMS_دليل_شاشات_السايدبار_الشامل_النهائي_20260828.xlsx';
$roleSheets = array();
if (is_file($ROLES_XLSX)) {
    $WB = xlsx_read($ROLES_XLSX);
    foreach ($WB as $sh => $rows) {
        if ($sh === 'الفهرس' || $sh === 'كل الروابط') { continue; }
        $roleSheets[$sh] = count($rows);
    }
}

/* ═══ ④ المصالحة — كلُّ فرقٍ بحكمٍ مسمًّى ═══
   ⛔ **لا يُخمَّن الوصل**: الجدولُ أدناه منقولٌ من `repair01_dept_crosswalk`
   حيث وُجد المسمّى، ومحكومٌ صراحةً حيث لم يوجد — ولكلِّ صفٍّ سببُه. */
$XW = array();
$r = $conn->query("SELECT legacy_name, canonical_code, verdict FROM repair01_dept_crosswalk");
while ($r && ($x = $r->fetch_assoc())) { $XW[$x['legacy_name']][] = $x; }

$RECON = array(
    'ادارة التشغيل'                        => array('KEEP',   'DEP-11', 'مسمًّى حيٌّ في الجسر'),
    'ادارة الموردين'                       => array('KEEP',   'DEP-02', 'مسمًّى حيٌّ في الجسر'),
    'ادارة الاسطول'                        => array('RENAME', 'DEP-04', 'يُسمّى «04 إدارة الأسطول والأصول» — الاسمُ المعياريُّ يضمّ الأصول'),
    'ادارة الموارد البشرية'                => array('KEEP',   'DEP-07', 'مسمًّى حيٌّ في الجسر'),
    'إدارة الموقع (قديم — مدمج في 6)'      => array('DROP',   '',       'ورقةٌ ميّتةٌ بربطٍ واحد — الدمجُ وقع في «إدارة الموقع» ⇒ تُرفع بعذرِها'),
    'إدارة الموقع'                         => array('KEEP',   'DEP-12', 'مسمًّى حيٌّ في الجسر'),
    'الإدارة التنفيذية'                    => array('SPLIT',  'EX-CEO', 'تحمل مساحةَ الرئيسِ وحدَها — **ونوّابُ الرئيس `EX-DVP` بلا ورقةٍ أصلًا**'),
    'ادارة المبيعات'                       => array('RENAME', 'DEP-01', 'يُسمّى «01 إدارة المبيعات التعاقدية والعقود»'),
    'ادارة الصيانة'                        => array('KEEP',   'DEP-14', 'مسمًّى حيٌّ في الجسر'),
    'إدارة الصلاحيات'                      => array('DROP',   '',       '**دورٌ تقنيٌّ لا إدارة** — لا رمزَ معياريَّ له في `repair01_departments`'),
    'إدارة المشتريات'                      => array('KEEP',   'DEP-16', 'مسمًّى حيٌّ في الجسر'),
    'إدارة المالية'                        => array('SPLIT',  'DEP-05', '**شقٌّ وظيفيّ**: الاعترافُ والقيدُ ⇒ `DEP-05` · القبضُ والصرفُ ⇒ `DEP-06` — والورقةُ تخلطهما'),
    'إدارة النقل والترحيل'                 => array('KEEP',   'DEP-15', 'مسمًّى حيٌّ في الجسر'),
    'أمين المستودع'                        => array('RENAME', 'DEP-17', '⛔ **إعادةُ تسميةٍ لا نزع**: هو **الحاملُ الوحيدُ لإدارةِ المخازن** — ونزعُه بلا تسميةٍ يُفقِد إدارةً كاملة'),
    'إدارة التمويل'                        => array('RENAME', 'DEP-03', 'يُسمّى «03 إدارة التمويل والممولين»'),
    'القوى التشغيلية'                      => array('RENAME', 'DEP-13', 'يُسمّى «13 إدارة القوى التشغيلية»'),
    'إدارة المخاطر'                        => array('KEEP',   'DEP-09', 'مسمًّى حيٌّ في الجسر'),
    'المدير المالي'                        => array('DROP',   '',       '**دورٌ داخلَ المالية لا إدارة** — ورقتُه ٨ روابطَ كلُّها داخلَ نطاقِ `DEP-05`/`DEP-06`'),
    'المراجع الداخلي المستقل'              => array('KEEP',   'IAF',    'وظيفةُ تأكيدٍ مستقلّةٌ — ترفع للمالك (م 110)'),
);

/* الرموزُ التي لا ورقةَ لها */
$covered = array();
foreach ($RECON as $sheet => $d) { if ($d[1] !== '') { $covered[$d[1]] = $sheet; } }
$absent = array();
foreach ($depts as $code => $d) {
    if ($code === 'PLATFORM') { continue; }
    if (!isset($covered[$code])) { $absent[$code] = $d; }
}

/* ═══ التقرير ═══ */
$ts = date('Y-m-d H:i:s');
$md  = "# RPR-02-A · دليلُ السايدبارِ المعياريُّ ومصالحتُه بدليلِ العرضِ بالأدوار\n\n";
$md .= "> ⛔ **مولَّدٌ من تشغيلٍ حيّ**: `php tools/rpr02a_sidebar_spec.php`\n> **مولَّدٌ**: " . $ts . "\n";
$md .= "> **المقام**: `repair01_departments` · **المجموعاتُ والترتيب**: `01 · الدليل المعماري.xlsx` · **المقارَن**: `docs/EMS_دليل_شاشات_السايدبار_الشامل_النهائي_20260828.xlsx`\n\n";

$md .= "## ⓪ المقام — من المخزنِ لا من ورقة\n\n";
$md .= "| المفردة | العدد |\n|---|---:|\n";
$md .= "| إداراتٌ مرقَّمةٌ `DEP-01..17` | **" . $deptCount . "** |\n";
$md .= "| رموزٌ خارجَ التعداد (`EX-CEO` · `EX-DVP` · `IAF` · `WS-MY`) | **" . $outCount . "** |\n";
$md .= "| **= مقامُ الدليلِ المعياريّ** | **" . ($deptCount + $outCount) . "** |\n";
$md .= "| `PLATFORM` — رمزٌ منصّيٌّ مشتركٌ لا إدارة | " . ($platform ? 1 : 0) . " |\n";
$md .= "| أوراقُ الأدوارِ في دليلِ العرض | **" . count($roleSheets) . "** |\n\n";

$md .= "## ① الدليلُ المعياريُّ — مجموعاتُ كلِّ إدارةٍ وترتيبُ شاشاتِها\n\n";
$md .= "> **الترتيبُ هو ترتيبُ الدليلِ نفسِه** — وهو ترتيبُ دورةِ العملِ لا الترتيبُ المتراكم.\n";
$md .= "> **وأسطحُ التوثيقِ الـ21 مرفوعةٌ من هذا الدليل** — لا تظهر في السايدبار (`G-DOC-01`).\n\n";
$md .= "| الرمز | الإدارة | القطاع | مجموعات | شاشاتٌ في السايدبار |\n|---|---|---|---:|---:|\n";
foreach ($depts as $code => $d) {
    if ($code === 'PLATFORM') { continue; }
    $g = isset($spec[$code]) ? count($spec[$code]['groups']) : 0;
    $n = isset($spec[$code]) ? $spec[$code]['n'] : 0;
    $md .= '| `' . $code . '` | ' . $d['name_ar'] . ' | `' . $d['sector'] . '` | ' . $g . ' | ' . $n . " |\n";
}
$md .= "\n";
foreach ($depts as $code => $d) {
    if ($code === 'PLATFORM' || !isset($spec[$code])) { continue; }
    $md .= "### `" . $code . "` — " . $d['name_ar'] . "\n\n";
    $gi = 0;
    foreach ($spec[$code]['groups'] as $gname => $items) {
        $gi++;
        $md .= '**⬛ ' . $gi . ' · ' . $gname . "** — " . count($items) . " شاشة\n\n";
        foreach ($items as $it) { $md .= '  ' . $it['idx'] . '. ' . $it['name'] . "\n"; }
        $md .= "\n";
    }
}

$md .= "## ② المصالحةُ مع دليلِ العرضِ بالأدوار — فرقًا فرقًا\n\n";
$md .= "> **دليلُ العرضِ بالأدوار** اسمُه الصحيح — ⛔ **ويُنزع عنه وصفُ «الشامل النهائي»**: فهو تصييرُ ما يراه كلُّ دورٍ اليومَ، لا ما ينبغي أن يراه.\n\n";
$md .= "| ورقةُ الدور | الحكم | الرمزُ المعياريّ | السبب |\n|---|---|---|---|\n";
$cnt = array('KEEP' => 0, 'RENAME' => 0, 'DROP' => 0, 'SPLIT' => 0);
foreach ($RECON as $sheet => $d) {
    $cnt[$d[0]]++;
    $lbl = array('KEEP' => '**باقٍ**', 'RENAME' => '**معادُ التسمية**', 'DROP' => '⛔ **مرفوع**', 'SPLIT' => '⚠ **يُشقّ**');
    $md .= '| ' . $sheet . ' | ' . $lbl[$d[0]] . ' | ' . ($d[1] !== '' ? '`' . $d[1] . '`' : '—') . ' | ' . $d[2] . " |\n";
}
$md .= "\n";
$md .= "| الحكم | العدد |\n|---|---:|\n";
$md .= "| باقٍ كما هو | " . $cnt['KEEP'] . " |\n";
$md .= "| معادُ التسميةِ إلى الاسمِ المعياريّ | " . $cnt['RENAME'] . " |\n";
$md .= "| يُشقُّ إلى رمزَين | " . $cnt['SPLIT'] . " |\n";
$md .= "| **مرفوعٌ بعذرٍ مكتوب** | **" . $cnt['DROP'] . "** |\n";
$md .= "| **مضافٌ — رمزٌ بلا ورقةِ دورٍ أصلًا** | **" . count($absent) . "** |\n\n";

$md .= "### ⛔ التصحيحُ الحسابيّ — الأمرُ سمّى «نزعَ أربعةٍ وإضافةَ ثلاث»، والمقيسُ غيرُ ذلك\n\n";
$md .= "| الفرقُ في الأمر | المقيسُ هنا | البيان |\n|---|---|---|\n";
$md .= "| نزعُ **أربعةِ** أدوارٍ مدسوسة | **نزعُ ثلاثةٍ فقط** | `أمين المستودع` **ليس نزعًا بل إعادةَ تسمية** — وهو الحاملُ الوحيدُ لـ`DEP-17` |\n";
$md .= "| إضافةُ **ثلاثِ** إدارات | **إضافةُ " . count($absent) . "** | الثلاثةُ المسمّاةُ وزيادةٌ — تُسمَّى أدناه |\n";
$md .= "| ‏19 − 4 + 3 = **18** ≠ 21 | ‏19 − 3 + " . count($absent) . " = **" . (count($RECON) - $cnt['DROP'] + count($absent)) . "** | والفارقُ الذي لم يسمِّه الأمرُ **مُغلَقٌ بالكامل** |\n\n";

$md .= "### الرموزُ التي لا ورقةَ دورٍ لها — تُضاف\n\n";
$md .= "| الرمز | الاسمُ المعياريّ | القطاع | لماذا غابت |\n|---|---|---|---|\n";
$WHY_ABSENT = array(
    'DEP-06' => 'مدموجةٌ داخلَ ورقةِ «إدارة المالية» — والشقُّ وظيفيٌّ لا اسميّ',
    'DEP-08' => 'بلا دورٍ حيٍّ يحملها — و`إدارة الصلاحيات` ليست بديلًا عنها',
    'DEP-10' => 'بلا دورٍ حيٍّ يحملها — والبلاغاتُ تظهر بندًا شخصيًّا لا إدارةً',
    'EX-DVP' => '**مطموسةٌ داخلَ «الإدارة التنفيذية»** — وهي أسوأُ فجوةٍ في النظامِ بـ8.3٪',
    'WS-MY'  => 'مساحةٌ شخصيّةٌ تظهر بنودًا داخلَ أوراقِ الأدوارِ كلِّها ولا ورقةَ لها',
);
foreach ($absent as $code => $d) {
    $md .= '| `' . $code . '` | ' . $d['name_ar'] . ' | `' . $d['sector'] . '` | '
         . (isset($WHY_ABSENT[$code]) ? $WHY_ABSENT[$code] : '—') . " |\n";
}

$md .= "\n## ③ أوراقُ دليلِ العرضِ بأحجامِها — للمرجع\n\n";
$md .= "| الورقة | صفوف |\n|---|---:|\n";
foreach ($roleSheets as $sh => $n) { $md .= '| ' . $sh . ' | ' . $n . " |\n"; }

$path = $ROOT . '/docs/REPAIR01_20260823/RPR02A_SIDEBAR_SPEC.md';
file_put_contents($path, $md);
printf("إدارات %d + خارجَ التعداد %d = %d · PLATFORM %d · أوراقُ أدوارٍ %d · باقٍ %d · تسمية %d · شقّ %d · مرفوع %d · مضاف %d\n",
    $deptCount, $outCount, $deptCount + $outCount, $platform ? 1 : 0, count($roleSheets),
    $cnt['KEEP'], $cnt['RENAME'], $cnt['SPLIT'], $cnt['DROP'], count($absent));
echo "=> " . $path . "\n";
