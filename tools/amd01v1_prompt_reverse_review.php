/* ── وضعُ التردّد `--freq`: كم مرّةً ترد كلُّ مرساةٍ في المُنتَج؟ ────────────
   ⚠ **ولِمَ يلزم؟** الاختبارُ السالبُ يكسر مرساةً ليرى العدّادَ يتحرّك —
   **ومرساةٌ ترد مرّتَين لا تنكسر بتحريرٍ واحد**، فيبقى العدّادُ ثابتًا
   ويُظنُّ الفاحصُ أعمى وهو سليم. **فالكسرُ يقع على مرساةٍ فريدةٍ أو على كلِّ
   مواضعِها.** وهذا الوضعُ يُخرج القائمةَ الصالحةَ للكسر. */
if (in_array('--freq', $argv, true)) {
    $u = 0; $m = 0; $z = 0; $t = 0; $uniqList = array();
    foreach ($REQ as $r) {
        foreach ($r[2] as $a) {
            $t++;
            $n = mb_substr_count($N, $norm($a));
            if ($n === 0)      { $z++; printf("  ✘ %-2d %s\n", $n, $a); }
            elseif ($n === 1)  { $u++; $uniqList[] = $a; }
            else               { $m++; printf("  ⚠ %-2d %s\n", $n, $a); }
        }
    }
    printf("\nمراسٍ: %d · فريدةٌ: %d · متكرِّرةٌ: %d · معدومةٌ: %d\n", $t, $u, $m, $z);
    echo "\nصالحٌ للكسرِ في الاختبارِ السالب (فريدٌ — أوّلُ 5):\n";
    foreach (array_slice($uniqList, 0, 5) as $a) { echo "  · $a\n"; }
    exit(0);
}

/* ── الاختبارُ السالب `--selftest` — **الحاجبُ يُثبِت أنّه يَحمَرّ** ─────────
   المعيارُ الذي أقرَّه المالكُ في `RPR-02-A` §٧·١: **«بإثباتِها بحركةِ عدّادٍ
   بواحدٍ ثمَّ عودةٍ لا بمجرّدِ رسوب»**. فيُكسَر هنا مرساةٌ **فريدةٌ** واحدةٌ في
   نسخةٍ **في الذاكرة** (‏لا في الملفّ) ويُشترط: ‏N ⇒ N−1 ⇒ N بالضبط.
   ⚠ **والمرساةُ تُختار فريدةً** — ومرساةٌ ترد مرّتَين لا تنكسر بتحريرٍ واحد
     فيبقى العدّادُ ثابتًا ويُظنُّ الفاحصُ أعمى وهو سليم. */
$score = function ($text) use ($REQ, $norm) {
    $t = $norm($text); $c = 0;
    foreach ($REQ as $r) {
        $all = true;
        foreach ($r[2] as $a) { if (mb_strpos($t, $norm($a)) === false) { $all = false; break; } }
        if ($all) { $c++; }
    }
    return $c;
};
if (in_array('--selftest', $argv, true)) {
    $base = $score($doc);
    $victim = null;
    foreach ($REQ as $r) {
        foreach ($r[2] as $a) {
            if (mb_substr_count($N, $norm($a)) === 1) { $victim = $a; break 2; }
        }
    }
    if ($victim === null) { exit("✘ لا مرساةَ فريدةً — الاختبارُ السالبُ غيرُ ممكن\n"); }
    /* الكسرُ في الذاكرة: تُحذف المرساةُ الفريدةُ من نصِّ المستند */
    $pos = mb_strpos($N, $norm($victim));
    $broken = mb_substr($N, 0, $pos) . '‡KSR‡' . mb_substr($N, $pos + mb_strlen($norm($victim)));
    $after  = $score($broken);
    $back   = $score($doc);
    echo "\n═══ الاختبارُ السالبُ — حركةُ عدّادٍ ثمَّ عودة ═══\n";
    echo "  المرساةُ المكسورةُ (فريدة): «{$victim}»\n";
    printf("  ① قبل الكسر  : %d\n  ② بعد الكسر  : %d\n  ③ بعد العودة : %d\n", $base, $after, $back);
    $pass = ($after === $base - 1) && ($back === $base);
    echo $pass
        ? "\n🟢 **العدّادُ تحرَّك بواحدٍ ثمَّ عاد — فالفاحصُ يَحمَرُّ فعلًا**\n"
        : "\n🔴 **العدّادُ لم يتحرَّك بواحدٍ — الفاحصُ لا يُوثَق به**\n";
    exit($pass ? 0 : 1);
}

