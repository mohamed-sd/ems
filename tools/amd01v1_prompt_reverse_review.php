       «المقارنةِ بين تمثيلَين لشيءٍ واحد»**. فتُطوى الأرقامُ إلى صورةٍ واحدة.
       ⛔ **وهذا لا يُضعِّف مرساةً**: توحيدُ تمثيلِ العددِ لا يُمرِّر عددًا آخر. */
