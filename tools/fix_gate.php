$db = fix_db();
$RESULTS = array();

function gate_run($code, $title, $measures, $notMeasures, callable $fn)
{
    global $RESULTS, $only;
    if ($only !== null && $only !== $code) { return; }
    $ok = false; $evidence = 'لم يُنفَّذ'; // ◆ الرسوبُ افتراضٌ — والمرورُ بشاهد
    try {
        $r = $fn();
        $ok = !empty($r['ok']);
        $evidence = (string) ($r['evidence'] ?? '');
    } catch (Throwable $e) {
        $ok = false;
        $evidence = 'استثناء: ' . $e->getMessage();
    }
    $RESULTS[] = compact('code', 'title', 'measures', 'notMeasures', 'ok', 'evidence');
    printf("%s %-8s %s\n", $ok ? '✔' : '✘', $code, $title);
    printf("        يقيس: %s\n", $measures);
    printf("        لا يقيس: %s\n", $notMeasures);
    printf("        الشاهد: %s\n\n", $evidence);
}

echo "══════════════════════════════════════════════════════════════════════\n";
echo " بوابةُ FIX — الأعطالُ الجذريةُ الثلاثةُ والبواباتُ ومعاييرُ التكويد\n";
echo " القاعدة: " . fix_one($db, 'SELECT DATABASE()') . " · " . date('Y-m-d H:i:s') . "\n";
echo "══════════════════════════════════════════════════════════════════════\n\n";

