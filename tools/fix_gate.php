       ولا يراها فحصُ العمودِ المخزَّن.
     ⓑ كلُّ عنصرٍ **قبِله المُنتقي** يظهر في الناتج — يكشف ما تُسقطه حلقةُ
       التصييرِ صامتًا (بابٌ خارجَ الثمانيةِ المعرَّفة). */
