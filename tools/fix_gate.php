        $md .= '| ' . $r['code'] . ' | ' . ($r['ok'] ? '✔' : '✘') . ' | ' . $r['measures']
             . ' | ' . $r['notMeasures'] . ' | ' . str_replace('|', '\\|', $r['evidence']) . " |\n";
    }
    $md .= "\n**النتيجة: {$pass}/" . ($pass + $fail) . "**\n";
    @file_put_contents($mdOut, $md);
    echo "تقرير: {$mdOut}\n";
}

exit($fail === 0 ? 0 : 1);
