    'AC-N1',
    'كلُّ رابطِ تنقُّلٍ يُصيَّر ويحلُّ إلى ملفٍّ قائم',
    'تصييرٌ حيٌّ لكلِّ دورٍ نشطٍ في عمليةٍ معزولة، ومقارنةُ الناتجِ بمُخرَجِ المُنتقي',
    'لا يفتح الصفحةَ فعلًا فلا يقيس عطلًا داخلَها ولا حجبًا حوكميًّا بعد الفتح',
    static function () use ($ROOT) {
        $out = (string) @shell_exec(escapeshellarg(PHP_BINARY) . ' '
             . escapeshellarg($ROOT . '/tools/fix_nav_href_probe.php') . ' --json 2>&1');
        $j = json_decode($out, true);
        if (!is_array($j) || !isset($j['bad'], $j['total'])) {
            return array('ok' => false, 'evidence' => 'تعذّرت قراءةُ مخرجِ المِسبار');
        }
        $un = count($j['unreachable'] ?? array());
        $ok = ($j['bad'] === 0 && $j['total'] > 0 && $un === 0
               && empty($j['fatal']) && empty($j['empty']));
        return array('ok' => $ok, 'evidence' => 'مُصيَّرٌ ' . $j['total'] . ' · مكسورٌ '
                     . $j['bad'] . ' · ساقطٌ صامتًا ' . $un);
    }
);

