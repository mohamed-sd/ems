foreach ($argv as $a) { if (strpos($a, '--md=') === 0) { $mdOut = substr($a, 5); } }

/* ── مصدرُ السجلِّ الجامع ─────────────────────────────────────────────── */
$candidates = array($TSV, $ROOT . '/docs/fix_2026-08/master_register.tsv');
