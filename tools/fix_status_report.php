    'INJ-0061',

    /* ── «البنودُ التسعةَ عشرَ» — الشاهدُ لكلٍّ: `tools/fix_od19_probe.php` ────
       ◆ كان هذا التقريرُ يعرف INJ-0061 وحدَه منها، والمِسبارُ يشهد لستةَ عشر
         بقياسٍ حيٍّ على النظام. فأداتان تقولان رقمين — وذلك بعينُه ما تمنعه
