    'INJ-0544', 'INJ-0589',

    /* سلسلةُ اعتمادِ الخصم — الشاهد: `tools/fix_inj0219_tests.php` (39/39)
       + قيدُ `chk_scr_ded_approved_evidence` مجسوسًا حيًّا في المِسبار. */
    'INJ-0219',

    /* ── فاحصان كانا يصادقان زورًا في بوابةِ M-10 ──────────────────────────
       الشاهد: `tools/fix_m10_gate_tests.php` **14/14** — ويجسُّ التمييزَ في
       الاتجاهين لا في اتجاهٍ واحد:
         · AC-05 (INJ-0241): الشرطُ الخاويُّ (مطابقةُ حروفِ «table» في المصدر)
           مرفوعٌ، ومحلُّه **تصييرٌ حيٌّ** يفحص الناتج؛ ومِسبارُ ملفٍّ فيه جدولٌ
           وحدَه **يُرفض** بسببٍ مُبيَّن.
         · AC-06 (INJ-0242): عدُّ الصفوفِ مرفوعٌ، ومحلُّه **فحصُ تبنٍّ**؛ وحقلٌ
