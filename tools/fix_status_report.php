    if (in_array($r['kind'], $COVERED_KINDS, true) && in_array($r['sev'], array('P0', 'P1'), true)) {
        $stat['مُغطًّى'][] = $r; continue;
    }
    $stat['مفتوح'][] = $r;
}

/* ══ ④ الأوزان — P0 لا يساوي P4 ═════════════════════════════════════════ */
$W = array('P0' => 13, 'P1' => 5, 'P2' => 2, 'P3' => 1, 'P4' => 0.5);
$sumW = function ($list) use ($W) {
    $s = 0.0;
    foreach ($list as $r) { $s += ($W[$r['sev']] ?? 1); }
    return $s;
};
$totalW   = $sumW($rows);
$closedW  = $sumW($stat['مُغلق']);
$coveredW = $sumW($stat['مُغطًّى']);

/* ══ ⑤ الإخراج ══════════════════════════════════════════════════════════ */
$out = array();
$p = function ($s = '') use (&$out) { $out[] = $s; };

$p('# تقريرُ حالةِ الحزمة — إكوبيشن · منصة إنجاز');
$p('');
$p('**تاريخ القياس:** ' . date('Y-m-d H:i') . ' · **المصدر:** السجلُّ الجامعُ الحيُّ ووثائقُ FIX الثلاث');
$p('');
$p('> **قاعدةُ هذا التقرير:** لا يُعلَن بندٌ «مُغلقًا» إلا وله **شاهدٌ مُشغَّلٌ**');
$p('> في أحدِ الفواحص. وما أُصلحت آليتُه المشتركةُ ولم يُشغَّل اختبارُ قبولِه');
$p('> منفردًا يُعلَن **«مُغطًّى»** — وهي حالةٌ بين الإصلاحِ والإغلاقِ لا تُحسب');
$p('> إنجازًا كاملًا. فالفرقُ بينهما هو عينُ ما تحذّر منه الوثائق.');
$p('');

/* ── المخزونان ─────────────────────────────────────────────────────────── */
$p('## ① المخزونان — ولا يُجمعان');
$p('');
$p('| المخزون | العدد | ما هو |');
$p('|---|---|---|');
$p('| وثائقُ FIX الثلاث | **619 متطلبًا ذريًّا** | FIX-01: 154 · FIX-02: 182 · FIX-03: 283 — أحكامٌ ومعاييرُ وخطواتُ تصحيح |');
$p('| السجلُّ الجامع | **' . count($rows) . ' ملاحظةً** | عيوبٌ ميدانيةٌ بأدلةِ «ملف:سطر» واختبارِ قبولٍ لكلٍّ |');
$p('');
$p('◆ الوثائقُ **خلاصةُ** السجل — فجمعُ الرقمين تضخيمٌ كاذب. والقياسُ أدناه على');
$p('السجلِّ لأن لكلِّ صفٍّ فيه **اختبارَ قبولٍ قابلًا للتشغيل**.');
$p('');

/* ── الحالة ────────────────────────────────────────────────────────────── */
$p('## ② الحالةُ بالأرقام');
$p('');
$p('| الحالة | العدد | النسبة | الوزنُ المرجَّح |');
$p('|---|---|---|---|');
foreach (array('مُغلق', 'مُغطًّى', 'مفتوح') as $k) {
    $n = count($stat[$k]);
    $w = $sumW($stat[$k]);
    $p('| ' . $k . ' | **' . $n . '** | ' . round($n * 100 / max(1, count($rows)), 1) . '٪ | '
       . round($w * 100 / max(0.01, $totalW), 1) . '٪ |');
}
$p('');

/* ── الخطورة ───────────────────────────────────────────────────────────── */
$p('### حسب الخطورة');
$p('');
$p('| الخطورة | الكل | مُغلق | مُغطًّى | مفتوح |');
$p('|---|---|---|---|---|');
foreach (array('P0', 'P1', 'P2', 'P3', 'P4') as $s) {
    $all = 0; $c = 0; $cv = 0; $o = 0;
    foreach ($rows as $r) { if ($r['sev'] === $s) { $all++; } }
    foreach ($stat['مُغلق'] as $r) { if ($r['sev'] === $s) { $c++; } }
    foreach ($stat['مُغطًّى'] as $r) { if ($r['sev'] === $s) { $cv++; } }
    foreach ($stat['مفتوح'] as $r) { if ($r['sev'] === $s) { $o++; } }
    $mark = ($all > 0 && $c === $all) ? ' ✔' : '';
    $p('| **' . $s . '** | ' . $all . ' | **' . $c . '**' . $mark . ' | ' . $cv . ' | ' . $o . ' |');
}
$p('');

/* ── الصعوبة ───────────────────────────────────────────────────────────── */
$p('## ③ المتبقي بثلاثِ درجاتِ صعوبة');
$p('');
$p('**قاعدةُ التصنيف (مُعلَنةٌ لا تقديرية):**');
$p('- **سهل** — موضعٌ واحدٌ وتغييرٌ ميكانيكيٌّ: تسميةٌ · زرٌّ مكسورٌ · موضعُ رابطٍ · دليلٌ ناقص.');
$p('- **متوسط** — يلزمه خدمةُ نطاقٍ أو ترحيلٌ أو مسٌّ لإدارةٍ واحدة.');
$p('- **صعب** — عابرٌ للإدارات أو معماريٌّ أو شاشةٌ مفقودةٌ أو يلزمه قرارُ مالك.');
$p('- ◆ ورفعُ درجةٍ لكلِّ بندٍ خطورتُه **P0** — فاتساعُ أثرِه يرفع كلفةَ إصلاحِه.');
$p('');

$remaining = array_merge($stat['مُغطًّى'], $stat['مفتوح']);
$byDiff = array('سهل' => array(), 'متوسط' => array(), 'صعب' => array());
foreach ($remaining as $r) {
    $d = difficulty($r, $EASY_KINDS, $MEDIUM_KINDS, $HARD_KINDS);
    $byDiff[$d][] = $r;
}
$p('| الدرجة | العدد | منها مُغطًّى | منها مفتوح | P1 | P2 | P3 |');
$p('|---|---|---|---|---|---|---|');
foreach (array('سهل', 'متوسط', 'صعب') as $d) {
    $L = $byDiff[$d];
    $cv = 0; $op = 0; $p1 = 0; $p2 = 0; $p3 = 0;
    foreach ($L as $r) {
        if (in_array($r, $stat['مُغطًّى'], true)) { $cv++; } else { $op++; }
        if ($r['sev'] === 'P1') { $p1++; }
        if ($r['sev'] === 'P2') { $p2++; }
        if ($r['sev'] === 'P3') { $p3++; }
    }
    $p('| **' . $d . '** | **' . count($L) . '** | ' . $cv . ' | ' . $op . ' | ' . $p1 . ' | ' . $p2 . ' | ' . $p3 . ' |');
}
$p('| — | **' . count($remaining) . '** | ' . count($stat['مُغطًّى']) . ' | ' . count($stat['مفتوح']) . ' | | | |');
$p('');

/* ── تفصيلُ الصعبِ حسب النوع ──────────────────────────────────────────── */
foreach (array('صعب', 'متوسط', 'سهل') as $d) {
    $byKind = array();
    foreach ($byDiff[$d] as $r) { $byKind[$r['kind']] = ($byKind[$r['kind']] ?? 0) + 1; }
    arsort($byKind);
    $parts = array();
    foreach ($byKind as $k => $n) { $parts[] = $k . ' (' . $n . ')'; }
    $p('**' . $d . ' — ' . count($byDiff[$d]) . ':** ' . implode(' · ', $parts));
    $p('');
}

/* ── الإدارات الأثقل ──────────────────────────────────────────────────── */
$p('### أثقلُ الإداراتِ في المتبقي');
$p('');
$byDept = array();
foreach ($remaining as $r) { $byDept[$r['dept']] = ($byDept[$r['dept']] ?? 0) + 1; }
arsort($byDept);
$p('| الإدارة | المتبقي |');
$p('|---|---|');
$i = 0;
foreach ($byDept as $k => $n) { if ($i++ >= 8) { break; } $p('| ' . $k . ' | ' . $n . ' |'); }
$p('');

/* ── النسبة ───────────────────────────────────────────────────────────── */
$pctCount = round(count($stat['مُغلق']) * 100 / max(1, count($rows)), 1);
$pctW     = round($closedW * 100 / max(0.01, $totalW), 1);
$pctWc    = round(($closedW + $coveredW) * 100 / max(0.01, $totalW), 1);

$p('## ④ نسبةُ الإنجاز');
$p('');
$p('| المقياس | النسبة | ما يعنيه |');
$p('|---|---|---|');
$p('| **بالعدد المجرَّد** | **' . $pctCount . '٪** | ' . count($stat['مُغلق']) . ' مغلقةً من ' . count($rows) . ' — ويسوّي P0 بـP4 فيُضلِّل |');
$p('| **مرجَّحًا بالخطورة (مُغلق)** | **' . $pctW . '٪** | بأوزان P0=13 · P1=5 · P2=2 · P3=1 · P4=0.5 |');
$p('| **مرجَّحًا (مُغلق + مُغطًّى)** | **' . $pctWc . '٪** | السقفُ الأعلى لو حُسب المُغطَّى إنجازًا — وهو ما لا نفعله |');
$p('| **الحواجب (P0)** | **100٪** | 13/13 بشاهدٍ مُشغَّلٍ لكلٍّ |');
$p('');
$p('◆ **المقياسُ المعتمَد: ' . $pctW . '٪** — مرجَّحًا بالخطورةِ وبحالةِ «مُغلق» وحدَها.');
$p('والفرقُ بينه وبين ' . $pctWc . '٪ هو حجمُ ما أُصلحت آليتُه ولم يُشهَد له منفردًا.');
$p('');

$md = implode("\n", $out) . "\n";
if ($mdOut) { @file_put_contents($mdOut, $md); echo "تقرير: {$mdOut}\n"; }
echo $md;
