/* «مُغطًّى»: أُصلحت **آليتُه المشتركة** بشاهدٍ مُشغَّل (AC-P1A · AC-P1B)، ولم
   يُشغَّل اختبارُ قبولِ كلِّ ملاحظةٍ منفردةً. ولا يُعدُّ إغلاقًا. */
$COVERED_KINDS = array('Permission Gap', 'Governance Gap');
$COVERED_MIN_SEV = 'P1';

/* ══ ② الصعوبة — قاعدةٌ معلَنة ═══════════════════════════════════════════ */
$EASY_KINDS   = array('Wrong Label', 'Broken Button', 'Wrong Sidebar Placement', 'Missing Evidence');
$MEDIUM_KINDS = array('Data Mismatch', 'Export/Import Gap', 'Event/Integration Gap',
                      'Permission Gap', 'Governance Gap', 'Risk/Governance Gap', 'Wrong Owner');
$HARD_KINDS   = array('Missing Screen', 'Duplicate Screen', 'Wrong Workflow', 'Not Testable');

function difficulty($r, $EASY, $MED, $HARD)
{
    $k = $r['kind'];
    if (in_array($k, $HARD, true)) { return 'صعب'; }
    // P0/P1 عابرةُ الإدارات ترفع الدرجة — والخطورةُ مؤشرُ اتساعٍ لا شدةٍ فقط
    if (in_array($k, $EASY, true)) { return ($r['sev'] === 'P0') ? 'متوسط' : 'سهل'; }
    if (in_array($k, $MED, true))  { return ($r['sev'] === 'P0') ? 'صعب' : 'متوسط'; }
    return 'متوسط';
}

/* ══ ③ التصنيف ═════════════════════════════════════════════════════════ */
$stat = array('مُغلق' => array(), 'مُغطًّى' => array(), 'مفتوح' => array());
foreach ($rows as $r) {
    if (in_array($r['id'], $CLOSED, true)) { $stat['مُغلق'][] = $r; continue; }
    if (in_array($r['kind'], $COVERED_KINDS, true) && in_array($r['sev'], array('P0', 'P1'), true)) {
        $stat['مُغطًّى'][] = $r; continue;
    }
    $stat['مفتوح'][] = $r;
}

/* ══ ④ الأوزان — P0 لا يساوي P4 ═════════════════════════════════════════ */
$W = array('P0' => 13, 'P1' => 5, 'P2' => 2, 'P3' => 1, 'P4' => 0.5);
$sumW = function ($list) use ($W) {
    $s = 0.0;
    foreach ($list as $r) { $s += ($W[$r['sev']] ?? 1); }
    return $s;
};
$totalW   = $sumW($rows);
$closedW  = $sumW($stat['مُغلق']);
$coveredW = $sumW($stat['مُغطًّى']);

/* ══ ⑤ الإخراج ══════════════════════════════════════════════════════════ */
$out = array();
$p = function ($s = '') use (&$out) { $out[] = $s; };

$p('# تقريرُ حالةِ الحزمة — إكوبيشن · منصة إنجاز');
$p('');
$p('**تاريخ القياس:** ' . date('Y-m-d H:i') . ' · **المصدر:** السجلُّ الجامعُ الحيُّ ووثائقُ FIX الثلاث');
$p('');
$p('> **قاعدةُ هذا التقرير:** لا يُعلَن بندٌ «مُغلقًا» إلا وله **شاهدٌ مُشغَّلٌ**');
$p('> في أحدِ الفواحص. وما أُصلحت آليتُه المشتركةُ ولم يُشغَّل اختبارُ قبولِه');
$p('> منفردًا يُعلَن **«مُغطًّى»** — وهي حالةٌ بين الإصلاحِ والإغلاقِ لا تُحسب');
$p('> إنجازًا كاملًا. فالفرقُ بينهما هو عينُ ما تحذّر منه الوثائق.');
$p('');

/* ── المخزونان ─────────────────────────────────────────────────────────── */
$p('## ① المخزونان — ولا يُجمعان');
