    $rows[] = array(
        'id' => $c[0], 'doc' => $c[1], 'dept' => $c[3], 'screen' => $c[4],
        'kind' => $c[9], 'sev' => $c[10], 'blocks' => $c[18], 'test' => $c[20],
    );
}
fclose($fh);

/* ══ ① الحالة — بقوائمَ صريحةٍ لا استنتاج ═══════════════════════════════
