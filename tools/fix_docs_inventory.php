    'AC-U9' => 'سهل', 'AC-U10' => 'متوسط', 'AC-U11' => 'متوسط', 'AC-U12' => 'صعب',
);

/* ══ ②-ب تجاوزاتٌ بمعرِّفِ الحكمِ — لأحكامٍ لا تحمل رمزًا معياريًّا ══════ */
$ID_STATE = array(
    /* CL-01..CL-05 قواعدُ الإغلاق — التُزمت في كلِّ بندٍ أُعلن: «الإصلاحُ وحدَه
       لا يُغلق بندًا» هو عينُ التمييزِ بين «مُغلق» و«مُغطًّى» في تقاريرِنا،
       و«درجةُ التحققِ تُعلَن مع كلِّ بند» هو عمودُ الحالةِ نفسُه. */
    'FIXA-0045' => 'مُغلق', 'FIXA-0046' => 'مُغلق', 'FIXA-0047' => 'مُغلق',
    'FIXA-0048' => 'مُغلق', 'FIXA-0049' => 'مُغلق',
);
$ID_DIFF = array();
/* الشاشاتُ التمثيليةُ الثماني — إعادةُ بناءٍ كاملةٍ لا تعديلُ نمط */
for ($i = 60; $i <= 68; $i++) { $ID_DIFF[sprintf('FIXB-%04d', $i)] = 'صعب'; }

/* ══ ③ الاستخراج ═══════════════════════════════════════════════════════ */
$all = array();
foreach ($DOCS as $docName => $meta) {
    $path = rtrim($dir, "/\\") . '/' . $meta['f'];
    if (!is_file($path)) { continue; }
    $txt = file_get_contents($path);
    $pre = $meta['p'];
    // كلُّ سطرِ جدولٍ يبدأ ببندٍ ذريّ
    if (!preg_match_all('/^\|\s*(' . $pre . '-(\d{4}))-([^\s|]+)\s*\|(.*)$/mu', $txt, $m, PREG_SET_ORDER)) {
        continue;
    }
    foreach ($m as $row) {
        $ruling = $row[1];
        $body   = $row[4];
        if (!isset($all[$ruling])) {
            $all[$ruling] = array('doc' => $docName, 'clauses' => 0, 'text' => '');
        }
        $all[$ruling]['clauses']++;
        $all[$ruling]['text'] .= ' ' . $body;
    }
}

/* ══ ④ الحكم ═══════════════════════════════════════════════════════════ */
$codeRe = '/\b(CS-\d{2}|RF-\d{2}|GT-\d{2}|FN-\d{2}|SH-\d{2}|MD-\d{2}|AC-U\d{1,2}|AC-F\d{1,2})\b/u';
foreach ($all as $id => &$r) {
    preg_match_all($codeRe, $r['text'], $cm);
    $codes = array_values(array_unique($cm[1]));
    $r['codes'] = $codes;

    // الحالة: أسوأُ حالةٍ بين رموزِه — فحكمٌ يمسّ رمزين لا يُغلَق بأحدِهما
    $rank  = array('مُغلق' => 0, 'مُغطًّى' => 1, 'مفتوح' => 2);
    $state = null;
    foreach ($codes as $c) {
        if (!isset($CODE_STATE[$c])) { continue; }
        $s = $CODE_STATE[$c];
        if ($state === null || $rank[$s] > $rank[$state]) { $state = $s; }
    }
    if ($state === null) {
        // بلا رمزٍ معياريّ: أحكامُ المنهجِ والحوكمةِ والشواهد
        $t = $r['text'];
        if (preg_match('/اختبارُ منهج|شاهدِ قبول|موضعٌ ونمطٌ|بالملفِّ والسطر/u', $t)) {
            $state = 'مُغلق';               // منهجٌ التُزم به في كلِّ ما نُفِّذ
        } elseif (preg_match('/قرارُ مالك|يقرّره المالك|يعتمده المالك/u', $t)) {
            $state = 'قرارُ مالك';
        } else {
            $state = 'مفتوح';
        }
    }
    if (isset($ID_STATE[$id])) { $state = $ID_STATE[$id]; }
    $r['state'] = $state;

    // الصعوبة
    $drank = array('سهل' => 0, 'متوسط' => 1, 'صعب' => 2);
    $diff  = null;
    foreach ($codes as $c) {
        if (!isset($CODE_DIFF[$c])) { continue; }
        if ($diff === null || $drank[$CODE_DIFF[$c]] > $drank[$diff]) { $diff = $CODE_DIFF[$c]; }
    }
    $r['diff'] = $ID_DIFF[$id] ?? ($diff ?: 'متوسط');
}
unset($r);

/* ══ ⑤ الإخراج ═════════════════════════════════════════════════════════ */
$out = array();
$p = function ($s = '') use (&$out) { $out[] = $s; };

$totalRulings = count($all);
$totalClauses = 0;
foreach ($all as $r) { $totalClauses += $r['clauses']; }

$p('# جردُ وثائقِ FIX — كلُّ حكمٍ بحالتِه');
$p('');
$p('**القياس:** ' . date('Y-m-d H:i') . ' · **' . $totalRulings . ' حكمًا** في **'
   . $totalClauses . ' بندًا ذريًّا** عبر ثلاثِ وثائق');
$p('');

/* حسب الوثيقة */
$p('## ① لكلِّ وثيقةٍ حصيلتُها');
$p('');
$p('| الوثيقة | الأحكام | البنودُ الذرية | مُغلق | مُغطًّى | مفتوح | قرارُ مالك | ٪ مُغلق |');
$p('|---|---|---|---|---|---|---|---|');
$perDoc = array();
foreach ($all as $id => $r) {
    $d = $r['doc'];
    if (!isset($perDoc[$d])) {
        $perDoc[$d] = array('n' => 0, 'cl' => 0, 'مُغلق' => 0, 'مُغطًّى' => 0, 'مفتوح' => 0, 'قرارُ مالك' => 0);
    }
    $perDoc[$d]['n']++;
    $perDoc[$d]['cl'] += $r['clauses'];
    $perDoc[$d][$r['state']]++;
}
$g = array('n' => 0, 'cl' => 0, 'مُغلق' => 0, 'مُغطًّى' => 0, 'مفتوح' => 0, 'قرارُ مالك' => 0);
foreach ($DOCS as $d => $_) {
    if (!isset($perDoc[$d])) { continue; }
    $x = $perDoc[$d];
    foreach ($g as $k => $v) { $g[$k] += $x[$k]; }
    $p('| ' . $d . ' | **' . $x['n'] . '** | ' . $x['cl'] . ' | **' . $x['مُغلق'] . '** | '
       . $x['مُغطًّى'] . ' | ' . $x['مفتوح'] . ' | ' . $x['قرارُ مالك'] . ' | **'
       . round($x['مُغلق'] * 100 / max(1, $x['n']), 1) . '٪** |');
}
$p('| **المجموع** | **' . $g['n'] . '** | **' . $g['cl'] . '** | **' . $g['مُغلق'] . '** | '
   . $g['مُغطًّى'] . ' | ' . $g['مفتوح'] . ' | ' . $g['قرارُ مالك'] . ' | **'
   . round($g['مُغلق'] * 100 / max(1, $g['n']), 1) . '٪** |');
$p('');

/* المتبقي بالصعوبة */
$p('## ② المتبقي من الوثائقِ بثلاثِ درجات');
$p('');
$rem = array('سهل' => array(), 'متوسط' => array(), 'صعب' => array());
foreach ($all as $id => $r) {
    if ($r['state'] === 'مُغلق') { continue; }
    $rem[$r['diff']][] = $id . ($r['codes'] ? ' (' . implode(',', $r['codes']) . ')' : '');
}
$p('| الدرجة | عددُ الأحكام |');
$p('|---|---|');
$tot = 0;
foreach (array('سهل', 'متوسط', 'صعب') as $d) { $p('| **' . $d . '** | **' . count($rem[$d]) . '** |'); $tot += count($rem[$d]); }
$p('| — | **' . $tot . '** |');
$p('');
foreach (array('صعب', 'متوسط', 'سهل') as $d) {
    if (!$rem[$d]) { continue; }
    $p('**' . $d . ':** ' . implode(' · ', array_slice($rem[$d], 0, 40))
       . (count($rem[$d]) > 40 ? ' … (+' . (count($rem[$d]) - 40) . ')' : ''));
    $p('');
}

/* حالةُ الرموزِ المعيارية */
$p('## ③ الرموزُ المعياريةُ بحالتِها');
$p('');
$p('| الرمز | الحالة | | الرمز | الحالة | | الرمز | الحالة |');
$p('|---|---|---|---|---|---|---|---|');
$keys = array_keys($CODE_STATE);
for ($i = 0; $i < count($keys); $i += 3) {
    $cells = array();
    for ($j = 0; $j < 3; $j++) {
        $k = $keys[$i + $j] ?? null;
        $cells[] = $k ? ('`' . $k . '` | ' . ($CODE_STATE[$k] === 'مُغلق' ? '**مُغلق** ✔' : $CODE_STATE[$k])) : ' | ';
    }
    $p('| ' . implode(' | | ', $cells) . ' |');
}
$p('');

$pct = round($g['مُغلق'] * 100 / max(1, $g['n']), 1);
$pctc = round(($g['مُغلق'] + $g['مُغطًّى']) * 100 / max(1, $g['n']), 1);
$p('## ④ النسبة');
$p('');
$p('- **مُغلقٌ بشاهدٍ مُشغَّل: ' . $pct . '٪** (' . $g['مُغلق'] . ' من ' . $g['n'] . ' حكمًا)');
$p('- سقفُه لو حُسب المُغطَّى: **' . $pctc . '٪**');
$p('');

$md = implode("\n", $out) . "\n";
if ($mdOut) { @file_put_contents($mdOut, $md); echo "تقرير: {$mdOut}\n"; }
echo $md;
