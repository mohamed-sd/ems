    'MD-05' => 'مُغلق', 'RF-04' => 'مُغلق',
);

/* ══ ② الصعوبةُ لكلِّ رمز — بقاعدةٍ معلَنة ═══════════════════════════════ */
$CODE_DIFF = array(
    'GT-02' => 'متوسط', 'CS-05' => 'متوسط', 'CS-12' => 'صعب',
