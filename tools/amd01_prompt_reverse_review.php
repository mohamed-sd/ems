$norm = function ($s) {
    $s = preg_replace('~^\s*>+\s?~mu', '', (string) $s);   /* اقتباسُ ماركداون */
    $s = preg_replace('~[*`_]~u', '', $s);                 /* زينةُ ماركداون  */
    $s = preg_replace('~[\x{064B}-\x{0652}\x{0653}-\x{0655}\x{0670}\x{0640}]~u', '', $s);
    $s = preg_replace('~[\x{0622}\x{0623}\x{0625}]~u', "\u{0627}", $s);
    $s = preg_replace('~\x{0649}~u', "\u{064A}", $s);
    $s = preg_replace('~\x{0629}~u', "\u{0647}", $s);
    /* ③ **عطبٌ ثالثٌ وقع فعلًا في هذه الجولة**: الرقمُ الهنديُّ والعربيُّ تمثيلان
       لعددٍ واحد — فمرساةُ «٢١» رسَبَت على نصٍّ يكتبها «21»، **وهو عينُ عائلةِ
       «المقارنةِ بين تمثيلَين لشيءٍ واحد»**. فتُطوى الأرقامُ إلى صورةٍ واحدة.
       ⛔ **وهذا لا يُضعِّف مرساةً**: توحيدُ تمثيلِ العددِ لا يُمرِّر عددًا آخر. */
    $s = strtr($s, array('٠'=>'0','١'=>'1','٢'=>'2','٣'=>'3','٤'=>'4',
                         '٥'=>'5','٦'=>'6','٧'=>'7','٨'=>'8','٩'=>'9','٫'=>'.'));
    $s = preg_replace('~\s+~u', ' ', $s);
    return $s;
};
