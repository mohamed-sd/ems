<?php
/**
 * tools/repair01_migration_gate_negative.php — كسرُ البوّابةِ عمدًا وردُّها
 * ═══════════════════════════════════════════════════════════════════════════
 * **الدستور ④**: «**حاجبٌ لم يُكسَر عمدًا حاجبٌ غيرُ مُثبَت** — وكلُّ بوّابةٍ
 * تُثبَت باختبارٍ سالبٍ يفشل فعلًا». **و`RPR-02` §٩ يوجبها نصًّا**: «وتُثبَت
 * باختبارٍ سالب: هجرةٌ صوريّةٌ لا تسجّل نفسَها ⇒ **ترسُب فعلًا**».
 *
 * ◆ **وثلاثُ محاولاتٍ لا واحدة** — فبوّابةٌ تردُّ حالةً وتُمرِّر أختَها ليست
 *   بوّابة:
 *   ① هجرةٌ صوريّةٌ **لا تستدعي الدفتر** ⇒ يجب أن يرسُب `G-MIG-01` و`G-MIG-02`.
 *   ② هجرةٌ صوريّةٌ **تستدعي الدفترَ ولم تُشغَّل** ⇒ `G-MIG-01` يمرُّ و`G-MIG-02`
 *      يرسُب — **فالاستدعاءُ نيّةٌ والقيدُ فعل**.
 *   ③ اسمٌ خارجَ عُرفِ التسمية ⇒ يجب أن يرسُب `G-MIG-04`.
 *
 * ◆ **والقياسُ قبلَ وبعد**: تُقرأ حالةُ البوّابةِ أوّلًا، ثمَّ تُكسَر، ثمَّ
 *   **يُتحقَّق أنّها عادت إلى حالتِها بالضبط** — ⛔ فاختبارٌ سالبٌ يترك أثرًا
 *   يُفسد ما بعده.
 *
 * ⛔ **ولا يُشغَّل ملفٌّ صوريٌّ قطُّ**: يُكتب ويُقاس ويُحذف — ولا يمسُّ القاعدةَ.
 *
 * التشغيل: php tools/repair01_migration_gate_negative.php
 * الخروج:  0 كلُّ المحاولاتِ رُدَّت · 1 محاولةٌ نفذت — **والبوّابةُ تجميليّة**
 * ═══════════════════════════════════════════════════════════════════════════
 */
if (php_sapi_name() !== 'cli') { exit("CLI فقط\n"); }
error_reporting(E_ALL & ~E_DEPRECATED);
mb_internal_encoding('UTF-8');
$ROOT = dirname(__DIR__);
$DIR  = $ROOT . '/database/migrations';
$GATE = $ROOT . '/tools/repair01_migration_gate.php';

/** يُشغِّل البوّابةَ ويعيد [رمزَ الخروج, النصّ] */
$runGate = function () use ($GATE) {
    $o = array(); $rc = 0;
    exec('"' . PHP_BINARY . '" ' . escapeshellarg($GATE) . ' 2>&1', $o, $rc);
    return array($rc, implode("\n", $o));
};
/** هل رسَب حاجبٌ بعينِه في النصّ؟ */
$failed = function ($txt, $code) { return strpos($txt, '✘ **`' . $code . '`**') !== false; };
/**
 * أعدادُ سطرِ الحاجبِ نفسِه — ⛔ **ورسوبُ الحاجبِ وحدَه لا يُثبت شيئًا هنا**:
 * فالبوّابةُ راسبةٌ سلفًا بسبعٍ وخمسين، فـ«رسَب بعدَ الكسر» يصدُق ولو لم تُحدث
 * الهجرةُ الصوريّةُ أثرًا. **والدليلُ أن يتحرّك عدَدُ الحاجبِ بواحدٍ بالضبط ثمَّ
 * يعود** — وهذا هو الفرقُ بين حاجبٍ يعمل وأخضرَ كاذبٍ في ثوبِ أحمر.
 */
$nums = function ($txt, $code) {
    foreach (explode("\n", $txt) as $l) {
        if (strpos($l, '**`' . $code . '`**') !== false) {
            preg_match_all('/\*\*(\d+)\*\*/', $l, $m);
            return array_map('intval', $m[1]);
        }
    }
    return null;
};
/** فرقُ متجهَين — يُعيد نصًّا مقروءًا */
$delta = function ($a, $b) {
    if (!is_array($a) || !is_array($b) || count($a) !== count($b)) { return 'متجهان غيرُ قابلَين للمقارنة'; }
    $d = array();
    foreach ($a as $i => $v) { $d[] = ($b[$i] - $v); }
    return '[' . implode(',', $d) . ']';
};

$made = array(); $pass = 0; $total = 0; $log = array();
$say = function ($s) use (&$log) { $log[] = $s; echo $s . "\n"; };

/* ── القياسُ قبلَ الكسر ──────────────────────────────────────────────────── */
list($rc0, $txt0) = $runGate();
$say(sprintf('◆ الحالُ قبلَ الكسر: رمزُ الخروجِ **%d**%s', $rc0,
    $rc0 ? ' — البوّابةُ راسبةٌ سلفًا، **والاختبارُ يقيس تغيُّرَ الحاجبِ المعنيِّ لا الرمزَ وحدَه**' : ''));
$before = array(
    'G-MIG-01' => $failed($txt0, 'G-MIG-01'),
    'G-MIG-02' => $failed($txt0, 'G-MIG-02'),
    'G-MIG-04' => $failed($txt0, 'G-MIG-04'),
);
/* المتجهاتُ الأساسُ — يُقاس الفرقُ عنها لا الرسوبُ وحدَه */
$base1 = $nums($txt0, 'G-MIG-01');
$base2 = $nums($txt0, 'G-MIG-02');
$base4 = $nums($txt0, 'G-MIG-04');
$say(sprintf('   المتجهاتُ الأساس: `G-MIG-01`=%s · `G-MIG-02`=%s · `G-MIG-04`=%s',
    json_encode($base1), json_encode($base2), json_encode($base4)));

/* ── المحاولةُ ① · هجرةٌ لا تسجّل نفسَها ─────────────────────────────────── */
$total++;
$f1 = $DIR . '/2099_01_01_negative_probe_no_ledger.php';
file_put_contents($f1, "<?php\n/* هجرةٌ صوريّةٌ للاختبارِ السالب — لا تستدعي الدفترَ ولا تُشغَّل */\n"
    . "if (php_sapi_name() !== 'cli') { exit; }\n"
    . "exit(\"probe: لا تُشغَّل\\n\");\n");
$made[] = $f1;
list($rc1, $txt1) = $runGate();
$n1a = $nums($txt1, 'G-MIG-01'); $n1b = $nums($txt1, 'G-MIG-02');
/* المتوقَّعُ بالضبط: كلُّ عدادٍ في السطرَين يزيد واحدًا — لا رسوبًا مجرَّدًا */
$d1a = $delta($base1, $n1a); $d1b = $delta($base2, $n1b);
$hit1 = $failed($txt1, 'G-MIG-01') && $failed($txt1, 'G-MIG-02') && $rc1 === 1
        && $d1a === '[1,1,1,1]' && $d1b === '[1,1,1]';
if ($hit1) { $pass++; }
$say(sprintf('%s **المحاولة ①** هجرةٌ لا تستدعي الدفتر ⇒ %s',
    $hit1 ? '✔' : '✘',
    $hit1 ? '`G-MIG-01` و`G-MIG-02` رسَبا (rc=1) **وعدّاداهما تحرّكا بواحدٍ بالضبط** '
            . $d1a . $d1b . ' — **رُدَّت**'
          : '⛔ **لم تُردَّ بدليلٍ كافٍ** — G-MIG-01=' . ($failed($txt1, 'G-MIG-01') ? 'رسَب' : 'مرَّ')
            . ' فرقُه ' . $d1a . ' · G-MIG-02=' . ($failed($txt1, 'G-MIG-02') ? 'رسَب' : 'مرَّ')
            . ' فرقُه ' . $d1b . ' · rc=' . $rc1));
@unlink($f1); array_pop($made);

/* ── المحاولةُ ② · تستدعي الدفترَ ولم تُشغَّل ────────────────────────────── */
$total++;
$f2 = $DIR . '/2099_01_02_negative_probe_calls_ledger.php';
file_put_contents($f2, "<?php\n/* هجرةٌ صوريّةٌ تستدعي الدفترَ ولا تُشغَّل — الاستدعاءُ نيّةٌ والقيدُ فعل */\n"
    . "if (php_sapi_name() !== 'cli') { exit; }\n"
    . "exit(\"probe: لا تُشغَّل\\n\");\n"
    . "/* ems_migration_recorded(__FILE__, \$conn); */\n");
$made[] = $f2;
list($rc2, $txt2) = $runGate();
$n2a = $nums($txt2, 'G-MIG-01'); $n2b = $nums($txt2, 'G-MIG-02');
/* الاستدعاءُ موجودٌ ⇒ عدّادا «بلا استدعاء» و«بلا حكم» **لا يتحرّكان**،
   والمقامُ يتحرّك · والقيدُ غائبٌ ⇒ `G-MIG-02` يتحرّك كلُّه */
$d2a = $delta($base1, $n2a); $d2b = $delta($base2, $n2b);
$hit2 = $failed($txt2, 'G-MIG-02') && $rc2 === 1
        && $d2a === '[1,1,0,0]' && $d2b === '[1,1,1]';
if ($hit2) { $pass++; }
$say(sprintf('%s **المحاولة ②** تستدعي الدفترَ ولم تُشغَّل ⇒ %s',
    $hit2 ? '✔' : '✘',
    $hit2 ? '`G-MIG-02` تحرَّك ' . $d2b . ' · و«بلا استدعاءٍ» لم يتحرّك ' . $d2a
            . ' — **القيدُ فعلٌ لا نيّة**'
          : '⛔ **لم تُردَّ بدليلٍ كافٍ** — G-MIG-02 فرقُه ' . $d2b
            . ' · G-MIG-01 فرقُه ' . $d2a . ' · rc=' . $rc2));
@unlink($f2); array_pop($made);

/* ── المحاولةُ ③ · اسمٌ خارجَ عُرفِ التسمية ─────────────────────────────── */
$total++;
$f3 = $DIR . '/negative_probe_unmanaged.php';
file_put_contents($f3, "<?php\n/* اسمٌ خارجَ عُرفِ التسميةِ — يجب أن يُعلَن بحكمِه لا أن يُتجاهَل */\nexit;\n");
$made[] = $f3;
list($rc3, $txt3) = $runGate();
$n3 = $nums($txt3, 'G-MIG-04');
$d3 = $delta($base4, $n3);
$hit3 = $failed($txt3, 'G-MIG-04') && $rc3 === 1 && $d3 === '[1,1]';
if ($hit3) { $pass++; }
$say(sprintf('%s **المحاولة ③** اسمٌ خارجَ العُرف ⇒ %s',
    $hit3 ? '✔' : '✘',
    $hit3 ? '`G-MIG-04` رسَب وعدّادُه تحرَّك ' . $d3 . ' — **رُدَّت**'
          : '⛔ **لم تُردَّ بدليلٍ كافٍ** — G-MIG-04 فرقُه ' . $d3 . ' · rc=' . $rc3));
@unlink($f3); array_pop($made);

/* ── الرجوعُ إلى الحالِ الأوّل — ⛔ فاختبارٌ يترك أثرًا يُفسد ما بعده ────── */
foreach ($made as $f) { @unlink($f); }
list($rc4, $txt4) = $runGate();
$after = array(
    'G-MIG-01' => $failed($txt4, 'G-MIG-01'),
    'G-MIG-02' => $failed($txt4, 'G-MIG-02'),
    'G-MIG-04' => $failed($txt4, 'G-MIG-04'),
);
$restored = ($rc4 === $rc0) && ($after == $before);
$say(sprintf('%s **الرجوع** رمزُ الخروجِ عاد **%d** (كان %d) وحالُ الحواجبِ %s',
    $restored ? '✔' : '✘', $rc4, $rc0, $restored ? 'مطابقةٌ لما قبل' : '**مختلفةٌ — أثرٌ بقي**'));

$ok = ($pass === $total) && $restored;
echo "\n" . sprintf('**النتيجة: %d/%d محاولةً رُدَّت%s — %s**', $pass, $total,
    $restored ? ' والحالُ عاد' : ' ⛔ **والحالُ لم يعد**',
    $ok ? '✔ **البوّابةُ مُثبَتةٌ بالكسر**' : '⛔ **البوّابةُ غيرُ مُثبَتة**') . "\n";
exit($ok ? 0 : 1);
