function ui_scan_screens($ROOT) {
    $SKIP = array('vendor', 'node_modules', '.git', 'tools', 'tests', 'database', 'docs', 'storage', '.ssdiff', 'backups');
    $DIAC = '/[\x{064B}-\x{0652}\x{0670}]/u';
    $marks = 0; $files = 0; $cmt = 0; $total = 0;
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($ROOT, FilesystemIterator::SKIP_DOTS));
    foreach ($it as $f) {
        $p   = str_replace(chr(92), '/', $f->getPathname());
        $rel = str_replace(str_replace(chr(92), '/', $ROOT) . '/', '', $p);
        $skip = false;
        foreach ($SKIP as $s) { if (strpos($rel, $s . '/') === 0) { $skip = true; break; } }
        if ($skip || substr($p, -4) !== '.php') { continue; }
        $code = ''; $com = '';
        foreach (@token_get_all((string) file_get_contents($p)) as $t) {
            if (is_array($t)) {
                if ($t[0] === T_COMMENT || $t[0] === T_DOC_COMMENT) { $com .= $t[1]; continue; }
                $code .= $t[1];
            } else { $code .= $t; }
        }
        $n = preg_match_all($DIAC, $code);
        $cmt += preg_match_all($DIAC, $com);
        $total++;
        if ($n) { $marks += $n; $files++; }
    }
    return array('marks' => $marks, 'files' => $files, 'comments' => $cmt, 'total' => $total);
}
