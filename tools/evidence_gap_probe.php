/* ══ ① الملفاتُ المسمّاةُ في اختبارِ القبولِ أو الإصلاح ═══════════════════ */
function named_paths($txt)
{
    $out = array();
    /* مسارٌ داخلَ علاماتٍ خلفيةٍ أو عاديًّا — بامتدادِ php/sql/md/js/css */
    if (preg_match_all('#(?:`|\s|^|\()([A-Za-z0-9_./\-]+\.(?:php|sql|md|js|css|tsv|json))#u', $txt, $m)) {
        foreach ($m[1] as $p) {
            $p = trim($p, '`.,;:()');
            if ($p === '' || strlen($p) < 6) { continue; }
            $out[$p] = 1;
        }
    }
    return array_keys($out);
}
/* الجداولُ المسمّاة */
function named_tables($txt)
{
    $out = array();
    if (preg_match_all('#`([a-z][a-z0-9_]{3,})`#u', $txt, $m)) {
        foreach ($m[1] as $t) { if (strpos($t, '.') === false) { $out[$t] = 1; } }
    }
    return array_keys($out);
}

/* هل الأداةُ موجودةٌ وتعمل؟ */
$runCache = array();
function tool_ok($ROOT, $rel, $doRun, &$runCache)
{
    $abs = $ROOT . '/' . ltrim($rel, '/');
    if (!is_file($abs)) { return array(false, 'الملفُّ غيرُ موجود'); }
    if (!$doRun || substr($rel, -4) !== '.php' || strpos($rel, 'tools/') !== 0) {
        return array(true, 'موجودٌ (لم يُشغَّل)');
    }
    if (isset($runCache[$rel])) { return $runCache[$rel]; }
    $out = (string) @shell_exec(escapeshellarg(PHP_BINARY) . ' ' . escapeshellarg($abs) . ' 2>&1');
    $bad = (stripos($out, 'Fatal error') !== false) || (stripos($out, 'Parse error') !== false);
    $res = array(!$bad, $bad ? 'يُشغَّل فيرمي خطأً' : 'يُشغَّل بلا خطأ');
    $runCache[$rel] = $res;
    return $res;
}
function table_rows($db, $t)
{
    $r = $db->query('SELECT COUNT(*) FROM `' . $t . '`');
    return $r ? (int) $r->fetch_row()[0] : null;
}

