        continue;
    }
    $hits = array();
    foreach ($FAM as $type => $toks) {
        foreach ($toks as $t) {
            if (mb_strpos($hay, $t) !== false) { $hits[$type] = $t; break; }
        }
    }
    if (!$hits) { $none[] = $id; continue; }
    /* الغلبةُ المعلنةُ تحسم التعدّد — فلا التباسَ إلا بلا غالب (مستحيلٌ هنا
