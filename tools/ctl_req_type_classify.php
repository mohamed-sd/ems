        if (isset($hits[$type])) {
            $why = 'مفردةُ الحسم «' . $hits[$type] . '» من الدفترِ الحاكم';
            $loser = array();
            foreach ($hits as $t2 => $tok2) { if ($t2 !== $type) { $loser[] = $t2 . ':«' . $tok2 . '»'; } }
            if ($loser) { $why .= ' — وغلبت ' . implode(' و', $loser) . ' بسلّمِ الغلبةِ المعلن'; }
            $judged[$id] = array($type, $why);
            $cnt[$type] = 1 + (isset($cnt[$type]) ? $cnt[$type] : 0);
            break;
        }
    }
