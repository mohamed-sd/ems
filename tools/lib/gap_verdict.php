<?php
/**
 * tools/lib/gap_verdict.php — عقدُ حكمِ الإغلاق (GAP-56)
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ **العيبُ الذي يعالجه**: مقياسُ الإغلاقِ كان يَعُدُّ الفجوةَ مغطّاةً إن **ذكر
 *   رمزَها** فاحصٌ أخضر. فذِكرُ `GAP-23` في جملةٍ تقول «يبقى مفتوحًا بحقّ»
 *   كان يُحسب إغلاقًا. ⇒ **الذِّكرُ ليس سدًّا.**
 *
 * ◆ **والعقدُ البديل**: الحكمُ يُصرَّح به من داخلِ الفاحصِ نفسِه — بعدَ أن تجري
 *   قياساتُه — بسطرٍ آليِّ القراءة:
 *
 *       #GAPV <GAP-nn> <PASS|OPEN> <نصُّ معيارِ القبول>
 *
 *   وفجوةٌ **مذكورةٌ بلا هذا السطرِ** تُحسب `UNVERIFIED` — أي **غيرَ مغلقة**.
 *
 * ◆ **وفشلٌ صريحٌ يغلب نجاحًا صريحًا**: إن أصدر فاحصٌ `OPEN` لفجوةٍ أصدر لها
 *   غيرُه `PASS` فالحكمُ `OPEN`. لأن الإغلاقَ يلزمه سدُّ كلِّ شقوقِه لا أحدِها.
 *
 * ◆ **ولا يُصدَّر `PASS` والفاحصُ راسب**: `gapv()` تقرأ عدَّ الرسوبِ فتقلبه
 *   `OPEN` تلقائيًّا — فلا يُصرَّح بإغلاقٍ من فاحصٍ لم تمرَّ قياساتُه.
 * ═══════════════════════════════════════════════════════════════════════════
 */

if (!function_exists('gapv')) {
    /**
     * يُصدِر حكمَ فجوةٍ واحدةً بصيغةٍ آليةِ القراءة.
     *
     * @param string $code      رمزُ الفجوة — GAP-nn
     * @param bool   $sealed    هل سُدَّ العيبُ فعلًا؟ (لا: هل ذُكر)
     * @param string $criterion نصُّ معيارِ القبولِ المقيسِ — يُطبع كما هو
     * @param int    $failures  عدُّ رسوبِ الفاحص؛ أيُّ رسوبٍ يقلب الحكمَ OPEN
     */
    function gapv($code, $sealed, $criterion, $failures = 0)
    {
        $state = ($sealed && (int) $failures === 0) ? 'PASS' : 'OPEN';
        $criterion = trim(preg_replace('/\s+/u', ' ', (string) $criterion));
        echo "#GAPV {$code} {$state} {$criterion}\n";
        return $state;
    }
}

if (!function_exists('gapv_many')) {
    /**
     * حكمٌ واحدٌ لعدةِ فجواتٍ يسدُّها الفاحصُ نفسُه.
     * @param array $codes
     */
    function gapv_many(array $codes, $sealed, $criterion, $failures = 0)
    {
        foreach ($codes as $c) { gapv($c, $sealed, $criterion, $failures); }
    }
}
