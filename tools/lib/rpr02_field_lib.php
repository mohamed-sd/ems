/* ═══ ① التطبيعُ ومعيارُ الهويّة — **المعيارُ نفسُه لا معيارٌ ثانٍ** ═════════ */
function fm_norm($s)
{
    $s = (string) $s;
    $s = preg_replace('~[\x{0640}\x{064B}-\x{0652}]~u', '', $s);
    $s = str_replace(array('أ','إ','آ','ى','ة','ؤ','ئ'), array('ا','ا','ا','ي','ه','و','ي'), $s);
    $s = mb_strtolower($s, 'UTF-8');
    $s = preg_replace('~[^\p{Arabic}\p{L}\p{N}]+~u', ' ', $s);
    return trim(preg_replace('~\s+~u', ' ', $s));
}
/* ⛔ **والمفرداتُ الشائعةُ تُنزع** — «في» و«من» و«على» ترد في مئاتِ الحقولِ
   فتُنتج مطابقةً بلا معنًى، **وهي الحيلةُ نفسُها التي مُنعت في §٤·٢**. */
function fm_tok($s, $STOP)
{
    $out = array();
    foreach (explode(' ', fm_norm($s)) as $w) {
        $w = trim($w);
        if ($w === '' || mb_strlen($w) < 3 || in_array($w, $STOP, true)) { continue; }
        $out[$w] = 1;
    }
    return array_keys($out);
}
/**
 * **اسمٌ لا مفردةَ فيه** — والمعيارُ لا يبلغه.
 * ═══════════════════════════════════════════════════════════════════════════
 * ◆ **العطبُ المقيس**: خمسةُ حقولٍ في الورقةِ كلِّها اسمُها «#» (‏عمودُ التسلسلِ
 *   في السجلّ). والتطبيعُ يُسقط كلَّ ما ليس حرفًا أو رقمًا ⇒ اسمُها يصير
 *   **فارغًا**، فلا يطابقه شيءٌ أبدًا — **ولو صُيِّر عمودُه أمامَ المستخدم**.
 *   قِيس حيًّا: `ems_w14_grid` تطبع رأسَ «#» في كلِّ شبكة، والمقياسُ يقرؤه ناقصًا.
 * ◆ **فالسلبيُّ كاذبٌ بالبنيةِ لا بالبناء** — والعلاجُ **مقارنةٌ حرفيّةٌ لهذه
 *   وحدَها**: اسمٌ خلا من مفردةٍ يُطابَق بنصِّه الخامِّ في أثرِ السطح.
 * ⛔ **ولا يُوسَّع هذا إلى ذي المفردات**: شرطُ استعمالِه أن يكون `fm_norm` فارغًا،
 *   فلا يفتح بابَ إيجابٍ كاذبٍ لاسمٍ له مفرداتٌ تُقاس.
 */
function fm_literal_hit($rawName, $bagRaw)
{
    $n = trim((string) $rawName);
    if ($n === '' || !is_array($bagRaw)) { return ''; }
    return isset($bagRaw[$n]) ? 'LITERAL' : '';
}

/* **الهويّةُ بثلثَي المفردات** — معيارُ §٤·٢ نفسُه، منقولًا لا مُبتكَرًا */
function fm_hit($dTok, $bagTok, $bagStr, $dNorm)
{
    if ($dNorm !== '' && isset($bagStr[$dNorm])) { return 'EXACT'; }
    if (!$dTok) { return ''; }
    if ($dNorm !== '') {
        foreach ($bagStr as $b => $_) {
            if ($b !== '' && mb_strpos($b, $dNorm) !== false) { return 'CONTAINED'; }
        }
    }
    $sh = 0;
    foreach ($dTok as $t) { if (isset($bagTok[$t])) { $sh++; } }
    return ($sh / count($dTok) >= 2 / 3) ? 'COVER' : '';
}

/* ═══ ② الانتزاعُ من الأثر ═══════════════════════════════════════════════ */
function fm_extract($src)
{
    $lab = array(); $th = array(); $nm = array();
    if (preg_match_all('~<label[^>]*>(.*?)</label>~is', $src, $m)) {
        foreach ($m[1] as $t) { $t = trim(strip_tags($t)); if ($t !== '') { $lab[] = $t; } }
    }
    if (preg_match_all('~<th[^>]*>(.*?)</th>~is', $src, $m)) {
        foreach ($m[1] as $t) { $t = trim(strip_tags($t)); if ($t !== '') { $th[] = $t; } }
    }
    /* [\x22\x27] = علامتا الاقتباس — بالرمزِ الست عشريِّ كي لا تُقطع السلسلة */
    if (preg_match_all('~<(?:input|select|textarea)[^>]*\bname\s*=\s*[\x22\x27]([^\x22\x27]+)[\x22\x27]~i', $src, $m)) {
        foreach ($m[1] as $t) { $t = trim($t); if ($t !== '') { $nm[] = $t; } }
    }
    /* ◆ **F6 · وسمٌ يراه المستخدمُ ولا يقع في `<label>`** — وقد كان يضيع:
         هذه الشجرةُ تسمّي كثيرًا من حقولِها بـ`aria-label` (‏لقارئِ الشاشة)
         وبـ`placeholder` (‏داخلَ الخانة) بلا `<label>` منفصل. **وهما وسمانِ
         مُصيَّرانِ للمستخدمِ لا تعليقانِ للمبرمج** ⇒ فإقصاؤهما يقيس الشكلَ لا
         الحقل، **ويُنتج نقصًا كاذبًا في سطحٍ حقلُه مبنيٌّ ومُسمًّى**.
       ⛔ **ولا يُوسَّع الادّعاءُ بتوسيعِ الشاهد**: المطابقةُ تبقى كما هي
         (‏هويّةٌ · احتواءٌ · ثلثا المفردات) — والمُوسَّعُ **مادّةُ الأثرِ** لا
         قاعدةُ القبول. */
    if (preg_match_all('~\b(?:aria-label|placeholder)\s*=\s*[\x22\x27]([^\x22\x27]+)[\x22\x27]~i', $src, $m)) {
        foreach ($m[1] as $t) { $t = trim(strip_tags($t)); if ($t !== '') { $lab[] = $t; } }
    }
    /* ◆ **F7 · حقولُ نافذةِ التفاصيلِ الموحَّدة (FINAL_CLOSE ⑭)** — مبنيّةٌ
         يراها المستخدمُ في `EmsDetailsModal` وتضيع على الأثرِ الساكن: تُعلَن
         في ملفِّ السطحِ بنداءاتِ `ems_wf_field('الوسم', …)` أو ببناءاتِ
         `label:` في حمولةِ المودال أو بأزواجِ `'label' => …, 'value' =>` —
         **وسمُ حقلٍ مقرونٌ بقيمتِه لا زرٌّ ولا ترويسة** (فأزرارُ
         `$header_actions` تحمل `label` بلا `value` فلا تدخل). */
    if (preg_match_all('~ems_wf_field\s*\(\s*[\x22\x27]([^\x22\x27]+)[\x22\x27]~u', $src, $m)) {
        foreach ($m[1] as $t) { $t = trim($t); if ($t !== '') { $lab[] = $t; } }
    }
    if (preg_match_all('~[\x22\x27]?label[\x22\x27]?\s*(?:=>|:)\s*[\x22\x27]([^\x22\x27]+)[\x22\x27]\s*,\s*[\x22\x27]?value[\x22\x27]?\s*(?:=>|:)~u', $src, $m)) {
        foreach ($m[1] as $t) { $t = trim(strip_tags($t)); if ($t !== '') { $lab[] = $t; } }
    }
    if (preg_match_all('~EmsDetailsModal[\s\S]{0,4000}?~u', $src, $mDm) && strpos($src, 'EmsDetailsModal') !== false) {
        if (preg_match_all('~\blabel\s*:\s*[\x22\x27]([^\x22\x27]+)[\x22\x27]~u', $src, $m)) {
            foreach ($m[1] as $t) { $t = trim(strip_tags($t)); if ($t !== '') { $lab[] = $t; } }
        }
    }
    return array('F1' => $lab, 'F2' => $th, 'F3' => $nm);
}
/* **سبيكةُ `u13` مصرَّحةً في ملفِّ السطح** — الجسرُ إلى `gov_field_class`.
   ⛔ ولا تُشتقّ من اسمِ الملفّ: `Audit/iaf_charter.php` قد يعلن `iaf_charter`
   وقد يعلن غيرَه، **والتصريحُ أصدقُ من الشكل**. */
function fm_u13_slug($src)
{
    if (strpos($src, 'u13_screen_kit.php') === false) { return ''; }
    if (preg_match('~[\x27\x22]screen[\x27\x22]\s*=>\s*[\x27\x22]([a-z0-9_]+)[\x27\x22]~i', $src, $m)) {
        return $m[1];
    }
    return '';
}
/* **حقولُ الفعلِ في عقدِ `u13`** — `'fields' => array('k' => 'وسم')` */
function fm_u13_action_fields($src)
{
    $out = array();
    /* ⛔ **والإغلاقُ بسطرِ الإغلاقِ لا بأوّلِ قوس** — عطبٌ مقيس: النمطُ الكسولُ
       كان يقف عند أوّلِ قوسِ إغلاقٍ **داخلَ وسمٍ مقتبَس** («اسم المورد (بحث)» ·
       «(كما ورد)» · «(حي)») فيبتر بقيّةَ الكتلةِ ويُسقط حقولَها من الأثر —
       فتُقرأ ناقصةً وهي مبنيّةٌ مُسمّاة. والإغلاقُ الآن قوسٌ في صدرِ سطرِه،
       **وهو اصطلاحُ `fm_guide_cols` نفسُه**. */
    if (preg_match_all('~[\x27\x22]fields[\x27\x22]\s*=>\s*array\s*\((.*?)\n\s*\)~s', $src, $mm)) {
        foreach ($mm[1] as $blk) {
            if (preg_match_all('~=>\s*[\x27\x22]([^\x27\x22]+)[\x27\x22]~', $blk, $m2)) {
                foreach ($m2[1] as $v) { $v = trim($v); if ($v !== '') { $out[] = $v; } }
            }
        }
    }
    return $out;
}
/* **F8 · خريطةُ `$GUIDE_COLS` المصرَّحةُ في ملفِّ السطح** — اسمُ الحقلِ العربيُّ
   ⇒ مفتاحُ العمود، في مصفوفةٍ واحدةٍ يقرؤها الرأسُ والخليّةُ معًا.
   ◆ **العطبُ الذي ترفعه**: شاشةٌ تطبع رؤوسَها بحلقةٍ فوقَ خريطةٍ (وهو الصوابُ
     هندسيًّا: الرأسُ والخليّةُ لا يتفرّقان) **لا يراها F2** لأنَّ `<th>` صارت
     تعبيرَ PHP لا نصًّا. قِيس حيًّا: سطحٌ يعرض ثلاثةً وأربعين اسمًا في الصفحةِ
     المُصيَّرةِ (28/28 و15/15 بفحصٍ عبرَ الشبكة) ونزل مقيسُه **واحدًا**.
   ⛔ **والاسمُ مقيَّدٌ عمدًا** بـ`$GUIDE_COLS` وحدَه — لا أيِّ مصفوفةٍ بمفاتيحَ
     عربيّة: فالمصرَّحُ باسمٍ معلومٍ عقدٌ، وما دونه تخمينٌ يفتح بابَ الإيجابِ الكاذب.
   ◆ وهو رافدٌ من جنسِ `F5` حرفًا: تصريحٌ في ملفِّ السطحِ نفسِه لا في مداه. */
function fm_guide_cols($src)
{
    $out = array();
    /* ◆ **والسطحُ قد يخدم هدفَين فيحمل خريطتَين** (§24: `Screens ≠ Placements`)
         — فتُقرأ كلُّ مصفوفةٍ اسمُها يبدأ بـ`$GUIDE_COLS` (‏`$GUIDE_COLS_MOVE`…)،
         **ولا تُقرأ مصفوفةٌ أخرى** مهما كانت مفاتيحُها عربيّة. */
    if (!preg_match_all('~\$GUIDE_COLS[A-Z0-9_]*\s*=\s*array\s*\((.*?)\n\s*\);~s', $src, $m)) { return $out; }
    foreach ($m[1] as $blk) {
        /* والاسمُ «#» يُلتقط بنصِّه: خمسةُ حقولٍ في الورقةِ اسمُها «#» (عمودُ
             التسلسل)، ولا حرفَ عربيًّا فيها — فشرطُ العربيّةِ وحدَه يُسقطها
             فتُقرأ ناقصةً وهي مُعلَنةٌ في الخريطةِ ومُصيَّرةٌ رأسًا. والتوسيعُ
             مقصورٌ على هذا الاسمِ بعينِه لا على كلِّ مفتاحٍ لاتينيّ. */
        /* والمفتاحُ يُقرأ بأيِّ لغةٍ كان: الورقةُ تسمّي حقولًا باللاتينيّةِ
             (`Pricing_Model` · `Record_Basis` · `Source_Row_Ref`)، وشرطُ
             العربيّةِ كان يُسقطها فتُقرأ ناقصةً وهي مُعلَنةٌ في الخريطةِ
             ومُصيَّرةٌ رأسًا — قِيس: عشرةُ حقولٍ في `DEP-02` وحدَها.
           والضبطُ باقٍ باسمِ المصفوفةِ نفسِه: `$GUIDE_COLS` عقدٌ مصرَّحٌ، ولا
             تُقرأ مصفوفةٌ أخرى مهما كانت مفاتيحُها. */
        if (preg_match_all('~[\x27\x22]([^\x27\x22]+)[\x27\x22]\s*=>~u', $blk, $mm)) {
            foreach ($mm[1] as $v) { $v = trim($v); if ($v !== '') { $out[] = $v; } }
        }
    }
    return $out;
}
/* **مسارٌ مُحوِّلٌ لا شاشة** — `route_redirect` يعني أنَّ الأثرَ ليس هنا */
function fm_is_redirector($src)
{
    return (strpos($src, 'route_redirect') !== false && mb_strlen($src) < 4000);
}
function fm_includes($rp, $ROOT, $CHROME)
{
    $out = array();
    $src = (string) @file_get_contents($rp);
    if ($src === '') { return $out; }
    if (preg_match_all('~(?:include|require)(?:_once)?\s*\(?\s*[^;]*?[\x22\x27]([^\x22\x27]+\.php)[\x22\x27]~', $src, $m)) {
        foreach ($m[1] as $inc) {
            if (in_array(basename($inc), $CHROME, true)) { continue; }
            $cand = array(dirname($rp) . '/' . $inc, $ROOT . '/' . ltrim($inc, './'),
                          $ROOT . '/includes/' . basename($inc));
            foreach ($cand as $cp) {
                if (is_file($cp)) { $rc = realpath($cp); if ($rc) { $out[$rc] = 1; } break; }
            }
        }
    }
    return array_keys($out);
}
