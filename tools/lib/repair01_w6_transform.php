/**
 * قراءةُ قاموسِ عرضِ الرموز من السجلِّ — مرتَّبًا بالأطولِ أوّلًا حتى لا
 * يبتلع رمزٌ قصيرٌ جزءًا من أطولَ منه (`fleet.asset` قبل `asset`).
 */
function repair01_w6_dict(mysqli $conn)
{
    static $cache = null;
    if ($cache !== null) { return $cache; }
    $cache = array();
    $r = @$conn->query("SELECT raw_code, display_ar FROM repair01_w6_code_dict WHERE display_ar <> ''");
    while ($r && $x = $r->fetch_row()) { $cache[(string) $x[0]] = (string) $x[1]; }
    uksort($cache, function ($a, $b) { return mb_strlen($b) - mb_strlen($a); });
    return $cache;
}

/**
 * إحلالُ رموزِ القاموسِ في مقطعٍ غيرِ محميّ.
 * ◆ **نمطٌ واحدٌ لا نمطٌ لكلِّ رمز**: القاموسُ يبلغ مئاتِ الرموزِ (‏رموزُ
 *   الأحداثِ تُبذَر من سجلِّ العقود)، والمرورُ عليها رمزًا رمزًا على آلافِ
 *   الصفوفِ ملايينُ الاستدعاءات. والبديلُ تبادلٌ واحدٌ مرتَّبٌ بالأطولِ أوّلًا
 *   حتى لا يبتلع القصيرُ جزءًا من الطويل.
 */
function repair01_w6_dict_apply($text, array $dict)
{
    static $re = null; static $built = null;
    if ($built !== $dict) {
        $built = $dict;
        $alts = array();
        foreach (array_keys($dict) as $code) { $alts[] = preg_quote($code, '/'); }
        $re = $alts ? '/(?<![A-Za-z0-9_.])(' . implode('|', $alts) . ')(?![A-Za-z0-9_.])/u' : null;
    }
    if ($re === null) { return $text; }
    return preg_replace_callback($re, function ($m) use ($dict) {
        return isset($dict[$m[1]]) ? $dict[$m[1]] : $m[0];
    }, $text);
}

/**
 * التحويلُ الكاملُ لصفٍّ واحد: ① آليٌّ ← ② أنماطٌ مُعلَنةٌ ← ③ قاموسٌ ←
 * ④ إعادةُ كتابةٍ صريحة. ويُعاد **الجديدُ وصنفُ العيبِ والقاعدةُ والعذر**.
 *
 * @return array{new:string, kinds:array<string>, rules:array<string>, why:string}
 */
function repair01_w6_transform(mysqli $conn, $sourceKey, $src, $rowKey, $old)
{
    $composite = (int) $src['composite'] === 1;
    $kinds = array(); $rules = array(); $why = '';

    /* الذيلُ المحميُّ يُفصل ويُعاد حرفًا (‏البند ٢٠). */
    $tail = '';
    $head = (string) $old;
    if ($composite) {
        list($h, $t) = UiPurity::splitUserText($head);
        if ($t !== '') { $head = $h; $tail = $t; }
    }

    /* ①-أ **إعادةُ صوغِ الاسمِ المركَّبِ قبل أيِّ نمط** (‏W06 §٤-٤): لو سبقتها
       التنقيةُ الآليّةُ لَنُزعت النقطتانِ بمسافةٍ فضاع المفتاحُ الذي يُصاغ به.
       والمقارنةُ على النصِّ المشذَّبِ لا الخام — فالمسافاتُ الطرفيّةُ ليست اسمًا. */
    $rw = repair01_w6_name_rewrites();
    $probe = trim(preg_replace('/\s+/u', ' ', $head));
    if (isset($rw[$probe])) {
        $head = $rw[$probe];
        $kinds[] = 'NAME_COLON'; $rules[] = 'W6-R-NAME';
        $why = 'اسم مركب كان موصولا بنقطتين — والقاعدة الثالثة تمنعها في اسم عنصر فاعيد صوغه';
    }

    /* ① التنقيةُ الآليّة — تحفظ ما بين «…» بنفسِها. */
    $new = UiPurity::purifyGenerated($head);
    if ($new !== $head) { $kinds[] = 'MECH'; $rules[] = 'W6-R-00'; }

    /* ② الأنماطُ المُعلَنة. */
    foreach (repair01_w6_mech_rules() as $m) {
        $after = preg_replace($m['re'], $m['to'], $new);
        if ($after !== $new) { $kinds[] = $m['kind']; $rules[] = $m['rule']; $why = $m['why']; $new = $after; }
    }

    /* ③ القاموسُ — خارجَ «…» وحدَه. */
    $dict = repair01_w6_dict($conn);
    if ($dict) {
        $segs = preg_split('/(' . trim(UiPurity::RE_QUOTED, '/u') . ')/u', $new, -1,
                            PREG_SPLIT_DELIM_CAPTURE | PREG_SPLIT_NO_EMPTY);
        $out = '';
        foreach ($segs as $seg) {
            if (preg_match(UiPurity::RE_QUOTED, $seg)) { $out .= $seg; continue; }
            $out .= repair01_w6_dict_apply($seg, $dict);
        }
        if ($out !== $new) { $kinds[] = 'RAW_CODE'; $rules[] = 'W6-R-DICT'; $new = $out; }
    }

    /* تنظيفٌ ثانٍ بعد الإحلال — قد يخلّف الإحلالُ مسافتين. */
    $new = trim(preg_replace('/[ \t]+/u', ' ', $new));

    /* ④ إعادةُ الكتابةِ الصريحة — الأخيرةُ فهي الحاكمة، **ونصُّها كاملٌ**:
         يشمل الذيلَ إن كان للصفِّ ذيل، فلا يُضمُّ مرّتين. */
    $ex = repair01_w6_explicit();
    if (isset($ex[$sourceKey][$rowKey])) {
        $e = $ex[$sourceKey][$rowKey];
        return array('new' => $e[0], 'kinds' => array_values(array_unique(array_merge($kinds, array($e[1])))),
                     'rules' => array_values(array_unique(array_merge($rules, array('W6-R-EXPLICIT')))),
                     'why' => $e[2]);
    }

    if ($tail !== '') { $new = $new === '' ? '(' . $tail . ')' : $new . ' (' . $tail . ')'; }

    return array('new' => $new, 'kinds' => array_values(array_unique($kinds)),
                 'rules' => array_values(array_unique($rules)), 'why' => $why);
}
