<?php
/**
 * tools/round_closeout.php — إغلاقُ الجولةِ قبلَ الالتزام: يُشخِّص ويُصلح ويُسمّي الباقي
 * ═══════════════════════════════════════════════════════════════════════════
 * **العطبُ الذي يمنعه**: بوّابةُ ما قبلِ الالتزامِ تُظهر العَرَضَ بعيدًا عن سببِه.
 * تقول «‏`INJ-FRD-REM-01: evidence belt failed`» — والسببُ الحقيقيُّ سكربتُ
 * تراجعٍ لم يُسوَّ، أو تمرينُ تثبيتٍ تقادم لأنَّ الجولةَ أضافت هجرة. فيُعاد
 * اكتشافُ السلسلةِ نفسِها كلَّ جولةٍ من الصفر — وقع ذلك **أربعَ مرّاتٍ متتاليةً**
 * (INJ-INT-01 · EXE-01 · PERM-01 مرّتين).
 *
 * ◆ **والسلسلةُ مُلزِمةُ الترتيب**: التسويةُ ثمَّ `dump-schema` ثمَّ التمرين.
 *   فالتمرينُ يبني قاعدةً بكرًا **من `database/schema/`** ويقارنها بالحيّة،
 *   وتشغيلُه قبلَ التوليدِ يرسُب بـ«حيٌّ غائبٌ عن البكر» — **رسوبٌ بسببٍ غيرِ
 *   سببِه** يُضلِّل ساعةً.
 *
 * ◆ **ويتخطّى ما لا يلزم**: يقيس أوّلًا فلا يُشغّل تمرينًا (٢٠ ثانية) ولا
 *   يُولّد مخطَّطًا (٤ م.ب) إن كان الحالُ سليمًا. فتشغيلُه رخيصٌ دائمًا.
 *
 * ⛔ **وما لا يُصلَح آليًّا يُسمّى ولا يُبتلع**: هجرةٌ بلا `ems_migration_recorded()`
 *   تحتاج تحريرَ ملفٍّ · وشاشةٌ بلا تسجيلٍ تحتاج قرارَ إدارةٍ مالكة · ودَينٌ
 *   بصريٌّ جديدٌ يحتاج علاجًا لا رفعَ خطّ. يطبع لكلٍّ **الأمرَ الذي يعالجه**.
 *
 * التشغيل:
 *   php tools/round_closeout.php            ← يشخِّص ولا يكتب
 *   php tools/round_closeout.php --apply    ← يُنفِّذ ما يُصلَح آليًّا
 * الخروج: 0 الشجرةُ جاهزةٌ للالتزام · 1 بقي ما يحتاجك
 * ═══════════════════════════════════════════════════════════════════════════
 */
if (php_sapi_name() !== 'cli') { exit("CLI فقط\n"); }
error_reporting(E_ALL & ~E_DEPRECATED & ~E_WARNING & ~E_NOTICE);
mb_internal_encoding('UTF-8');
$ROOT  = str_replace(DIRECTORY_SEPARATOR, '/', dirname(__DIR__));
$APPLY = in_array('--apply', $argv, true);
$PHP   = PHP_BINARY;

function sh($cmd) { $o = array(); $rc = 0; @exec($cmd . ' 2>&1', $o, $rc); return array($rc, implode("\n", $o)); }

$todo = array();   /* ما يحتاج المستخدمَ — يُطبع في الخاتمة */
echo "══ إغلاقُ الجولةِ — تشخيصٌ ثمَّ إصلاح ══\n\n";

/* ═══ ① بوّابةُ دفترِ الهجرات ═══════════════════════════════════════════ */
list($rc, $out) = sh("\"{$PHP}\" \"{$ROOT}/tools/repair01_migration_gate.php\"");
if ($rc === 0) { echo "① بوّابةُ الهجرات: ✔ خضراء\n"; }
else {
    echo "① بوّابةُ الهجرات: ✘ راسبة\n";
    /* الهجرةُ التي لا تستدعي الدفترَ تحتاج تحريرَ ملفٍّ — لا تُسوَّى آليًّا */
    if (preg_match_all('~✘ `([^`]+)` — لا تستدعي الدفترَ~u', $out, $m)) {
        foreach (array_unique($m[1]) as $f) {
            if (substr($f, -9) === '_down.php') { continue; }   /* العكسُ يُسوَّى */
            $todo[] = "أضِفْ ذيلَ `ems_migration_recorded()` إلى `database/migrations/{$f}`"
                    . " ثمَّ شغِّلْه وقيِّدْه بـ`migrate.php mark-applied {$f}`";
        }
    }
    if ($APPLY) {
        list($rc2, $o2) = sh("\"{$PHP}\" \"{$ROOT}/tools/repair01_migration_settle.php\" --apply");
        preg_match('~أحكامٌ كُتبت في `gov_migration_settlement`: \*\*(\d+)~u', $o2, $mm);
        echo "   ⇒ سُوِّيت " . ($mm[1] ?? '?') . " حكمًا\n";
        list($rc, $out) = sh("\"{$PHP}\" \"{$ROOT}/tools/repair01_migration_gate.php\"");
        echo "   ⇒ البوّابةُ الآن: " . ($rc === 0 ? '✔ خضراء' : '✘ ما زالت راسبة') . "\n";
        if ($rc !== 0 && preg_match_all('~✘ `([^`]+)` — ~u', $out, $m3)) {
            foreach (array_unique($m3[1]) as $f) { $todo[] = "هجرةٌ لم تُسوَّ آليًّا: `{$f}` — اقرأْ سببَها في مخرَجِ البوّابة"; }
        }
    } else { echo "   ◆ يُصلحها: php tools/repair01_migration_settle.php --apply\n"; }
}

/* ═══ ② المخطَّطُ والتمرين — بالترتيبِ المُلزِم ══════════════════════════ */
list($rcD, $outD) = sh("\"{$PHP}\" \"{$ROOT}/tests/injfrd01_gov014_clean_clone_fingerprint.php\"");
if ($rcD === 0) { echo "② المخطَّطُ والتمرين: ✔ غيرُ متقادم\n"; }
else {
    $stale = (strpos($outD, 'غيرُ متقادم') !== false && strpos($outD, '✘ **والتمرينُ') !== false);
    echo "② المخطَّطُ والتمرين: ✘ " . ($stale ? 'التمرينُ متقادمٌ (الجولةُ أضافت هجرة)' : 'راسب') . "\n";
    if ($APPLY) {
        echo "   ⇒ dump-schema …\n";
        list($r1, $o1) = sh("\"{$PHP}\" \"{$ROOT}/database/migrate.php\" dump-schema");
        if ($r1 !== 0) { $todo[] = 'فشل `migrate.php dump-schema` — اقرأْ مخرَجَه'; }
        else {
            echo "   ⇒ تمرينُ الاستنساخ …\n";
            $note = 'round_closeout — الجولةُ أضافت هجراتٍ فتقادمت بصمةُ المجموعة';
            list($r2, $o2) = sh("\"{$PHP}\" \"{$ROOT}/tools/gov_exec_fresh_install_drill.php\" --note=\"{$note}\"");
            if (preg_match('~(DR-\d{4}-\d+).*?الحكم: \*\*(\w+)~su', $o2, $mm)) {
                echo "   ⇒ {$mm[1]} · {$mm[2]}\n";
            }
            list($rcD, $outD) = sh("\"{$PHP}\" \"{$ROOT}/tests/injfrd01_gov014_clean_clone_fingerprint.php\"");
            echo "   ⇒ GOV-014 الآن: " . ($rcD === 0 ? '✔' : '✘') . "\n";
            if ($rcD !== 0) { $todo[] = 'تمرينُ الاستنساخِ ما زال راسبًا — شغِّلْه يدويًّا واقرأْ سببَه'; }
        }
    } else { echo "   ◆ يُصلحه (بهذا الترتيبِ حصرًا): migrate.php dump-schema ← gov_exec_fresh_install_drill.php\n"; }
}

/* ═══ ③ تسجيلُ الأسطحِ — ثلاثةُ سجلّاتٍ لا واحد ═════════════════════════ */
list($rcU, $outU) = sh("\"{$PHP}\" \"{$ROOT}/tools/uxui_gates.php\" --enforce");
if ($rcU === 0) { echo "③ بواباتُ UXUI: ✔ خضراء\n"; }
else {
    echo "③ بواباتُ UXUI: ✘ راسبة\n";
    if (preg_match('~✗ U1 [^\n]*إنفاذ=(\d+)~u', $outU, $m1) && (int) $m1[1] > 0) {
        preg_match_all('~^      · (\S+\.php)$~um', $outU, $m2);
        $todo[] = "U1 — " . $m1[1] . " مسارًا مُصيَّرًا بلا صفٍّ في المصفوفة"
                . (isset($m2[1]) && $m2[1] ? ': ' . implode(' · ', array_slice($m2[1], 0, 5)) : '')
                . "\n     ⇒ السطحُ يحتاج **ثلاثةَ** سجلّات: `repair01_screen_registry` و`gov_screen_cycle`"
                . " و`docs/uxui_matrix_20260818.csv` — والقيمُ من `nav_workspace_placements` الحاكم";
    }
    if (preg_match('~✗ U9 [^\n]*إنفاذ=(\d+)~u', $outU, $m9) && (int) $m9[1] > 0) {
        $todo[] = "U9 — قسمٌ تجاوز حدَّ التسعة. **والقسمةُ قرارُ مالك**: إمّا قسمةٌ بمعنًى"
                . " وإمّا استثناءٌ مكتوبٌ في ورقةِ الدليل";
    }
}

/* ═══ ④ سقّاطةُ الدَّين — تُسمّي السجلَّ والملفّاتِ ═══════════════════════ */
list($rcR, $outR) = sh("\"{$PHP}\" \"{$ROOT}/tools/u12_debt_ratchet.php\"");
if ($rcR === 0) { echo "④ سقّاطةُ الدَّين: ✔ لا دَينَ زاد\n"; }
else {
    echo "④ سقّاطةُ الدَّين: ✘ دَينٌ زاد\n";
    if (preg_match_all('~✘ (\S+)\s+(.+?)\s+(\d+)\s+(\d+)\s+زادَ (\d+)~u', $outR, $mr, PREG_SET_ORDER)) {
        foreach ($mr as $x) {
            $todo[] = "{$x[1]} زادَ {$x[5]} ({$x[3]} ⇐ {$x[4]}) — {$x[2]}"
                    . "\n     ⇒ عالِجِ الملفَّ لا العدّاد. وإن كان الدَّينُ **ملتزَمًا ومُعلَنًا** فالخطُّ"
                    . " يُرفَع مرّةً بـ`u12_debt_ratchet.php --set` والسابقُ يُحفَظ في `history`";
        }
    }
}

/* ═══ ⑤ حزامُ الشواهد — وهو الذي تقف عنده البوّابةُ فعلًا ═══════════════
   ◆ **وأوّلُ صياغةٍ لهذه الأداةِ أغفلته** ففحصت أربعةً وأعلنت «جاهزة» ثمَّ
     رسَبت البوّابةُ على الخامس. **وأداةُ إغلاقٍ تفحص بعضَ الحواجبِ تُعطي
     خضرةً كاذبةً أسوأَ من لا شيء** — فمَن يثق بها يفاجَأ.
   ◆ **والحزامُ بطيءٌ (~٤ دقائق)** فيُفحَص شاهدُ `GOV-006` وحدَه أوّلًا: هو
     البابُ الذي يتكرّر رسوبُه (فجوةٌ سُكَّت في السردِ ولم تُكتب في الدفتر —
     أربعَ مرّاتٍ حتى الآن). فإن رسَب، سُمِّي سببُه بلا انتظارِ الحزامِ كلِّه. */
list($rcG, $outG) = sh("\"{$PHP}\" \"{$ROOT}/tests/injfrd01_gov006_finding_intake.php\"");
if ($rcG === 0) { echo "⑤ استقبالُ الكشوف (GOV-006): ✔ لا كشفَ يتيم\n"; }
else {
    echo "⑤ استقبالُ الكشوف (GOV-006): ✘ راسب\n";
    if (preg_match('~(\d+) مُهمَل: (.+)$~mu', $outG, $mg)) {
        $todo[] = "GOV-006 — {$mg[1]} كشفًا يتيمًا: {$mg[2]}"
                . "\n     ⇒ **فجوةٌ سُكَّت في جدولِ الفجواتِ ولم تُكتب في الدفترِ الرسميّ**."
                . " اكتبْ لكلِّ رمزٍ مطلبًا في `docs/sources/INJ-FRD-REM-01/workbook.xlsx`"
                . " بمضمونٍ **منقولٍ** من جدولِ الفجواتِ — على غرارِ `tools/bl_j_gap_register.php`."
                . "\n     ⛔ ولا تُعدَّل الكشوفُ لتمرَّ البوّابة: الكشفُ دليلٌ مقيس.";
    } else {
        $todo[] = "GOV-006 راسب — شغِّلْ `php tests/injfrd01_gov006_finding_intake.php` واقرأْ سببَه";
    }
}

/* ═══ ⑥ الحكمُ النهائيُّ — البوّابةُ نفسُها لا قائمةٌ تحاكيها ═══════════════
   ⭐ **وهذا أغلى درسٍ في هذه الأداة**: أوّلُ صياغةٍ فحصت أربعةَ حواجبَ فرسَبت
     البوّابةُ على الخامسِ (الحزام)؛ فأُضيف الخامسُ فرسَبت على السادسِ
     (`NF-24`). **وقائمةٌ منتقاةٌ باليدِ تُخطئ دائمًا** — الحواجبُ تنمو والنسخةُ
     تتقادم. فالحكمُ الأخيرُ **تشغيلُ البوّابةِ نفسِها**، ولا تُعلَن خضرةٌ إلّا
     بمخرَجِها هي. والفحوصُ الخمسةُ أعلاه تبقى **لتسميةِ السبب** — فالبوّابةُ
     تقول «سقط الحزام» ولا تقول لماذا — لا لتحلَّ محلَّها. */
if (!$todo && $APPLY) {
    $hook = $ROOT . '/.git/hooks/pre-commit.ps1';
    if (is_file($hook)) {
        echo "\n⑥ البوّابةُ نفسُها (~4 دقائق) …\n";
        list($rcH, $outH) = sh('powershell.exe -NoProfile -ExecutionPolicy Bypass -File "'
            . str_replace('/', '\\', $hook) . '"');
        if ($rcH === 0) { echo "   ⇒ ✔ خضراء\n"; }
        else {
            $lines = array_values(array_filter(array_map('trim', explode("\n", trim($outH)))));
            $todo[] = "**البوّابةُ راسبةٌ بفحصٍ خارجَ الخمسةِ أعلاه**: " . end($lines)
                    . "\n     ⇒ اقرأْ مخرَجَها كاملًا، **وأضِفْ هذا الفحصَ إلى هذه الأداةِ**"
                    . " كي يُسمّى سببُه مرّةً واحدةً ولا يُكتشَف من جديد.";
        }
    }
}

/* ═══ الخاتمة ═══════════════════════════════════════════════════════════ */
echo "\n" . str_repeat('─', 70) . "\n";
if (!$todo) {
    echo "🟢 الشجرةُ جاهزةٌ.\n";
    echo $APPLY ? "◆ والحكمُ من البوّابةِ نفسِها لا من محاكاةٍ لها.\n"
                : "◆ قياسٌ فقط — والحكمُ القاطعُ بتشغيلِ البوّابةِ في `--apply`.\n";
    exit(0);
}
printf("🔴 بقي %d بندًا يحتاجك:\n\n", count($todo));
foreach ($todo as $i => $t) { printf("  %d. %s\n\n", $i + 1, $t); }
if (!$APPLY) { echo "◆ وأكثرُها يُصلَح آليًّا: أعِد التشغيلَ بـ`--apply`\n"; }
exit(1);
